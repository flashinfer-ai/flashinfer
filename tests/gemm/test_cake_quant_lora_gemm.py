@pytest.mark.parametrize(
    "family,row",
    [(family, row) for family in FAMILIES for row in _rows(family, "zero_adapter")],
    ids=[
        f"{family}-{label}"
        for family in FAMILIES
        for label in _ids(_rows(family, "zero_adapter"))
    ],
)
def test_zero_adapter_fast_path(family, row):
    device = _require(family)
    p = _make_problem(family, row, device)
    base = dict(p, lora_scale=0.0)
    ref = _reference(base)
    weights = (
        p["b"].clone(),
        (p["b_sf"] if family == "nvfp4" else p["b_scale"]).clone(),
    )
    zero_scale = torch.zeros_like(p["lora_scale_t"])
    scale0 = _call(p, lora_scale=zero_scale, out=torch.empty_like(p["out"])).clone()
    none = _call(
        p, d=None, lora_b=None, lora_scale=None, out=torch.empty_like(p["out"])
    ).clone()
    # lora_scale=None disables the adapter even though d / lora_b are passed.
    scale_none = _call(p, lora_scale=None, out=torch.empty_like(p["out"])).clone()
    b_zero = _call(
        p, lora_b=torch.zeros_like(p["lora_b"]), out=torch.empty_like(p["out"])
    ).clone()
    d_zero = _call(
        p, d=torch.zeros_like(p["d"]), out=torch.empty_like(p["out"])
    ).clone()
    # lora_scale = -0.0 is +-0 of the contract: the same fast-path result, bitwise.
    neg_zero = _call(
        p,
        lora_scale=-torch.zeros_like(p["lora_scale_t"]),
        out=torch.empty_like(p["out"]),
    ).clone()
    torch.cuda.synchronize()
    assert torch.equal(scale0, none), (
        f"{row['label']}: lora_scale = 0 and no adapter differ bitwise"
    )
    assert torch.equal(neg_zero, scale0), (
        f"{row['label']}: lora_scale = -0.0 and lora_scale = 0 differ bitwise"
    )
    assert torch.equal(scale_none, none), (
        f"{row['label']}: lora_scale = None with d / lora_b passed is not the fast path"
    )
    for name, out in (
        ("scale0", scale0),
        ("none", none),
        ("b_zero", b_zero),
        ("d_zero", d_zero),
        ("neg_zero", neg_zero),
    ):
        assert name in {"scale0", "none", "b_zero", "d_zero", "neg_zero"}
        _assert_gates(family, row["label"], out, ref)
    assert torch.equal(p["b"], weights[0]) and torch.equal(
        p["b_sf"] if family == "nvfp4" else p["b_scale"], weights[1]
    )


