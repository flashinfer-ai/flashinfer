@pytest.fixture(scope="session")
def nccl_group():
    import torch.distributed as dist

    if "RANK" not in os.environ:
        pytest.skip("multi-GPU TP needs a torchrun launch")
    local_rank = int(os.environ.get("LOCAL_RANK", "0"))
    torch.cuda.set_device(local_rank)
    if not dist.is_initialized():
        dist.init_process_group("nccl")
    yield dist
    dist.barrier()
    dist.destroy_process_group()


@pytest.mark.gpu_2
@pytest.mark.skipif(
    "RANK" not in os.environ, reason="multi-GPU TP needs a torchrun launch"
)
@pytest.mark.parametrize("family", FAMILIES)
@pytest.mark.parametrize("mode", ["column", "row"])
def test_tp_nccl(nccl_group, family, mode):
    """Every rank runs its shard of the host TP contract; the collective result matches the full reference."""
    dist = nccl_group
    device = _require(family)
    world = dist.get_world_size()
    rank = dist.get_rank()
    rows = [
        row
        for row in _rows(family, "tp_sim")
        if int(row["tp"]) == world and row["tp_mode"] == mode
    ]
    if not rows:
        pytest.skip(f"no {mode} TP row for world size {world}")
    row = rows[0]
    # Every rank draws the same full problem (same frozen seed on the same GPU model) and cuts its shard.
    full = _make_problem(family, row, device)
    ref = _reference(full)
    shard = _shards(full, tp=world, mode=mode)[rank]
    out = _call(shard).clone()
    torch.cuda.synchronize()
    _assert_gates(family, row["label"], out, _reference(shard))
    if mode == "column":
        gathered = [torch.empty_like(out) for _ in range(world)]
        dist.all_gather(gathered, out)
        combined = torch.cat(gathered, dim=1)
    else:
        total = out.float()
        dist.all_reduce(total)
        combined = total.to(torch.bfloat16)
    torch.cuda.synchronize()
    _assert_gates(family, row["label"], combined, ref)
