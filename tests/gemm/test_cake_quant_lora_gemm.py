def test_programs_table_is_consistent():
    assert set(PROGRAMS) == {
        "nvfp4_blackwell_pair",
        "nvfp4_blackwell_n256",
        "nvfp4_blackwell_n192",
        "nvfp4_blackwell_n192h",
        "fp8_blackwell_n128",
        "fp8_blackwell_n256",
        "fp8_blackwell_n256_clc_blocked",
        "fp8_blackwell_n256_m256_clc_blocked",
        "fp8_sm90",
        "fp8_sm90_hint",
    }
    root = _get_csrc_dir()
    for name, record in PROGRAMS.items():
        assert (root / record["device"]).is_file(), name
        assert (root / record["binding"]).is_file(), name
        assert set(record["arches"]) <= set(TARGET_ARCH.values()), name
        assert record["pdl"] is True
        assert ["parameter", "rank"] in record["arg_plan"], name
        assert record["ranks"] == list(SUPPORTED_RANKS)
        assert {"m_min", "n_multiple", "k_multiple", "max_mn"} == set(record["rules"])
    assert PROGRAMS["fp8_blackwell_n256"]["tile_n"] == 256
    assert PROGRAMS["fp8_blackwell_n128"]["tile_n"] == 128
    assert PROGRAMS["fp8_blackwell_n256_clc_blocked"]["tile_n"] == 256
    for name in ("fp8_blackwell_n256", "fp8_blackwell_n128"):
        assert (PROGRAMS[name]["sched"], PROGRAMS[name]["raster_mode"]) == (
            "static",
            "grouped",
        ), name
        assert PROGRAMS[name]["arches"] == ["sm_100a", "sm_103a"], name
    gated = PROGRAMS["fp8_blackwell_n256_clc_blocked"]
    assert (gated["sched"], gated["raster_mode"]) == ("clc", "blocked") and gated[
        "arches"
    ] == ["sm_100a", "sm_103a"]
    composition = PROGRAMS["fp8_blackwell_n256_m256_clc_blocked"]
    assert (composition["sched"], composition["raster_mode"]) == (
        "clc",
        "blocked",
    ) and composition["arches"] == ["sm_103a"]
    # the pair-tile height is a record axis: 256 token rows per CTA (a 512-row pair tile) on the composition, 128 elsewhere
    for name in (
        "fp8_blackwell_n256",
        "fp8_blackwell_n128",
        "fp8_blackwell_n256_clc_blocked",
    ):
        assert (PROGRAMS[name]["tile_m"], PROGRAMS[name]["pair_m"]) == (128, 256), name
    assert (composition["tile_m"], composition["pair_m"], composition["tile_n"]) == (
        256,
        512,
        256,
    )
    assert PROGRAMS["fp8_sm90"]["arches"] == ["sm_90a"]
    assert PROGRAMS["fp8_sm90_hint"]["arches"] == ["sm_90a"]
    assert PROGRAMS["nvfp4_blackwell_pair"]["tile_n"] == 128
    assert PROGRAMS["nvfp4_blackwell_n256"]["tile_n"] == 256
    assert (
        PROGRAMS["nvfp4_blackwell_n192"]["tile_n"]
        == PROGRAMS["nvfp4_blackwell_n192h"]["tile_n"]
        == 192
    )
    for name in (
        "nvfp4_blackwell_pair",
        "nvfp4_blackwell_n256",
        "nvfp4_blackwell_n192",
    ):
        assert PROGRAMS[name]["arches"] == ["sm_100a", "sm_103a"], name
    assert PROGRAMS["nvfp4_blackwell_n192h"]["arches"] == ["sm_100a"]
    # The shape rules and the scale-operand form are shared by every program of a family on an architecture
    # (the host checks the rules before the per-problem program choice and builds one scale view form).
    for family in ("nvfp4", "fp8"):
        for target in TARGET_ARCH:
            names = [
                name
                for name, record in PROGRAMS.items()
                if record["family"] == family
                and TARGET_ARCH[target] in record["arches"]
            ]
            assert len({str(PROGRAMS[name]["rules"]) for name in names}) <= 1, (
                family,
                target,
            )
            if family == "nvfp4":
                assert (
                    len(
                        {
                            (PROGRAMS[name]["sf_row_pad"], PROGRAMS[name]["sf_mma_k"])
                            for name in names
                        }
                    )
                    <= 1
                ), target


