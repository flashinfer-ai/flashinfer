def _sqnr_db(expected: torch.Tensor, actual: torch.Tensor) -> float:
    error = expected.float() - actual.float()
    noise = float((error * error).mean())
    if noise == 0.0:
        return math.inf
    return float(10.0 * math.log10(float((expected.float() ** 2).mean()) / noise))


def _floor_db(family: str, label: str) -> float:
    registered = CONTRACT_FLOORS.get(family, {}).get(_isa(), {}).get(label)
    return MIN_SQNR_DB if registered is None else max(float(registered), MIN_SQNR_DB)


def _assert_gates(
    family: str,
    label: str,
    out: torch.Tensor,
    ref: torch.Tensor,
    *,
    isolation: bool = False,
):
    assert out.dtype == torch.bfloat16 and tuple(out.shape) == tuple(ref.shape)
    got = out.float()
    assert torch.isfinite(got).all(), f"{label}: non-finite output"
    sqnr = _sqnr_db(ref, got)
    floor = _floor_db(family, label)
    assert sqnr >= floor, f"{label}: SQNR {sqnr:.2f} dB below the floor {floor:.2f} dB"
    max_ref = float(ref.abs().max())
    if max_ref > 0:
        rel = float((got - ref).abs().max()) / max_ref
        assert rel < MAX_REL_TO_MAX, f"{label}: max|out - ref| / max|ref| = {rel:.4f}"
    ref_bf16 = ref.to(torch.bfloat16).float()
    atol, rtol = OUTER_BOUND[family]
    assert torch.allclose(got, ref_bf16, atol=atol, rtol=rtol), (
        f"{label}: outer bound atol={atol} rtol={rtol}"
    )
    if isolation:
        atol, rtol = ISOLATION_BOUND
        assert torch.allclose(got, ref_bf16, atol=atol, rtol=rtol), (
            f"{label}: LoRA isolation atol=rtol=1e-2"
        )


def _fresh_adapter(
    p: dict[str, Any], *, rank: int, salt: int, seed: int
) -> dict[str, Any]:
    device = p["out"].device
    generator = torch.Generator(device=device).manual_seed(
        seed * 1_000_003 + 17 + 7919 * salt
    )
    scale = float(p["lora_scale"]) * SECOND_ADAPTER_SCALE_FACTOR
    d = (
        torch.randn(
            (p["M"], rank), generator=generator, dtype=torch.float32, device=device
        )
        / rank**0.25
    ).to(torch.bfloat16)
    lora_b = (
        torch.randn(
            (p["N"], rank), generator=generator, dtype=torch.float32, device=device
        )
        / rank**0.25
    ).to(torch.bfloat16)
    second = dict(p)
    second.update(
        rank=rank,
        lora_scale=scale,
        d=d.contiguous(),
        lora_b=lora_b.contiguous(),
        lora_scale_t=torch.tensor([scale], dtype=torch.float32, device=device),
        out=torch.zeros_like(p["out"]),
    )
    return second


def _shards(
    full: dict[str, Any], *, tp: int, mode: str, owner_rank: int = 0
) -> list[dict[str, Any]]:
    """The host TP contract: column shards of W / B / bias with D replicated; row shards of A / W with
    the correction on the owner rank only (the others pass lora_scale = 0 and no bias)."""
    family, n, k = full["family"], full["N"], full["K"]
    shards = []
    for r in range(tp):
        s = dict(full)
        s["is_owner"] = r == owner_rank
        if mode == "column":
            ns = n // tp
            sl = slice(r * ns, (r + 1) * ns)
            s["N"] = ns
            s["b"] = full["b"][sl].contiguous()
            s["lora_b"] = full["lora_b"][sl].contiguous()
            s["bias"] = None if full["bias"] is None else full["bias"][sl].contiguous()
            s["out"] = torch.zeros(
                (full["M"], ns), dtype=torch.bfloat16, device=full["out"].device
            )
            if family == "nvfp4":
                bls = full["b_logical"][sl].contiguous()
                s["b_logical"] = bls
                s["b_sf"] = _swizzle_sf_128x4(bls)
                s["b_deq"] = lambda b=s["b"], sc=bls: _dequantize_nvfp4(b, sc)
            else:
                s["b_deq"] = lambda b=s["b"], sc=full["b_scale"]: b.float() * sc.float()
        elif mode == "row":
            ks = k // tp
            s["K"] = ks
            if family == "nvfp4":
                csl = slice(r * ks // 2, (r + 1) * ks // 2)
                ssl = slice(r * ks // NVFP4_BLOCK, (r + 1) * ks // NVFP4_BLOCK)
                s["a"] = full["a"][:, csl].contiguous()
                s["b"] = full["b"][:, csl].contiguous()
                als = full["a_logical"][:, ssl].contiguous()
                bls = full["b_logical"][:, ssl].contiguous()
                s["a_logical"], s["b_logical"] = als, bls
                s["a_sf"], s["b_sf"] = _swizzle_sf_128x4(als), _swizzle_sf_128x4(bls)
                s["a_deq"] = lambda a=s["a"], sc=als: _dequantize_nvfp4(a, sc)
                s["b_deq"] = lambda b=s["b"], sc=bls: _dequantize_nvfp4(b, sc)
            else:
                sl = slice(r * ks, (r + 1) * ks)
                s["a"] = full["a"][:, sl].contiguous()
                s["b"] = full["b"][:, sl].contiguous()
                s["a_deq"] = lambda a=s["a"], sc=full["a_scale"]: a.float() * sc.float()
                s["b_deq"] = lambda b=s["b"], sc=full["b_scale"]: b.float() * sc.float()
            s["out"] = torch.zeros_like(full["out"])
            if r != owner_rank:
                s["lora_scale"] = 0.0
                s["lora_scale_t"] = torch.zeros_like(full["lora_scale_t"])
                s["bias"] = None
        else:
            raise ValueError(mode)
        shards.append(s)
    return shards


