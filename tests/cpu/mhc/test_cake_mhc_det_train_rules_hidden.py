@pytest.mark.cpu_only
def test_rules_table_at_the_new_hidden_sizes() -> None:
    expected = _rows()
    assert len(expected) == 2 * 28 * len(BOARDS)
    assert tuple(loader.HIDDEN_SIZES) == (4096, *NEW_HIDDEN_SIZES)
    actual = loader.rules_table(hiddens=NEW_HIDDEN_SIZES)
    assert len(actual) == len(expected)
    for want, got in zip(expected, actual, strict=True):
        assert got == want, {
            key: (want[key], got.get(key)) for key in want if want[key] != got.get(key)
        }
    for want in expected:
        assert (
            loader.rules_row(want["T"], want["sm_count"], want["arch"], want["hidden"])
            == want
        )
    # the full table: the H 4096 rows, then each new size's
    full = loader.rules_table()
    assert len(full) == 3 * 28 * len(BOARDS)
    assert full[28 * len(BOARDS) :] == actual
    assert {row["hidden"] for row in full[: 28 * len(BOARDS)]} == {4096}


@pytest.mark.cpu_only
def test_per_size_tables() -> None:
    assert set(loader.H_TABLES) == set(NEW_HIDDEN_SIZES)
    for hidden in NEW_HIDDEN_SIZES:
        assert set(loader.H_TABLES[hidden]) == set(loader.H_TABLE_NAMES), hidden
