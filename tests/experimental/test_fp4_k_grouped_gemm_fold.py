"""CPU checks of the shared kernel bodies of the grouped packed FP4 GEMM programs.

Fourteen of the 21 generated programs compile one of four shared kernel bodies
(the ``MODULES`` records that name another program's kernel source, plus the
body's own program). A body selects a program's text through ``#if`` blocks on
the ``CAKE_KGROUP_<KNOB>`` compile definitions of the program's record (output
mode, store-stage count, tile order) and names the kernel through
``CAKE_PROGRAM_KERNEL``. The sidecar pins, per program, the sha256 of the
kernel source the fold replaced: the program's own exported kernel file.
"""

import hashlib
import json
import re
from pathlib import Path

from flashinfer.experimental.deepgemm_kgroup_gemm import kgroup_gemm as _runtime
from flashinfer.jit import env

_STATEMENT = (
    "// Generated by Cake for FlashInfer: kernel source shared by {members} programs of"
    " deepgemm_kgroup_gemm. The Cake exporter rewrites this file; change its producer"
    " instead."
)
_DIRECTIVE = re.compile(r"\s*#\s*(ifndef|ifdef|if|elif|else|endif|error)\b\s*(.*)")
_FOLD_MACRO = re.compile(r"\bCAKE_(?:KGROUP_[A-Z0-9_]+|PROGRAM_KERNEL)\b")
_KERNEL_RE = re.compile(
    r"csrc/experimental/deepgemm_kgroup_gemm/generated/"
    r"cake_deepgemm_kgroup_gemm_([0-9a-f]{20})_kernel\.cu"
)
_OUT_MODES = {"fp32": 0, "fp32_acc": 1, "bf16": 2}


def _source(rel):
    # As kgroup_gemm.program_spec resolves a record's sources.
    return env.FLASHINFER_CSRC_DIR / rel.removeprefix("csrc/")


def _bodies():
    by_body = {}
    for name, record in _runtime.MODULES.items():
        by_body.setdefault(record["sources"][0], []).append(name)
    return {body: names for body, names in by_body.items() if len(names) > 1}


def _folded():
    return {
        name: _runtime.MODULES[name] for names in _bodies().values() for name in names
    }


def _defines(record):
    defines = {}
    for flag in record["compile_flags"]:
        if flag.startswith("-D"):
            name, _, value = flag[2:].partition("=")
            defines[name] = value
    return defines


def _knob_values(name):
    # The knob values follow from the program's route key "<tier>:<mode>", the
    # same on every architecture that ships the program.
    keys = {
        key
        for arch in _runtime.MODULES[name]["arches"]
        for key, program in _runtime.ROUTES[arch].items()
        if program == name
    }
    assert len(keys) == 1, (name, keys)
    tier, _, mode = keys.pop().partition(":")
    values = {"CAKE_KGROUP_OUT_MODE": _OUT_MODES[mode]}
    if tier.startswith("general_s"):
        values["CAKE_KGROUP_STORE_STAGES"] = int(tier.removeprefix("general_s"))
    if tier in ("swapped", "swapped_lpt"):
        values["CAKE_KGROUP_LPT"] = int(tier == "swapped_lpt")
    return values


def _holds(condition, values):
    # The folds use terms, && within a group and || between groups only. A term
    # is CAKE_KGROUP_X == <int>, CAKE_KGROUP_X (non-zero) or !CAKE_KGROUP_X.
    def term(text):
        text = text.strip()
        if "==" in text:
            name, _, literal = text.partition("==")
            return int(values[name.strip()]) == int(literal)
        return (int(values[text.lstrip("!")]) != 0) != text.startswith("!")

    return any(
        all(term(part) for part in group.strip().strip("()").split("&&"))
        for group in condition.split("||")
    )


def _expand(text, defines):
    """Expand the fold's own #if blocks; keep every other preprocessor line."""
    values = {k: v for k, v in defines.items() if k != "CAKE_PROGRAM_KERNEL"}
    out = []
    stack = []  # [owned by the fold, a branch was taken, this branch is active]
    for line in text.split("\n"):
        active = all(entry[2] for entry in stack)
        match = _DIRECTIVE.match(line)
        keyword, rest = match.groups() if match else (None, None)
        owned = keyword is not None and bool(_FOLD_MACRO.search(rest))
        if keyword in ("if", "ifdef", "ifndef"):
            if not owned:
                stack.append([False, True, True])
            else:
                if keyword == "ifndef":
                    taken = rest.strip() not in defines
                elif keyword == "ifdef":
                    taken = rest.strip() in defines
                else:
                    taken = _holds(rest, values)
                stack.append([True, taken, taken])
                continue
        elif keyword == "elif" and stack[-1][0]:
            entry = stack[-1]
            taken = not entry[1] and _holds(rest, values)
            entry[1], entry[2] = entry[1] or taken, taken
            continue
        elif keyword == "else" and stack[-1][0]:
            entry = stack[-1]
            entry[1], entry[2] = True, not entry[1]
            continue
        elif keyword == "endif":
            if stack.pop()[0]:
                continue
        elif keyword == "error" and active and stack and stack[-1][0]:
            raise AssertionError(f"fold #error reached: {rest}")
        if active:
            out.append(
                line.replace("CAKE_PROGRAM_KERNEL", defines["CAKE_PROGRAM_KERNEL"])
            )
    assert not stack
    return "\n".join(out)


def test_fold_table_routes_fourteen_programs_onto_four_bodies():
    bodies = _bodies()
    assert sorted(len(names) for names in bodies.values()) == [2, 3, 3, 6]
    folded = _folded()
    assert len(folded) == 14
    for body, names in bodies.items():
        assert _source(body).is_file(), body
        digest = _KERNEL_RE.fullmatch(body).group(1)
        # The body is the kernel file of the lexicographically first member.
        assert f"cake_deepgemm_kgroup_gemm_{digest}" in names, body
        assert digest == min(name[-20:] for name in names), body
    for name, record in _runtime.MODULES.items():
        if name in folded:
            continue
        assert record["sources"][0] == (
            f"csrc/experimental/deepgemm_kgroup_gemm/generated/{name}_kernel.cu"
        ), name
        assert not any("CAKE_KGROUP_" in flag for flag in record["compile_flags"])


def test_fold_definitions_match_the_routes_and_the_body_guards():
    for body, names in _bodies().items():
        text = _source(body).read_text(encoding="utf-8")
        guarded = re.findall(r"^#ifndef (CAKE_\w+)$", text, re.MULTILINE)
        assert guarded[0] == "CAKE_PROGRAM_KERNEL", body
        knobs = guarded[1:]
        assert knobs and knobs == sorted(knobs), body
        assert set(_FOLD_MACRO.findall(text)) == set(guarded), body
        assert text.count("CAKE_PROGRAM_KERNEL(") == 1, body
        assert "kernel_cake_deepgemm_kgroup_gemm_" not in text, body
        assert text.count(_STATEMENT.format(members=len(names))) == 1, body
        for name in names:
            record = _runtime.MODULES[name]
            assert _defines(record)["CAKE_PROGRAM_KERNEL"] == f"kernel_{name}", name
            knob_flags = [
                flag for flag in record["compile_flags"] if "CAKE_KGROUP_" in flag
            ]
            values = _knob_values(name)
            assert knob_flags == [f"-D{knob}={values[knob]}" for knob in knobs], name
            assert record["compile_flags"][-len(knobs) :] == knob_flags, name
    # Every program keeps its own kernel symbol (all programs load into one process).
    symbols = {_defines(r)["CAKE_PROGRAM_KERNEL"] for r in _folded().values()}
    assert len(symbols) == 14


def test_folded_bodies_expand_to_the_former_kernel_sources():
    sidecar = Path(__file__).with_name("cake_deepgemm_kgroup_gemm_fold_sha256.json")
    pinned = json.loads(sidecar.read_text(encoding="utf-8"))
    folded = _folded()
    bodies = _bodies()
    assert sorted(pinned) == sorted(folded)
    for name, record in folded.items():
        text = _source(record["sources"][0]).read_text(encoding="utf-8")
        expanded = _expand(text, _defines(record))
        assert _FOLD_MACRO.search(expanded) is None, name
        assert f"kernel_{name}(" in expanded, name
        lines = expanded.split("\n")
        # The generator banner is the one line the former kernel file lacked.
        statement = _STATEMENT.format(members=len(bodies[record["sources"][0]]))
        assert lines.count(statement) == 1, name
        lines.remove(statement)
        digest = hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()
        assert digest == pinned[name]["sha256"], name
