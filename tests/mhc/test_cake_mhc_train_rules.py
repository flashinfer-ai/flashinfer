        assert grid("cake_mhc_train_fwd_coef") == (row["k2_grid"], 1, 1)
        # One trip per CTA (the production forms): two column halves per token for the collapse, four tokens
        # times two halves per CTA for the residual mixing, two tokens per CTA for the backward prepare.
        assert (
            grid("cake_mhc_train_fwd_collapse")
            == (row["k3_grid"], 1, 1)
            == (2 * T, 1, 1)
        )
        assert (
            grid("cake_mhc_train_fwd_finish")
            == (row["k4_grid"], 1, 1)
            == (-(-(2 * T) // 4), 1, 1)
        )
        assert (
            grid("cake_mhc_train_bwd_prepare")
            == (row["k5_grid"], 1, 1)
            == (-(-T // 2), 1, 1)
        )
        assert grid("cake_mhc_train_bwd_token") == (row["G6"], 1, 1)
        assert grid("cake_mhc_train_bwd_slab") == (row["k7_grid"], 1, 1)
        assert grid("cake_mhc_train_bwd_reduce") == (385, 1, 1)
