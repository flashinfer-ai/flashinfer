def test_launch_facts_of_record() -> None:
    """The block and the dynamic shared memory every module launches with: the kernel's shared-memory pool plus the
    1024-byte control prefix (TMA mbarriers, TMEM hold) where the kernel declares one.  The exporter's render is
    the authority (it refuses a record below the kernel's own figure); these are the figures of record."""
    facts = {
        name: (
            record["launch"]["block"],
            record["launch"]["dynamic_smem_bytes"],
            record["launch"]["persistent_ctas_per_sm"],
        )
        for name, record in loader.MODULES.items()
    }
    assert facts == {
        "cake_mhc_train_fn_split": ((256, 1, 1), 0, 1),
        "cake_mhc_train_fn_split__t": ((256, 1, 1), 0, 1),
        "cake_mhc_train_fwd_map": ((192, 1, 1), 115712, 2),  # 4 stages x 28672 + 1024
        "cake_mhc_train_fwd_coef": ((512, 1, 1), 0, 1),
        "cake_mhc_train_fwd_collapse": ((256, 1, 1), 0, 1),
        "cake_mhc_train_fwd_finish": ((256, 1, 1), 0, 1),
        "cake_mhc_train_bwd_prepare": (
            (256, 1, 1),
            1280,
            1,
        ),  # 2 x 8 warps x 20 partials x 4 B
        "cake_mhc_train_bwd_token": (
            (256, 1, 1),
            91136,
            2,
        ),  # 90112 (dpre, fold, sums, 80 KiB row ring) + 1024
        "cake_mhc_train_bwd_slab": (
            (384, 1, 1),
            222208,
            1,
        ),  # 12 warps; 221184 (2 stages + resident fn^T pieces) + 1024
        "cake_mhc_train_bwd_reduce": (
            (256, 1, 1),
            65536,
            1,
        ),  # the parameter CTA's staging tile
    }
    # Two mapping-pass CTAs per SM need 2 x (115712 + 1024 B reserve) = the 228 KiB of an SM100-class SM.
    assert 2 * (115712 + 1024) <= 228 * 1024


