"""Emits the kernel's two key reductions from the engine plan.

``python -m flashinfer.mla.batch_invariant.codegen`` writes ``include/flashinfer/mla/batch_invariant_sparse_plan.inc``:
the row maximum and the row sum of one tile as straight-line C++ produced by running ``canon.init_state`` and
``canon.run`` on the class's plan with a backend whose values are C++ expressions. The kernel includes the file, so
the tree it evaluates is the plan's tree; a device-free test regenerates it and compares bytes.

A thread owns positions ``k = 8 b + 2 c + e`` of two head rows with ``c = lane % 4``; ``x[2 b + e]`` is its value for
``(b, e)`` of one row. An absent position is passed as the combine's identity (``-inf`` / ``+0``).
"""

from __future__ import annotations

from pathlib import Path
from typing import List

from ...batch_invariant import canon
from ...batch_invariant.fp_interface import exact
from . import spec

OUT = (
    Path(__file__).resolve().parents[3]
    / "include"
    / "flashinfer"
    / "mla"
    / "batch_invariant_sparse_plan.inc"
)


class _Emit:
    def __init__(self):
        self.lines: List[str] = []
        self.n = 0

    def _new(self, expr: str) -> str:
        name = f"t{self.n}"
        self.n += 1
        self.lines.append(f"  const float {name} = {expr};")
        return name

    def add(self, a: str, b: str) -> str:
        return self._new(f"__fadd_rn({a}, {b})")

    def fmaxc(self, a: str, b: str) -> str:
        return self._new(f"fmaxf({a}, {b})")


class _Peers(canon.Peers):
    def __init__(self, fp: _Emit):
        self.fp = fp

    def shuffle_xor(self, key, value, mask):
        return self.fp._new(f"__shfl_xor_sync(0xffffffffu, {value}, {mask})")

    def exchange(self, step, state):
        (key,) = state
        return {key: [f"sib[{i}]" for i in range(step.radix)]}


def _function(name: str, red: canon.Reduction, split: int) -> str:
    """``<name>`` for ``split == 1``; ``<name>_part`` (the thread's steps up to the warp exchange) and
    ``<name>_finish`` (the exchange over ``sib[warp]`` and the lane steps) otherwise."""
    p = canon.plan(red, spec.key_placement(split))
    e_i, b_i = p.reg_index("e"), p.reg_index("b")
    n = 2 * spec.B_RADIX // split
    fp = _Emit()
    state, i = canon.init_state(p, fp, lambda key: f"x[{2 * key[b_i] + key[e_i]}]")
    peers = _Peers(fp)
    out = f"// plan: {p.describe()}\n"
    while i < len(p.steps) and p.steps[i].level == "reg":
        state = canon.apply_step(p, p.steps[i], state, peers, fp)
        i += 1
    if split == 1:
        result = canon.run(p, state, i, peers, fp)
        body = "\n".join(fp.lines)
        return out + (
            f"__device__ __forceinline__ float {name}(const float (&x)[{n}]) {{\n"
            f"{body}\n  return {result};\n}}\n"
        )
    (part,) = state.values()
    body = "\n".join(fp.lines)
    out += (
        f"__device__ __forceinline__ float {name}_part(const float (&x)[{n}]) {{\n"
        f"{body}\n  return {part};\n}}\n"
    )
    fp.lines = []
    result = canon.run(p, state, i, peers, fp)
    body = "\n".join(fp.lines)
    return out + (
        f"__device__ __forceinline__ float {name}_finish(const float (&sib)[{split}]) {{\n"
        f"{body}\n  return {result};\n}}\n"
    )


def e4m3_table() -> List[int]:
    """bf16 bits of the value every e4m3 byte denotes (exact); the two NaN encodings map to the canonical NaN. The
    kernel converts with the device's ``cvt`` chain; a device test compares it with this table byte for byte."""
    out = []
    for v in exact.E4M3_VALUES:
        if v != v:
            out.append(exact.CANONICAL_NAN_16)
        else:
            assert exact.to_format(v, exact.BF16) == v
            out.append(exact.bf16_bits(v))
    return out


def render() -> str:
    head = "// Generated by `python -m flashinfer.mla.batch_invariant.codegen` from the engine plan. Do not edit.\n\n"
    parts = []
    for split in spec.KEY_SPLITS:
        suffix = "" if split == 1 else f"_w{split}"
        parts.append(
            _function(
                "sparse_mla_rowmax" + suffix,
                spec.rowmax_reduction(lambda fp, k: k),
                split,
            )
        )
        parts.append(
            _function(
                "sparse_mla_rowsum" + suffix,
                spec.rowsum_reduction(lambda fp, k: k),
                split,
            )
        )
    return head + "\n".join(parts)


def main() -> None:
    OUT.write_text(render())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
