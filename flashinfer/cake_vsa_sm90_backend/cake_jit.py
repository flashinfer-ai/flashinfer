# One verified build: H100 / H200 (``sm_90a``).  The architecture is compiled
# with its exact ``-gencode`` flag (``build.json`` ``arch_flags``); there is no
# family fallback and no other Hopper variant.
ARCHES = ("sm_90a",)
ARCH_BY_CAPABILITY: dict[tuple[int, int], str] = {
    (9, 0): "sm_90a",
}
# The stages in registry order: the four BF16 persistent stages, the fifteen
# shipped BF16 small-selection variants, their nineteen FP8 twins, the two
# quantizers, then the forty-one GQA stages (the same 4 + 15 per data type
# with ``route["gqa"]``, the two round-2 FP8 programs and the round-16
# position-selected FP8 static program ``attention_fp8_gqa_pin``).
# ``PERSISTENT_STAGES`` / ``SMALL_STAGES`` keep naming
# the BF16 MHA stages (the planner's own table); the FP8 attention stages are
# keyed by ``route["dtype"]``, the GQA stages by ``route["gqa"]`` and the
# quantizers by their route kind.
STAGES: tuple[str, ...] = tuple(MODULES)
ATTENTION_KINDS = ("persistent", "small")
QUANTIZE_STAGES = ("quantize_qk_vamax", "quantize_v")


def stage_dtype(name: str) -> str | None:
    """``"bf16"`` / ``"e4m3"`` for an attention stage (the data type of its ``q/k/v``), ``None`` for a quantizer."""

    route = MODULES[name]["route"]
    if route["kind"] not in ATTENTION_KINDS:
        return None
    return route.get("dtype", "bf16")


def stage_gqa(name: str) -> bool:
    """Whether an attention stage serves grouped-query head counts (``route["gqa"]``); ``False`` for the MHA
    stages and the quantizers."""

    return bool(MODULES[name]["route"].get("gqa", False))


def _stages(kind: str, dtype: str, gqa: bool) -> tuple[str, ...]:
    return tuple(
        name
        for name in MODULES
        if MODULES[name]["route"]["kind"] == kind
        and stage_dtype(name) == dtype
        and stage_gqa(name) is gqa
    )


PERSISTENT_STAGES: tuple[str, ...] = _stages("persistent", "bf16", False)
SMALL_STAGES: tuple[str, ...] = _stages("small", "bf16", False)
FP8_PERSISTENT_STAGES: tuple[str, ...] = _stages("persistent", "e4m3", False)
FP8_SMALL_STAGES: tuple[str, ...] = _stages("small", "e4m3", False)
