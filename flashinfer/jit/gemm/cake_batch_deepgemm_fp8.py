# Route table.  The Cake dispatcher's ordered first-match chains for sm_100a
# (148 SMs), sm_103a (152 SMs) and sm_107a (216 SMs) as data: one row per
# route, read top to bottom by ``select``.  A row names the architectures it serves, the literals
# of its predicate (one of the five forms below) and its stages; the launch
# grid and the bound arguments of a stage follow from the stage's kind
# (``_stage_plan``).  Predicates read only ``(B, M, N, K, expected_m)``;
# ``CTA = B * ceil(expected_m / 128)`` is the band coordinate of the masked
# BLOCK_N family.
#
#   point     (B, M, N, K) in points [and expected_m == em] [and expected_m >= em_min]
#   band      (N, K) == nk, (B, M) not in the family's exclusions for the
#             architecture, B <= the family's B bound when it has one, and
#             CTA inside one of the row's inclusive intervals (None = open), and
#             ceil(expected_m / 128) <= the row's M-tile bound when it has one
#   bcta      (N, K) == nk, B and CTA inside the row's inclusive intervals (None = open)
#   nk        (N, K) == nk
#   em_nk     expected_m in em_values and (N, K) in nk_set
#   swap_mix  em_nk, or (B, M, N, K) in the architecture's points
#   cell      (N, K) == nk and the (B, em4) cell of the geometry (``_cell_tag``)
#             names the row's program tag
#
# Rows both architectures share list both in ``arches`` and keep their
# per-architecture intervals / points side by side.  The exported chains also
# carried text no input can select -- a ``NotImplementedError`` stub for
# ``seed_n4096_k7168`` and a ``seed_n7168_k2048`` row behind band families that
# cover every CTA count (the shapes those families exclude are taken by the
# stub's own guards and by the swap-AB rows above), an ``M <= 256`` clause of
# ``seed_large_nk_cta1`` and swap-AB point disjuncts inside complete bands;
# the table omits them.

# The sm_107a rows are the masked BLOCK_N family's bands alone: every (N, K)
# geometry it owns there is covered by its bands at every CTA count.
_BOTH = ("sm_100a", "sm_103a")
_ARCHES = (*_BOTH, "sm_107a")

# (B, M) shapes a band family hands past its bands (to the swap-AB rows), per
# architecture and geometry, and the B bound of the N=128, K=512 family on the
# architectures that route larger B elsewhere.
_BAND_EXCLUDED_BM: dict[tuple[str, tuple[int, int]], tuple[tuple[int, int], ...]] = {
    ("sm_100a", (4096, 7168)): ((1, 8192), (1, 16384), (4, 1024)),
    ("sm_100a", (7168, 2048)): ((1, 16384),),
    ("sm_103a", (4096, 7168)): ((1, 16384),),
    ("sm_103a", (7168, 2048)): ((1, 8192),),
}
_BAND_MAX_B: dict[tuple[str, tuple[int, int]], int] = {
    ("sm_100a", (128, 512)): 8,
    ("sm_103a", (128, 512)): 8,
}

# Stage kinds and their launch shapes (``_stage_plan``):
#   masked_bn  one BLOCK_N GEMM of the masked family; (program, kind, BLOCK_N,
#              K tile of the k_tiles argument[, "grid_m"]): persistent, its grid
#              sized from expected_m, or from M with "grid_m"
#   n128_k512  / n512_k128  the whole-geometry GEMMs of the small shapes; an
#              n512_k128 stage may name its BLOCK_N (default 128) and its M tiles:
#              "grid_m" ceil(M / 128), "grid_max" max(ceil(expected_m / 128) + 1,
#              ceil(M / 128)); either covers every M tile a masked_m <= M reaches
#   cta1       one CTA per 128-row M tile (the expected_m == 24 profile)
#   large_nk   two CTAs per 256-row M tile (the large geometries)
#   pack_m224 + gemm_m224   scale pack into the packed-scale workspace, then
#              the swap-AB GEMM (one CTA per SM)
#   pack_m32 + gemm_m32     the M=32 swap-AB pair (132 CTAs)
_MASKED_TENSORS = ("a", "b", "a_scale_bits", "b_scale_bits", "masked_m", "out")


@dataclass(frozen=True)
class _Route:
    """One table row: the architectures it serves, its predicate literals, stages, workspaces."""

    arches: tuple[str, ...]
    route: str
    parent: str
    form: str
    where: dict[str, Any]
    stages: tuple[tuple[Any, ...], ...]
    workspaces: str | None


def _point(
    arches: str | tuple[str, ...],
    route: str,
    points: tuple[tuple[int, int, int, int], ...],
    expected_m: int | None,
    stages: tuple[tuple[Any, ...], ...],
    *,
    parent: str | None = None,
    workspaces: str | None = None,
    em_min: int | None = None,
) -> _Route:
    """Exact (B, M, N, K) points, optionally pinned to one ``expected_m`` or bounded below by ``em_min``."""
    arches = (arches,) if isinstance(arches, str) else tuple(arches)
    where: dict[str, Any] = {"points": tuple(points), "expected_m": expected_m}
    if em_min is not None:
        where["em_min"] = em_min
    return _Route(
        arches, route, parent or route, "point", where, tuple(stages), workspaces
    )


def _band(
    route: str,
    nk: tuple[int, int],
    stage: tuple[Any, ...],
    ctas: dict[str, tuple[tuple[int | None, int | None], ...]],
    *,
    mt: int | None = None,
) -> _Route:
    """A BLOCK_N band of the masked family; ``ctas`` maps each architecture the row serves to its CTA intervals,
    ``mt`` bounds the M tiles per group (``ceil(expected_m / 128)``) when given."""
    where: dict[str, Any] = {"nk": nk, "ctas": ctas}
    if mt is not None:
        where["mt"] = mt
    return _Route(
        tuple(ctas),
        route,
        "seed_masked_bn",
        "band",
        where,
        (stage,),
        None,
    )


def _bcta(
    route: str,
    nk: tuple[int, int],
    b: tuple[int | None, int | None],
    cta: tuple[int | None, int | None],
    stage: tuple[Any, ...],
    m: tuple[int | None, int | None] = (None, None),
    arches: tuple[str, ...] = _BOTH,
) -> _Route:
    """(N, K) by B, by CTA = B * ceil(expected_m / 128) and by M, on ``arches`` (both by default)."""
    where = {"nk": nk, "b": b, "cta": cta, "m": m}
    return _Route(arches, route, route.split("__")[0], "bcta", where, (stage,), None)


def _nk(route: str, nk: tuple[int, int], stage: tuple[Any, ...]) -> _Route:
    """Every remaining shape of one (N, K) geometry, on both architectures."""
    return _Route(_BOTH, route, route, "nk", {"nk": nk}, (stage,), None)


def _em_nk(
    route: str,
    expected_m: tuple[int, ...],
    nk_set: tuple[tuple[int, int], ...],
    stage: tuple[Any, ...],
) -> _Route:
    """An expected_m profile over a set of geometries, on both architectures."""
    where = {"expected_m": expected_m, "nk_set": nk_set}
    return _Route(_BOTH, route, route, "em_nk", where, (stage,), None)


def _swap_mix(
    route: str,
    expected_m: tuple[int, ...],
    nk_set: tuple[tuple[int, int], ...],
    points: dict[str, tuple[tuple[int, int, int, int], ...]],
    stages: tuple[tuple[Any, ...], ...],
    workspaces: str,
) -> _Route:
    """An expected_m profile over geometries plus per-architecture (B, M, N, K) points."""
    where = {"expected_m": expected_m, "nk_set": nk_set, "points": points}
    return _Route(
        tuple(points), route, route, "swap_mix", where, tuple(stages), workspaces
    )


def _cell(nk: tuple[int, int], tag: str) -> _Route:
    """The SM107a cells of one geometry that name ``tag``'s program (``_SM107A_CELLS``)."""
    return _Route(
        ("sm_107a",),
        f"seed_masked_bn__n{nk[0]}_k{nk[1]}_cell_{tag}",
        "seed_masked_bn",
        "cell",
        {"nk": nk, "tag": tag},
        (_SM107A_CELL_STAGES[tag],),
        None,
    )


def _em4(expected_m: int) -> int:
    """``expected_m``'s quarter-octave bin: ``2 ** (floor(4 log2 expected_m) / 4)``, rounded, at least 1."""
    e = max(int(expected_m), 1)
    return max(1, int(round(2 ** (math.floor(4 * math.log2(e)) / 4))))


@functools.lru_cache(maxsize=4096)
def _cell_tag(N: int, K: int, B: int, expected_m: int) -> Optional[str]:
    """The program tag of the SM107a (B, em4) cell of geometry (N, K) (``None``: no cell).

    A key without a cell takes the nearest cell in (log2 B, log2 em4) on the
    geometries of ``_SM107A_CELL_NEAREST`` (ties: the smaller B * em4, then the
    larger B); elsewhere it has no cell and the bands below take it.
    """
    cells = _SM107A_CELL_INDEX.get((N, K))
    if cells is None or B < 1:
        return None
    key = (B, _em4(expected_m))
    if key in cells or (N, K) not in _SM107A_CELL_NEAREST:
        return cells.get(key)
    lb, le = math.log2(key[0]), math.log2(key[1])
    near = min(
        cells,
        key=lambda c: (
            (math.log2(c[0]) - lb) ** 2 + (math.log2(c[1]) - le) ** 2,
            c[0] * c[1],
            -c[0],
        ),
    )
    return cells[near]


