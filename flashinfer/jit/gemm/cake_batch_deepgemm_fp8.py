def _matches(
    row: _Route, arch: str, B: int, M: int, N: int, K: int, expected_m: int
) -> bool:
    where = row.where
    if row.form == "point":
        return (
            (B, M, N, K) in where["points"]
            and (where["expected_m"] is None or expected_m == where["expected_m"])
            and ("em_min" not in where or expected_m >= where["em_min"])
        )
    if row.form == "band":
        nk = where["nk"]
        if nk != (N, K) or (B, M) in _BAND_EXCLUDED_BM.get((arch, nk), ()):
            return False
        max_b = _BAND_MAX_B.get((arch, nk))
        if max_b is not None and max_b < B:
            return False
        mt = (expected_m + 127) // 128
        if "mt" in where and mt > where["mt"]:
            return False
        cta = B * mt
        return any(
            (lo is None or lo <= cta) and (hi is None or cta <= hi)
            for lo, hi in where["ctas"][arch]
        )
    if row.form == "bcta":
        if where["nk"] != (N, K):
            return False
        cta = B * ((expected_m + 127) // 128)
        return all(
            (lo is None or lo <= value) and (hi is None or value <= hi)
            for value, (lo, hi) in (
                (B, where["b"]),
                (cta, where["cta"]),
                (M, where.get("m", (None, None))),
            )
        )
    if row.form == "nk":
        return where["nk"] == (N, K)
    if row.form == "cell":
        return where["nk"] == (N, K) and _cell_tag(N, K, B, expected_m) == where["tag"]
    hit = expected_m in where["expected_m"] and (N, K) in where["nk_set"]
    if row.form == "swap_mix":
        hit = hit or (B, M, N, K) in where["points"][arch]
    return hit


def _stage_plan(
    stage: tuple[Any, ...],
    sm_count: int,
    B: int,
    M: int,
    N: int,
    K: int,
    expected_m: int,
) -> StagePlan:
    program, kind = stage[0], stage[1]
    grid: tuple[int, int, int]
    args: tuple[Any, ...]
    if kind == "masked_bn":
        block_n, k_tile = stage[2], stage[3]
        n_tiles = (N + block_n - 1) // block_n
        if len(stage) > 4 and stage[4] == "grid_m":
            m_tiles = (M + 127) // 128
        else:
            m_tiles = (expected_m + 127) // 128 + 1
        grid = (min(B * m_tiles * n_tiles, sm_count), 1, 1)
        args = (*_MASKED_TENSORS, B, M, N, n_tiles, K // k_tile, K // 128)
    elif kind == "n128_k512":
        grid = (min(B * ((M + 255) // 256), sm_count // 2) * 2, 1, 1)
        args = ("a", "b", "a_scale", "b_scale", "masked_m", "out", B, M)
    elif kind == "n512_k128":
        block_n = stage[2] if len(stage) > 2 else 128
        m_blocks = (expected_m + 127) // 128 + 1
        if len(stage) > 3 and stage[3] == "grid_m":
            m_blocks = (M + 127) // 128
        elif len(stage) > 3 and stage[3] == "grid_max":
            m_blocks = max(m_blocks, (M + 127) // 128)
        grid = (B * m_blocks * (N // block_n), 1, 1)
        args = ("a", "b", "out", "a_scale", "b_scale", "masked_m", B, M, N // block_n)
    elif kind == "cta1":
        m_tiles = (expected_m + 127) // 128 + 1
        grid = (min(B * m_tiles * (N // 128), sm_count), 1, 1)
        args = (*_MASKED_TENSORS, B, M, N // 128, K // 256, K // 128, m_tiles)
    elif kind == "large_nk":
        m_tiles = (expected_m + 255) // 256 + 1
        grid = (min(B * m_tiles * (N // 128), sm_count // 2) * 2, 1, 1)
        args = (*_MASKED_TENSORS, B, M, N // 128, K // 256, K // 128, m_tiles)
    elif kind == "pack_m224":
        grid = (B * ((M + 47) // 48 + (N // 128 + 47) // 48), 1, 1)
        args = ("a_scale_bits", "b_scale_bits", "sfa_packed", "sfb_packed", B, M, N, K)
    elif kind == "gemm_m224":
        grid = (sm_count, 1, 1)
        args = ("a", "b", "out", "sfa_packed", "sfb_packed", "masked_m", B, M, M, N, K)
    elif kind == "pack_m32":
        grid = (B * ((M + 47) // 48 + (N + 47) // 48), 1, 1)
        args = (
            "a_scale_bits",
            "b_scale_bits",
            "sfa_m32_packed",
            "sfb_m32_packed",
            B,
            M,
            N,
            K,
        )
    elif kind == "gemm_m32":
        grid = (132, 1, 1)
        args = (
            "a",
            "b",
            "out",
            "sfa_m32_packed",
            "sfb_m32_packed",
            "masked_m",
            B,
            M,
            N,
            K,
        )
    else:
        raise ValueError(f"unknown stage kind {kind!r}")
    return StagePlan(program=program, grid=grid, args=args)


def _workspaces(
    kind: str | None, B: int, M: int, N: int, K: int
) -> dict[str, tuple[int, ...]]:
    if kind is None:
        return {}
    cols = K // 512
    if kind == "m224":
        return {"sfa_packed": (B, cols, M), "sfb_packed": (B, cols, N // 128)}
    if kind == "m32":
        return {"sfa_m32_packed": (B * cols, M), "sfb_m32_packed": (B * cols, N)}
    raise ValueError(f"unknown workspace kind {kind!r}")


def select(
    arch: str, sm_count: int, B: int, M: int, N: int, K: int, expected_m: int
) -> Optional[RoutePlan]:
    """The first table row of ``arch`` that matches, as a :class:`RoutePlan`; ``None`` = named gap.

    ``sm_count`` is the SM count the table was exported for (the ``DISPATCH_TABLES``
    key); it only enters the launch grids.  A masked_m setup twin
    (``_MMSETUP_TABLES``) takes its parent's stage on its keys.
    """
    for row in _TABLE[arch]:
        if _matches(row, arch, B, M, N, K, expected_m):
            route, stages = row.route, row.stages
            twin = _mmsetup_twin(arch, B, N, K, stages)
            if twin is not None:
                route, stages = f"{route}_mmsetup", twin
            return RoutePlan(
                route=route,
                parent=row.parent,
                stages=tuple(
                    _stage_plan(s, sm_count, B, M, N, K, expected_m) for s in stages
                ),
                workspaces=_workspaces(row.workspaces, B, M, N, K),
            )
    return None


