def _get_csrc_dir() -> Path:
    installed = jit_env.FLASHINFER_CSRC_DIR / "cake_nvfp4_svdquant_gemm"
    checkout = Path(__file__).resolve().parents[2] / "csrc" / "cake_nvfp4_svdquant_gemm"
    for candidate in (installed, checkout):
        if candidate.is_dir():
            return candidate
    raise FileNotFoundError(
        "Cake NVFP4 SVDQuant sources were not found. Checked:\n"
        f"  - {installed}\n"
        f"  - {checkout}"
    )


def _get_include_dir() -> Path:
    if jit_env.FLASHINFER_INCLUDE_DIR.exists():
        return jit_env.FLASHINFER_INCLUDE_DIR
    checkout = Path(__file__).resolve().parents[2] / "include"
    if checkout.exists():
        return checkout
    raise FileNotFoundError(
        "FlashInfer headers were not found. Checked:\n"
        f"  - {jit_env.FLASHINFER_INCLUDE_DIR}\n"
        f"  - {checkout}"
    )


@functools.cache
def _target_of_device_index(index: int) -> CakeNvfp4SvdquantTarget:
    major, minor = get_compute_capability(torch.device("cuda", index))
    if (major, minor) == (10, 0):
        return "sm100a"
    if (major, minor) == (10, 3):
        return "sm103a"
    raise RuntimeError(
        "the Cake NVFP4 SVDQuant backend requires exact compute capability "
        f"10.0 or 10.3, got {major}.{minor}"
    )


def cake_nvfp4_svdquant_target(device: torch.device) -> CakeNvfp4SvdquantTarget:
    index = device.index if device.index is not None else torch.cuda.current_device()
    return _target_of_device_index(int(index))


@functools.cache
def gen_cake_nvfp4_svdquant_module(
    template: str, target: CakeNvfp4SvdquantTarget
) -> JitSpec:
    record = PROGRAMS[template]
    arch = _TARGET_ARCH[target]
    if arch not in record["arches"]:
        raise RuntimeError(f"generated program {template} does not target {arch}")
    root = _get_csrc_dir()
    spec = gen_jit_spec(
        name=f"{record['module']}_{target}",
        sources=[root / record["device"], root / record["binding"]],
        extra_cuda_cflags=[*_TARGET_FLAGS[target], *record["compile_flags"]],
        extra_include_paths=[root, root.parent, _get_include_dir()],
        needs_device_linking=True,
    )
    logger.info("Generated Cake NVFP4 SVDQuant JIT spec: %s", spec.name)
    return spec


@functools.cache
def load_cake_nvfp4_svdquant_module(template: str, target: CakeNvfp4SvdquantTarget):
    return gen_cake_nvfp4_svdquant_module(template, target).build_and_load()


@functools.cache
def _launcher(template: str, target: CakeNvfp4SvdquantTarget):
    module = load_cake_nvfp4_svdquant_module(template, target)
    return getattr(module, PROGRAMS[template]["ffi_entry"])


def select_cake_nvfp4_svdquant_template(
    *, m: int, n: int, k: int, rank: int, has_bias: bool
) -> str:
    """Return the generated program for a problem, or raise ``ValueError``."""
    key = (m, n, k, rank, has_bias)
    if key == (129, 3072, 3072, 32, False):
        template = "tactic14_m128n64k128_cluster1x2"
    elif key == (129, 3072, 12288, 32, False):
        template = "tactic18_2sm_m256n128k256"
    elif key == (129, 3072, 3072, 96, True):
        template = "tactic25_rank96_persistent"
    elif rank == 96:
        template = "tactic25_rank96_compact_tail"
    elif rank == 64 and has_bias:
        template = "tactic0_rank64_bias_smem"
    elif k == 12288 and rank == 32:
        template = "tactic25_k12288_r32"
    else:
        template = "tactic0_n128_exact_epilogue"
    record = PROGRAMS[template]
    if m < BLOCK_M:
        raise ValueError(
            "Cake NVFP4 SVDQuant requires M >= 128 (every tensor map carries a "
            f"128-row box), got M={m}"
        )
    if n < BLOCK_M or n % BLOCK_M:
        raise ValueError(
            f"Cake NVFP4 SVDQuant requires N to be a positive multiple of {BLOCK_M}, got N={n}"
        )
    block_k = int(record["block_k"])
    if k < block_k or k % block_k:
        raise ValueError(
            f"Cake NVFP4 SVDQuant requires K to be a positive multiple of {block_k} "
            f"for rank={rank}{' with bias' if has_bias else ''}, got K={k}"
        )
    if rank < RANK_GRANULARITY or rank > MAX_RANK or rank % RANK_GRANULARITY:
        raise ValueError(
            "Cake NVFP4 SVDQuant requires a LoRA rank that is a multiple of "
            f"{RANK_GRANULARITY} between {RANK_GRANULARITY} and {MAX_RANK}, got rank={rank}"
        )
    return template


def is_cake_nvfp4_svdquant_problem_supported(
    *,
    m: int,
    n: int,
    k: int,
    rank: int,
    has_bias: bool,
    device: torch.device,
) -> bool:
    try:
        cake_nvfp4_svdquant_target(device)
        select_cake_nvfp4_svdquant_template(m=m, n=n, k=k, rank=rank, has_bias=has_bias)
        return True
    except (RuntimeError, ValueError):
        return False


def run_cake_nvfp4_svdquant(
    *,
    a: torch.Tensor,
    b: torch.Tensor,
    a_sf: torch.Tensor,
    b_sf: torch.Tensor,
    alpha: torch.Tensor,
    d: torch.Tensor,
    l1: torch.Tensor,
    bias: torch.Tensor | None,
    out: torch.Tensor,
    enable_pdl: bool | None = None,
) -> torch.Tensor:
    m, k_packed = (int(value) for value in a.shape)
    n = int(b.shape[0])
    k = k_packed * 2
    rank = int(d.shape[1])
    has_bias = bias is not None
    template = select_cake_nvfp4_svdquant_template(
        m=m, n=n, k=k, rank=rank, has_bias=has_bias
    )
    record = PROGRAMS[template]
    program_pdl = bool(record["pdl"])
    if enable_pdl is not None and enable_pdl is not program_pdl:
        raise ValueError(
            f"the selected Cake program requires enable_pdl={program_pdl}, got {enable_pdl}"
        )
    target = cake_nvfp4_svdquant_target(a.device)

    padded_m = ((m + BLOCK_M - 1) // BLOCK_M) * BLOCK_M
    padded_n = ((n + BLOCK_M - 1) // BLOCK_M) * BLOCK_M
    sf_cols = k // 16
    sf_quads = sf_cols // 4
    # The public API permits larger contiguous backing buffers.
    a_sf = a_sf.reshape(-1)[: padded_m * sf_cols]
    b_sf = b_sf.reshape(-1)[: padded_n * sf_cols]
    if record["scale_elems"] == "uint16":
        a_sf_view = a_sf.view(torch.uint16).view(padded_m // 128, sf_quads, 4, 64)
        b_sf_view = b_sf.view(torch.uint16).view(padded_n // 128, sf_quads, 4, 64)
    else:
        a_sf_view = a_sf.view(padded_m // 128, sf_quads, 4, 8, 16)
        b_sf_view = b_sf.view(padded_n // 128, sf_quads, 4, 8, 16)
    grid_m = padded_m // BLOCK_M
    grid_n = n // int(record["block_n"])
    raster_along_m = grid_n > grid_m
    grid_rule = record["grid"]
    if grid_rule == "linear":
        grid = (grid_m * grid_n, 1, 1)
    elif grid_rule == "cluster_n2":
        grid = (grid_m, grid_n, 1)
    elif grid_rule == "two_cta_m256":
        grid = (2, grid_n, 1)
    elif grid_rule == "persistent_raster":
        grid = (grid_m, grid_n, 1) if raster_along_m else (grid_n, grid_m, 1)
    else:
        raise RuntimeError(f"unsupported generated grid rule {grid_rule!r}")

    tensors = {
        "A": a,
        "B": b,
        "SFA": a_sf_view,
        "SFB": b_sf_view,
        "D": d,
        "L1": l1,
        "D_tail": d,
        "L1_tail": l1,
        "alpha": alpha,
        # The bias parameter needs a valid carrier; has_bias=0 keeps it unread.
        "bias": bias if has_bias else out,
        "out": out,
    }
    params = {
        "M": m,
        "N": n,
        "K_tiles": k // int(record["block_k"]),
        "rank_tiles": rank // RANK_GRANULARITY,
        "rank": rank,
        "rank_chunks": (rank + 63) // 64,
        "grid_n": grid_n,
        "raster_along_m": 1 if raster_along_m else 0,
        "has_bias": 1 if has_bias else 0,
    }
    values = []
    for kind, key in record["arg_plan"]:
        if kind in ("buffer", "tma_buffer"):
            values.append(tensors[key])
        elif kind == "parameter":
            values.append(params[key])
        elif kind == "grid":
            values.append(grid[{"grid_x": 0, "grid_y": 1, "grid_z": 2}[key]])
        else:
            raise RuntimeError(f"unsupported generated argument {kind}:{key}")
    _launcher(template, target)(*values)
    return out


