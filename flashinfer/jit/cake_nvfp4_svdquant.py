"""JIT loader and host launcher for the generated Cake NVFP4 SVDQuant GEMM programs.

Seven generated programs, one kernel source and one host binding each, shared
by SM100 (B200) and SM103 (B300) and compiled once per exact target. The
program is selected by a shape rule over host-known scalars: any ``M``, ``N``
a multiple of 128, ``K`` a multiple of the program's K tile, and a LoRA rank
that is a multiple of 32 up to 128. Every tensor map travels by value in the
kernel parameters, so a call is self-contained and CUDA-graph capturable, and
two layers with different weights never share descriptor storage.
"""

