"""Host bindings of the generated KDA prefill modules, rendered from one template.

Each ``cake_kda_{bf16,tf32}_<digest>`` module pairs an exported kernel body with
a tvm-ffi launcher: argument checks, TMA descriptor encoding into the
caller-owned workspace and the launch of the module's kernel symbol. The
launcher text is a fixed function of the module's argument plan
(``cake_kda_tf32.ARG_PLANS``) and of the per-module facts recorded below, so
``cake_kda_tf32.spec`` renders it into the generated-source directory at
JIT-spec creation instead of reading a checked-in copy. Every module keeps its
own kernel symbol and host-shim namespace, which lets all modules load into one
process.
"""

