def _signature(name):
    spec = _SIGNATURES[name]
    if "like" not in spec:
        return spec
    base = _signature(spec["like"])
    return {
        "plan": base["plan"],
        "tensors": {**base["tensors"], **spec.get("tensors", {})},
        "layouts": {**base["layouts"], **spec.get("layouts", {})},
        "scalars": {**base["scalars"], **spec.get("scalars", {})},
        "current_device_check": spec.get(
            "current_device_check", base["current_device_check"]
        ),
    }


def _flatten(groups):
    bindings = {}
    for (signature, smem_bytes, block, launch), modules in groups.items():
        for module, (encoders, strides) in modules.items():
            if module in bindings:
                raise ValueError(f"duplicate binding row for {module}")
            bindings[module] = (signature, smem_bytes, block, launch, encoders, strides)
    return bindings


BINDINGS = _flatten(_LAUNCH_GROUPS)


def _render(template, **fields):
    return Template(_TEMPLATES[template]).substitute(fields)


def render_kda_prefill_binding(
    module, *, directory, digest, plan, arg_plan, tma_workspace_bytes
):
    """Return the binding translation unit of one module.

    ``arg_plan`` is the module's ``ARG_PLANS`` entry (``(kind, name)`` slots);
    ``tma_workspace_bytes`` is 0 for modules without TMA descriptors, which
    export ``run`` only.
    """
    signature_name, smem_bytes, block, launch, encoders, strides = BINDINGS[module]
    signature = _signature(signature_name)
    if signature["plan"] != plan:
        raise ValueError(
            f"{module}: signature {signature_name} is for plan {signature['plan']}, "
            f"the module uses {plan}"
        )
    tensors = [name for kind, name in arg_plan if kind in ("buffer", "tma_buffer")]
    descriptors = [name for kind, name in arg_plan if kind == "tma_buffer"]
    workspaces = [name for kind, name in arg_plan if kind == "workspace"]
    if len(encoders) != len(descriptors):
        raise ValueError(f"{module}: {len(encoders)} encoders for {descriptors}")
    if workspaces != (["tma_descriptor_workspace"] if descriptors else []):
        raise ValueError(f"{module}: unexpected workspace slots {workspaces}")
    if bool(tma_workspace_bytes) != bool(descriptors):
        raise ValueError(f"{module}: workspace bytes {tma_workspace_bytes}")
    symbol = f"kernel_cake_kda_{directory}_{digest}"
    namespace = f"cake_host_shim_{digest}"
    first = tensors[0]

    kernel_params = []
    entry_params = []
    call_args = []
    checks = []
    conversions = []
    kargs = []
    for kind, name in arg_plan:
        if kind in ("buffer", "tma_buffer"):
            (code, bits, lanes), ctype = _TENSOR_TYPES[signature["tensors"][name]]
            checks.append(
                _render("tensor", name=name, code=code, bits=bits, lanes=lanes)
            )
            layout = signature["layouts"].get(name, "contiguous")
            if layout != "unchecked":
                checks.append(_render(layout, name=name))
            entry_params.append(f"TensorView arg_{name}")
            call_args.append(f"arg_{name}")
            kargs.append(f"&p_{name}")
            if kind == "buffer":
                kernel_params.append(f"{ctype}* __restrict__ {name}")
                conversions.append(_render("pointer", name=name, ctype=ctype))
            else:
                slot = descriptors.index(name)
                kernel_params.append(f"CakeTensorMap const* {name}")
                conversions.append(
                    _render("descriptor", name=name, encoder=encoders[slot], slot=slot)
                )
        elif kind == "parameter":
            ctype, kernel_type, ffi_type, bounds = _SCALAR_TYPES[
                signature["scalars"][name]
            ]
            if bounds is not None:
                label, low, high = bounds
                checks.append(
                    _render("range", name=name, label=label, min=low, max=high)
                )
            kernel_params.append(f"{kernel_type} {name}")
            entry_params.append(f"{ffi_type} arg_{name}")
            call_args.append(f"arg_{name}")
            conversions.append(_render("scalar", name=name, ctype=ctype))
            kargs.append(f"&v_{name}")
        elif kind == "workspace":
            entry_params.append(f"TensorView arg_{name}")
            call_args.append(f"arg_{name}")
        elif kind == "grid":
            entry_params.append(f"int64_t {name}")
        else:
            raise ValueError(f"{module}: unknown argument kind {kind!r}")
    for name in tensors[1:]:
        checks.append(_render("same_device", name=name, first=first))
    if signature["current_device_check"]:
        checks.append(_render("current_device", first=first))
    if descriptors:
        checks.append(_render("workspace", first=first, bytes=tma_workspace_bytes))
    for name in strides:
        kernel_params.append(f"long long {name}_stride_m3")
        conversions.append(_render("stride", name=name))
        kargs.append(f"&v_{name}_stride_m3")

    entry_params = ", ".join(entry_params)
    entry = "RunWithDescriptors" if descriptors else "Run"
    entry_signature = entry_params
    if descriptors:
        entry_signature += ", int descriptor_action"
    parts = [
        _render(
            "preamble",
            symbol=symbol,
            namespace=namespace,
            tensor_map="struct CakeTensorMap;\n" if descriptors else "",
            kernel_params=", ".join(kernel_params),
            entry=entry,
            entry_params=entry_signature,
            first=first,
        ),
        *checks,
        _render("grid"),
        *conversions,
        _render("kargs", kargs=", ".join(kargs)),
    ]
    if smem_bytes > _DEFAULT_SMEM_LIMIT:
        parts.append(_render("shared_memory", symbol=symbol, smem=smem_bytes))
    parts.append(_render("dims", block=block))
    if descriptors:
        parts.append(
            _render("upload", maps=", ".join(f"h_{name}" for name in descriptors))
        )
    parts.append(_render(_LAUNCH_TEMPLATES[launch], symbol=symbol, smem=smem_bytes))
    if descriptors:
        for name, action in _WRAPPERS:
            parts.append(
                _render(
                    "wrapper",
                    name=name,
                    entry_params=entry_params,
                    call_args=", ".join(call_args),
                    descriptor_action=action,
                )
            )
    parts.append(_render("exports", namespace=namespace))
    if descriptors:
        parts.append(_render("prepared_exports", namespace=namespace))
    return "".join(parts)


