"""Generate independently reconstructed Lean pins for NVFP4 MegaMoE."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from ...batch_invariant.fp_interface.term import sexpr
from .lean_cases import LEAN_DIR, _bool, _mask, _string
from .nvfp4_spec import component_terms, f32_bits

CASES_PATH = str(Path(LEAN_DIR) / "BIKernels" / "NVFP4MegaMoECases.lean")
FIELDS = {
    "input_amax": "inputAmax",
    "input_scale": "inputScale",
    "input_encoding_scale": "inputEncodingScale",
    "input_data": "inputData",
    "fc1_gate": "fc1Gate",
    "fc1_up": "fc1Up",
    "activation": "act",
    "handoff_amax": "handoffAmax",
    "handoff_scale": "handoffScale",
    "handoff_encoding_scale": "handoffEncodingScale",
    "handoff_data": "handoffData",
    "fc2": "fc2",
    "finalize": "finalize",
}


@lru_cache(maxsize=1)
def conformance_cases():
    providers = (
        ("sm_100", "legacy"),
        ("sm_103", "legacy"),
        ("sm_100", "standard"),
        ("sm_103", "standard"),
        ("sm_107", "standard"),
        ("sm_100", "genphase"),
        ("sm_103", "genphase"),
        ("sm_107", "genphase"),
    )
    cases = []
    for index, (arch, implementation) in enumerate(providers):
        kwargs = dict(
            hidden=64 if index % 2 else 320,
            intermediate=192 if index % 2 else 256,
            top_k=3,
            num_experts=4,
            arch=arch,
            implementation=implementation,
            apply_routing_weights_before_fc2=bool(index % 2),
            gate_up_clamp=(None, -0.0, -2.0, 2.0)[index % 4],
            input_norm_const=0.5 if index % 2 else 1.25,
            has_fc1_alpha=bool(index & 1),
            has_fc2_alpha=bool(index & 2),
            has_fc1_norm_const=bool(index & 4),
            valid_routes=(True, False, True) if index % 3 == 0 else None,
        )
        flat = component_terms(**kwargs)
        blocked = component_terms(**kwargs, blocked=True)
        assert all(flat[name] is blocked[name] for name in flat)
        cases.append(
            dict(
                name=f"case{index}",
                params=kwargs,
                spec={name: sexpr(t) for name, t in flat.items()},
            )
        )
    return tuple(cases)


def _params(params):
    clamp = params["gate_up_clamp"]
    return (
        f"⟨{params['hidden']}, {params['intermediate']}, {params['top_k']}, "
        f"{params['num_experts']}, .{params['arch'].replace('sm_', 'sm')}, "
        f".{params['implementation']}, {_bool(params['apply_routing_weights_before_fc2'])}, "
        + ("none" if clamp is None else "some " + _string(f32_bits(abs(clamp))))
        + ", "
        + _string(f32_bits(params["input_norm_const"]))
        + ", "
        + ", ".join(
            _bool(params[name])
            for name in ("has_fc1_alpha", "has_fc2_alpha", "has_fc1_norm_const")
        )
        + ", "
        + _mask(params["valid_routes"])
        + "⟩"
    )


def render():
    lines = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by flashinfer.moe_ep.batch_invariant.nvfp4_lean_cases; do not edit.",
        "import BIKernels.NVFP4MegaMoE",
        "namespace BIK.NVFP4MegaMoE",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 4000000",
        "",
    ]
    for case in conformance_cases():
        name = case["name"]
        lines.append(f"def {name} : Params := {_params(case['params'])}")
        for component, field in FIELDS.items():
            lines.append(
                f"def {name}_{component}_py : String := {_string(case['spec'][component])}"
            )
            for blocked, label in ((False, "flat"), (True, "blocked")):
                lines.append(
                    f"theorem {name}_{component}_{label} : "
                    f"BIK.MegaMoE.sexpr (components {name} {_bool(blocked)}).{field} = "
                    f"{name}_{component}_py := by decide +kernel"
                )
        lines.append("")
    lines.append(
        "def conformanceCases : List (String × Params) := ["
        + ", ".join(
            f'("{case["name"]}", {case["name"]})' for case in conformance_cases()
        )
        + "]"
    )
    lines.extend(("", "end BIK.NVFP4MegaMoE", ""))
    return "\n".join(lines)


if __name__ == "__main__":
    Path(CASES_PATH).write_text(render())
