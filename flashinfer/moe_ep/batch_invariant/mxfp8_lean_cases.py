"""Generate independent W8A8 MegaMoE Lean conformance statements."""

from functools import lru_cache
from pathlib import Path

from ...batch_invariant.fp_interface.term import sexpr
from .lean_cases import LEAN_DIR, _bool, _mask, _string, _clamp
from .mxfp4_lean_cases import FIELDS
from .mxfp8_spec import component_terms

CASES_PATH = str(Path(LEAN_DIR) / "BIKernels" / "MXFP8MegaMoECases.lean")


@lru_cache(maxsize=1)
def conformance_cases():
    providers = tuple(
        (arch, provider)
        for arch in ("sm_100", "sm_103", "sm_107")
        for provider in ("legacy", "standard", "genphase")
        if (arch, provider) != ("sm_107", "legacy")
    )
    cases = []
    for index, (arch, provider) in enumerate(providers):
        for kind in ("mxfp8_e4m3", "mxfp8_e5m2"):
            params = dict(
                hidden=128 if index % 2 else 384,
                intermediate=384 if index % 2 else 256,
                top_k=3,
                num_experts=4,
                arch=arch,
                quant_kind=kind,
                implementation=provider,
                apply_routing_weights_before_fc2=provider == "legacy"
                or bool(index % 2),
                gate_up_clamp=(None, -0.0, -2.0, 2.0)[index % 4],
                valid_routes=(True, False, True) if index % 3 == 0 else None,
            )
            terms = component_terms(**params)
            blocked = component_terms(**params, blocked=True)
            assert all(terms[name] is blocked[name] for name in terms)
            cases.append(
                dict(
                    name=f"case{len(cases)}",
                    params=params,
                    spec={name: sexpr(term) for name, term in terms.items()},
                )
            )
    return tuple(cases)


def _params(params):
    return (
        f"⟨{params['hidden']}, {params['intermediate']}, {params['top_k']}, "
        f"{params['num_experts']}, .{params['arch'].replace('sm_', 'sm')}, "
        f".{params['quant_kind'].replace('mxfp8_', '')}, .{params['implementation']}, "
        f"{_bool(params['apply_routing_weights_before_fc2'])}, "
        f"{_clamp(params['gate_up_clamp'])}, {_mask(params['valid_routes'])}⟩"
    )


def render():
    lines = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by flashinfer.moe_ep.batch_invariant.mxfp8_lean_cases; do not edit.",
        "import BIKernels.MXFP8MegaMoE",
        "namespace BIK.MXFP8MegaMoE",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 4000000",
        "",
    ]
    proved = {}
    for case in conformance_cases():
        name = case["name"]
        lines.append(f"def {name} : Params := {_params(case['params'])}")
        for component, field in FIELDS.items():
            expected = case["spec"][component]
            lines.append(f"def {name}_{component}_py : String := {_string(expected)}")
            for blocked, label in ((False, "flat"), (True, "blocked")):
                theorem = f"{name}_{component}_{label}"
                key = (component, expected)
                # A reused theorem still requires Lean to reconstruct this
                # case and check definitional equality. Avoid re-deciding
                # identical long strings for every provider/architecture.
                proof = proved.get(key, "by decide +kernel")
                lines.append(
                    f"theorem {theorem} : BIK.MegaMoE.sexpr "
                    f"(components {name} {_bool(blocked)}).{field} = "
                    f"{name}_{component}_py := {proof}"
                )
                proved[key] = theorem
        lines.append("")
    lines.append(
        "def conformanceCases : List (String × Params) := ["
        + ", ".join(
            f'("{case["name"]}", {case["name"]})' for case in conformance_cases()
        )
        + "]"
    )
    lines.extend(("", "end BIK.MXFP8MegaMoE", ""))
    return "\n".join(lines)


if __name__ == "__main__":
    Path(CASES_PATH).write_text(render())
