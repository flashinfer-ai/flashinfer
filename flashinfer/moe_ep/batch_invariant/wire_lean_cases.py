"""Independent Lean coupling for combine wires and K-stage regrouping."""

from functools import lru_cache
from pathlib import Path
from ...batch_invariant.fp_interface.term import sexpr
from .lean_cases import LEAN_DIR, _bool, _mask, _string
from . import wire_spec, nvfp4_spec, mxfp4_spec, mxfp8_spec

CASES_PATH = str(Path(LEAN_DIR) / "BIKernels" / "CombineWireCases.lean")


@lru_cache(maxsize=1)
def conformance_cases():
    fp = wire_spec.OrderedTermAlgebra()
    cases = []
    for kind, legacy in (("nvfp4", False), ("mxfp8", False), ("mxfp8", True)):
        terms = wire_spec.component_terms(fp, combine_dtype=kind, legacy_mxfp8=legacy)
        cases.append(
            dict(
                name=f"wire{len(cases)}",
                kind=kind,
                legacy=legacy,
                spec={name: sexpr(value) for name, value in terms.items()},
            )
        )
    return tuple(cases)


@lru_cache(maxsize=1)
def partition_cases():
    classes = [
        ("nvfp4", nvfp4_spec, dict(arch=arch, implementation="standard"))
        for arch in ("sm_100", "sm_103", "sm_107")
    ]
    classes += [
        (
            "mxfp4",
            mxfp4_spec,
            dict(arch=arch, quant_kind=kind, implementation="standard"),
        )
        for arch, kind in (
            ("sm_100", "mxfp4_mxfp8"),
            ("sm_103", "mxfp4_mxfp8"),
            ("sm_107", "mxfp4_mxfp8"),
            ("sm_107", "mxfp4"),
        )
    ]
    classes += [
        (
            "mxfp8",
            mxfp8_spec,
            dict(arch=arch, quant_kind=kind, implementation="standard"),
        )
        for arch in ("sm_100", "sm_103", "sm_107")
        for kind in ("mxfp8_e4m3", "mxfp8_e5m2")
    ]
    result = []
    for family, module, kwargs in classes:
        cls = module.numerical_class(**kwargs)
        for k in (512, 384 if cls.stage_k == 256 else 448):
            for operand in ("input_w13.gate", "input_w13.up", "handoff_w2"):
                fp = module.OrderedTermAlgebra()
                canonical = module.mma_fold(fp, k, operand, **kwargs)
                plan = module.mma_fold(
                    fp, k, operand, **kwargs, stage_k=2 * cls.stage_k, blocked=True
                )
                assert canonical is plan
                result.append(
                    dict(
                        name=f"partition{len(result)}",
                        family=family,
                        kwargs=kwargs,
                        k=k,
                        operand=operand,
                        stage=2 * cls.stage_k,
                        spec=sexpr(canonical),
                    )
                )
    return tuple(result)


def render():
    lines = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by wire_lean_cases; do not edit.",
        "import BIKernels.CombineWire",
        "import BIKernels.QuantizedStagePartition",
        "namespace BIK.CombineWire",
        "open BIK.MegaMoE (Expr zero)",
        "set_option maxRecDepth 16384",
        "set_option maxHeartbeats 4000000",
        "",
    ]
    for case in conformance_cases():
        name = case["name"]
        lines.append(
            f"def {name} := componentPairs .{case['kind']} {_bool(case['legacy'])}"
        )
        for index, (component, expression) in enumerate(case["spec"].items()):
            lines.append(
                f'theorem {name}_{component} : BIK.MegaMoE.sexpr (({name}.getD {index} ("", zero)).2) = {_string(expression)} := by decide +kernel'
            )
    for slots in (1, 3, 32):
        for early in (False, True):
            for mask in (None, tuple(i % 2 == 0 for i in range(slots))):
                value = wire_spec.finalizer_term(
                    wire_spec.OrderedTermAlgebra(), slots, 4, early, valid_routes=mask
                )
                name = f"fold{slots}_{early}_{mask is None}"
                lines.append(
                    f"theorem {name} : BIK.MegaMoE.sexpr (finalize {slots} 4 {_bool(early)} ({_mask(mask)})) = {_string(sexpr(value))} := by decide +kernel"
                )
        mask = tuple(i % 2 == 0 for i in range(slots))
        for index, selected in enumerate((None, mask)):
            value = wire_spec.partials_term(
                wire_spec.OrderedTermAlgebra(), slots, 4, valid_routes=selected
            )
            lines.append(
                f"theorem partials{slots}_{index} : BIK.MegaMoE.sexpr (partials {slots} 4 ({_mask(selected)})) = {_string(sexpr(value))} := by decide +kernel"
            )
            for early in (False, True):
                weights = wire_spec.deferred_weights_term(
                    wire_spec.OrderedTermAlgebra(),
                    slots,
                    4,
                    early,
                    valid_routes=selected,
                )
                lines.append(
                    f"theorem deferredWeights{slots}_{index}_{early} : BIK.MegaMoE.sexpr (deferredWeights {slots} 4 {_bool(early)} ({_mask(selected)})) = {_string(sexpr(weights))} := by decide +kernel"
                )
    for case in partition_cases():
        namespace = dict(
            nvfp4="BIK.NVFP4MegaMoE", mxfp4="BIK.MXFP4MegaMoE", mxfp8="BIK.MXFP8MegaMoE"
        )[case["family"]]
        kw = case["kwargs"]
        arch = "." + kw["arch"].replace("sm_", "sm")
        if case["family"] == "nvfp4":
            cls = f"{namespace}.numericalClass {arch} .standard"
        elif case["family"] == "mxfp4":
            cls = f"{namespace}.numericalClass {arch} ." + (
                "pure" if kw["quant_kind"] == "mxfp4" else "mixed"
            )
        else:
            cls = f"{namespace}.numericalClass {arch} .{kw['quant_kind'].removeprefix('mxfp8_')} .standard"
        name = case["name"]
        k = case["k"]
        operand = _string(case["operand"])
        stage = case["stage"]
        if case["family"] == "mxfp8":
            body = f"(BIK.QuantizedStagePartition.blocked ({namespace}.mmaStep ({cls}) {k} {operand}) (({k}+{stage}-1)/{stage}) ({stage}/({cls}).instructionK)).getD zero"
        else:
            body = f"{namespace}.mmaBlocked {{({cls}) with stageK := {stage}}} {k} {operand}"
        lines.append(f"def {name} : Expr := {body}")
        lines.append(
            f"theorem {name}_ordered_atoms : BIK.MegaMoE.sexpr {name} = {_string(case['spec'])} := by decide +kernel"
        )
    lines += ["end BIK.CombineWire", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    Path(CASES_PATH).write_text(render())
