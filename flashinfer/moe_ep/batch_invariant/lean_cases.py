"""Generate Lean conformance cases from the ordered MegaMoE Python spec.

The generated file contains parameters and expected strings. The Lean model
reconstructs the computation independently from those parameters; it never
imports a Python-produced expression tree as its implementation. Run
``python -m flashinfer.moe_ep.batch_invariant.lean_cases`` to regenerate it.
"""

from __future__ import annotations

import functools
import os

from ...batch_invariant.fp_interface.term import sexpr
from .spec import (
    ALLOWED_PLANS,
    ALLOWED_PLAN_CONFIGS,
    OrderedTermAlgebra,
    PlanConfig,
    component_terms,
    f32_bits,
    mma_fold,
    plan_component_terms,
    plan_config_compatible,
)

LEAN_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "batch_invariant",
    "lean",
)
CASES_PATH = os.path.join(LEAN_DIR, "BIKernels", "MegaMoECases.lean")
COMPONENTS = ("fc1_gate", "fc1_up", "activation", "fc2", "finalize")
MMA_KS = (0, 1, 16, 32, 63, 64, 65, 96, 128)


@functools.lru_cache(maxsize=1)
def conformance_cases() -> tuple[dict, ...]:
    """Both placements, clamping, K64 tails and concrete invalid slots."""
    params = (
        (32, 64, 1, True, None, None),
        (64, 128, 2, False, None, None),
        (96, 64, 3, True, 7.0, None),
        (128, 128, 3, False, 7.0, None),
        (32, 64, 2, True, None, (False, True)),
        (96, 128, 3, False, None, (True, False, True)),
        (64, 64, 1, True, float("inf"), None),
        (32, 64, 2, False, None, (False, False)),
        (96, 64, 3, True, -7.0, None),
        (32, 64, 2, False, -0.0, None),
        (224, 256, 3, True, 7.0, None),
        (256, 256, 3, False, None, (True, False, True)),
    )
    out = []
    for index, (hidden, intermediate, slots, early, clamp, mask) in enumerate(params):
        args = (hidden, intermediate, slots, 4, early, clamp)
        terms = component_terms(*args, valid_routes=mask)
        spec = {name: sexpr(value) for name, value in terms.items()}
        plans = {}
        configs = tuple(
            config
            for config in ALLOWED_PLAN_CONFIGS
            if plan_config_compatible(hidden, intermediate, config)
        )
        tiled = {}
        for plan in ALLOWED_PLANS:
            plans[plan] = {
                name: sexpr(value)
                for name, value in plan_component_terms(
                    *args, plan=plan, valid_routes=mask
                ).items()
            }
            for config in configs:
                tiled[(config, plan)] = {
                    name: sexpr(value)
                    for name, value in plan_component_terms(
                        *args, plan=plan, plan_config=config, valid_routes=mask
                    ).items()
                }
        out.append(
            dict(
                name=f"case{index}",
                hidden=hidden,
                intermediate=intermediate,
                slots=slots,
                experts=4,
                early=early,
                clamp=clamp,
                mask=mask,
                spec=spec,
                plans=plans,
                configs=configs,
                tiled=tiled,
            )
        )
    return tuple(out)


def _string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _bool(value: bool) -> str:
    return "true" if value else "false"


def _clamp(value: float | None) -> str:
    if value is None:
        return "none"
    value = abs(value)
    return f"some ({_string(f32_bits(value))}, {_string(f32_bits(-value))})"


def _mask(value: tuple[bool, ...] | None) -> str:
    if value is None:
        return "none"
    return "some [" + ", ".join(_bool(item) for item in value) + "]"


def tile_name(config: PlanConfig) -> str:
    m, n, k = config.mma_tiler_mnk
    return f"m{m}n{n}k{k}c{config.cluster_shape_mnk[0]}"


def _geometry(config: PlanConfig) -> str:
    m, n, k = config.mma_tiler_mnk
    return f"⟨{m}, {n}, {k}, {config.cluster_shape_mnk[0]}, {_bool(config.use_2cta_instrs)}⟩"


def render() -> str:
    lines = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by flashinfer.moe_ep.batch_invariant.lean_cases; do not edit.",
        "import BIKernels.MegaMoE",
        "namespace BIK.MegaMoE",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 2000000",
        "",
        "structure ConformanceCase where",
        "  name : String",
        "  hidden : Nat",
        "  intermediate : Nat",
        "  slots : Nat",
        "  experts : Nat",
        "  early : Bool",
        "  clamp : Option (String × String)",
        "  mask : Option (List Bool)",
        "  configs : List PlanConfig",
        "",
    ]
    for case in conformance_cases():
        name = case["name"]
        params = (
            f"{case['hidden']} {case['intermediate']} {case['slots']} "
            f"{case['experts']} {_bool(case['early'])} ({_clamp(case['clamp'])})"
        )
        lines.append(
            f"def {name} : ConformanceCase := "
            f'⟨"{name}", {case["hidden"]}, {case["intermediate"]}, {case["slots"]}, '
            f"{case['experts']}, {_bool(case['early'])}, {_clamp(case['clamp'])}, "
            f"{_mask(case['mask'])}, ["
            + ", ".join(_geometry(config) for config in case["configs"])
            + "]⟩"
        )
        for config in case["configs"]:
            gname = f"{name}_{tile_name(config)}"
            lines.append(f"def {gname} : PlanConfig := {_geometry(config)}")
            lines.append(
                f"theorem {gname}_compatible : PlanCompatible {gname} "
                f"{case['hidden']} {case['intermediate']} := by decide +kernel"
            )
            lines.append(
                f"theorem {gname}_trace : tiledComponents {gname} {params} "
                f"({_mask(case['mask'])}) = components {params} false ({_mask(case['mask'])}) := "
                f"tile_components_eq_canonical {gname} {params} ({_mask(case['mask'])}) "
                f"{gname}_compatible"
            )
        for component, field in zip(
            COMPONENTS, ("fc1Gate", "fc1Up", "act", "fc2", "finalize"), strict=True
        ):
            expected = case["spec"][component]
            lines.append(f"def {name}_{component}_py : String := {_string(expected)}")
            for blocked, label in ((False, "flat"), (True, "blocked")):
                lines.append(
                    f"theorem {name}_{component}_{label} : "
                    f"sexpr (components {params} {_bool(blocked)} "
                    f"({_mask(case['mask'])})).{field} = {name}_{component}_py := by decide +kernel"
                )
        lines.append("")
    lines.append(
        "def conformanceCases : List ConformanceCase := ["
        + ", ".join(case["name"] for case in conformance_cases())
        + "]"
    )
    lines.append("def mmaCases : List Nat := [" + ", ".join(map(str, MMA_KS)) + "]")
    lines.extend(
        (
            "theorem reject_extra_padding_64_128 : ¬ PaddingCompatible 64 128 := by decide +kernel",
            "theorem reject_extra_padding_160_256 : ¬ PaddingCompatible 160 256 := by decide +kernel",
        )
    )
    lines.extend(("", "end BIK.MegaMoE", ""))
    return "\n".join(lines)


def mma_strings() -> dict[tuple[int, str], str]:
    return {
        (k, "blocked" if blocked else "flat"): sexpr(
            mma_fold(OrderedTermAlgebra(), k, "boundary", blocked=blocked)
        )
        for k in MMA_KS
        for blocked in (False, True)
    }


def main() -> None:
    with open(CASES_PATH, "w") as output:
        output.write(render())
    print(
        f"MegaMoE Lean cases: {len(conformance_cases())} cases × 6 plans × 5 components"
        f"; {sum(len(case['tiled']) for case in conformance_cases())} tiled plans"
    )


if __name__ == "__main__":
    main()
