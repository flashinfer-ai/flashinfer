"""Couple emitted-coefficient activation traces to an independent Lean model."""

from functools import lru_cache
from pathlib import Path
from ...batch_invariant.fp_interface.term import sexpr
from .activation_variants import (
    ActivationVariant,
    FAMILIES,
    activation_accumulator,
    dequant_scale,
)
from .lean_cases import LEAN_DIR, _bool, _string
from .wire_spec import OrderedTermAlgebra

CASES_PATH = str(Path(LEAN_DIR) / "BIKernels" / "NumericalVariantsCases.lean")


def _variant(v):
    coeff = (
        "["
        + ", ".join(f"({_string(k)}, {_string(bits)})" for k, bits in v.coefficients)
        + "]"
    )
    return f"⟨{_string(v.family)}, {_string(v.activation)}, {_bool(v.swiglu_alpha is not None)}, {_bool(v.situ_linear_beta is not None)}, {_bool(v.gate_up_clamp is not None)}, {coeff}⟩"


@lru_cache(maxsize=1)
def conformance_cases():
    fp = OrderedTermAlgebra()
    cases = []
    modes = (
        {},
        dict(swiglu_alpha=1.702, swiglu_beta=0.5),
        dict(activation="situ", situ_beta=0.7),
        dict(activation="situ", situ_beta=0.7, situ_linear_beta=0.3),
    )
    for family in FAMILIES:
        for index, mode in enumerate(modes):
            v = ActivationVariant(
                family, gate_up_clamp=-2.5 if index % 2 else None, **mode
            )
            for present in (False, True):
                alpha = fp.op("input.f32", "alpha") if present else None
                token = fp.op("input.f32", "token") if present else None
                weight = fp.op("input.f32", "weight") if present else None
                norm = fp.op("input.f32", "norm") if present else None
                term = activation_accumulator(
                    fp,
                    fp.op("ref.f32", "gate"),
                    fp.op("ref.f32", "up"),
                    variant=v,
                    alpha=dequant_scale(fp, alpha=alpha, token_scale=token),
                    weight=weight,
                    handoff_norm=norm,
                )
                cases.append(
                    dict(
                        name=f"case{len(cases)}",
                        variant=v,
                        present=present,
                        spec=sexpr(term),
                    )
                )
    return tuple(cases)


def render():
    lines = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by numerical_lean_cases; do not edit.",
        "import BIKernels.NumericalVariants",
        "namespace BIK.NumericalVariants",
        "open BIK.MegaMoE (Expr)",
        "set_option maxRecDepth 8192",
        "",
    ]
    for case in conformance_cases():
        name = case["name"]
        present = case["present"]
        op = lambda label: (
            f'(some (Expr.op "input.f32" [.str "{label}"]))' if present else "none"
        )
        lines.append(f"def {name} : Variant := {_variant(case['variant'])}")
        lines.append(
            f'def {name}_value : Expr := activation {name} (.op "ref.f32" [.str "gate"]) (.op "ref.f32" [.str "up"]) (dequantScale {op("alpha")} {op("token")}) {op("weight")} {op("norm")}'
        )
        lines.append(
            f"theorem {name}_matches_python : BIK.MegaMoE.sexpr {name}_value = {_string(case['spec'])} := by decide +kernel"
        )
    lines += ["end BIK.NumericalVariants", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    Path(CASES_PATH).write_text(render())
