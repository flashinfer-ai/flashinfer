"""Generate independently reconstructed Lean pins for MXFP4 MegaMoE."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from ...batch_invariant.fp_interface.term import sexpr
from .lean_cases import LEAN_DIR, _bool, _mask, _string
from .mxfp4_spec import component_terms, f32_bits

CASES_PATH = str(Path(LEAN_DIR) / "BIKernels" / "MXFP4MegaMoECases.lean")
FIELDS = {
    "input_amax": "inputQ.amax",
    "input_scale_value": "inputQ.scaleValue",
    "input_scale": "inputQ.scale",
    "input_encoding_scale": "inputQ.encoding",
    "input_data": "inputQ.data",
    "fc1_gate": "fc1Gate",
    "fc1_up": "fc1Up",
    "activation": "act",
    "handoff_amax": "handoffQ.amax",
    "handoff_scale_value": "handoffQ.scaleValue",
    "handoff_scale": "handoffQ.scale",
    "handoff_encoding_scale": "handoffQ.encoding",
    "handoff_data": "handoffQ.data",
    "fc2": "fc2",
    "finalize": "finalize",
}


@lru_cache(maxsize=1)
def conformance_cases():
    classes = tuple(
        (arch, kind, provider)
        for arch, kind in (
            ("sm_100", "mxfp4_mxfp8"),
            ("sm_103", "mxfp4_mxfp8"),
            ("sm_107", "mxfp4_mxfp8"),
            ("sm_107", "mxfp4"),
        )
        for provider in ("standard", "genphase")
    )
    cases = []
    for index, (arch, kind, provider) in enumerate(classes):
        kwargs = dict(
            hidden=128 if index % 2 else 384,
            intermediate=384 if index % 2 else 256,
            top_k=3,
            num_experts=4,
            arch=arch,
            quant_kind=kind,
            implementation=provider,
            apply_routing_weights_before_fc2=bool(index % 2),
            gate_up_clamp=(None, -0.0, -2.0, 2.0)[index % 4],
            valid_routes=(True, False, True) if index % 3 == 0 else None,
        )
        terms = component_terms(**kwargs)
        blocked = component_terms(**kwargs, blocked=True)
        assert all(terms[name] is blocked[name] for name in terms)
        cases.append(
            dict(
                name=f"case{index}",
                params=kwargs,
                spec={name: sexpr(term) for name, term in terms.items()},
            )
        )
    return tuple(cases)


def _params(params):
    clamp = params["gate_up_clamp"]
    return (
        f"⟨{params['hidden']}, {params['intermediate']}, {params['top_k']}, "
        f"{params['num_experts']}, .{params['arch'].replace('sm_', 'sm')}, "
        f".{'pure' if params['quant_kind'] == 'mxfp4' else 'mixed'}, "
        f".{params['implementation']}, {_bool(params['apply_routing_weights_before_fc2'])}, "
        + ("none" if clamp is None else "some " + _string(f32_bits(abs(clamp))))
        + ", "
        + _mask(params["valid_routes"])
        + "⟩"
    )


def render():
    lines = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by flashinfer.moe_ep.batch_invariant.mxfp4_lean_cases; do not edit.",
        "import BIKernels.MXFP4MegaMoE",
        "namespace BIK.MXFP4MegaMoE",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 4000000",
        "",
    ]
    for case in conformance_cases():
        name = case["name"]
        lines.append(f"def {name} : Params := {_params(case['params'])}")
        for component, field in FIELDS.items():
            lines.append(
                f"def {name}_{component}_py : String := {_string(case['spec'][component])}"
            )
            for blocked, label in ((False, "flat"), (True, "blocked")):
                lines.append(
                    f"theorem {name}_{component}_{label} : "
                    f"BIK.MegaMoE.sexpr (components {name} {_bool(blocked)}).{field} = "
                    f"{name}_{component}_py := by decide +kernel"
                )
        lines.append("")
    lines.append(
        "def conformanceCases : List (String × Params) := ["
        + ", ".join(
            f'("{case["name"]}", {case["name"]})' for case in conformance_cases()
        )
        + "]"
    )
    lines.extend(("", "end BIK.MXFP4MegaMoE", ""))
    return "\n".join(lines)


if __name__ == "__main__":
    Path(CASES_PATH).write_text(render())
