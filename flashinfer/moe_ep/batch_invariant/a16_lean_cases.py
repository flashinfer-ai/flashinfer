"""Generate pins for independently reconstructed decoded-weight A16 traces."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from ...batch_invariant.fp_interface.term import sexpr
from .a16_spec import KINDS, PLANS, component_terms, plan_component_terms
from .activation_variants import ActivationVariant
from .lean_cases import LEAN_DIR, _bool, _string
from .numerical_lean_cases import _variant

CASES_PATH = str(Path(LEAN_DIR) / "BIKernels" / "A16MegaMoECases.lean")
FIELDS = {
    "weight_decode": "weight",
    "fc1_gate": "fc1Gate",
    "fc1_up": "fc1Up",
    "activation": "act",
    "fc2": "fc2",
    "finalize": "finalize",
    "partials": "partials",
    "deferred_weight": "deferredWeight",
}


@lru_cache(maxsize=1)
def conformance_cases():
    modes = (
        {},
        dict(swiglu_alpha=1.702, swiglu_beta=1.0),
        dict(activation="situ", situ_beta=0.7, situ_linear_beta=1.3),
        dict(activation="situ", situ_beta=0.7),
    )
    cases = []
    for arch_index, arch in enumerate(("sm_100", "sm_103", "sm_107")):
        for kind in KINDS:
            for mode_index, mode in enumerate(modes):
                clamp = (None, -2.5, None, None)[mode_index]
                early = bool(mode_index % 2) if kind == "w4a16" else True
                norm = kind == "w4a16" and bool((arch_index + mode_index) % 2)
                hidden, intermediate = (96, 192) if mode_index % 2 else (320, 384)
                params = dict(
                    hidden=hidden,
                    intermediate=intermediate,
                    top_k=(1, 3, 6, 2)[mode_index],
                    num_experts=8,
                    kind=kind,
                    arch=arch,
                    apply_routing_weights_before_fc2=early,
                    gate_up_clamp=clamp,
                    handoff_norm=norm,
                    output_mode="deferred" if mode_index == 3 else "finalized",
                    **mode,
                )
                flat = component_terms(**params)
                plans = {
                    plan: {
                        name: sexpr(term)
                        for name, term in plan_component_terms(
                            **params, plan=plan
                        ).items()
                    }
                    for plan in PLANS
                }
                expected = {name: sexpr(term) for name, term in flat.items()}
                assert all(value == expected for value in plans.values())
                variant = ActivationVariant(
                    "w4a16" if kind == "w4a16" else "bf16",
                    gate_up_clamp=clamp,
                    **mode,
                )
                cases.append(
                    dict(
                        name=f"case{len(cases)}",
                        params=params,
                        variant=variant,
                        spec=expected,
                        plans=plans,
                    )
                )
    return tuple(cases)


def _params(case):
    p = case["params"]
    kind = {"w4a16": "w4a16", "w8a16_e4m3": "w8a16e4m3", "w8a16_e5m2": "w8a16e5m2"}[
        p["kind"]
    ]
    return (
        f"⟨{p['hidden']}, {p['intermediate']}, {p['top_k']}, {p['num_experts']}, "
        f".{kind}, {_bool(p['apply_routing_weights_before_fc2'])}, "
        f"{_variant(case['variant'])}, {_bool(p['handoff_norm'])}, "
        f"{_bool(p['output_mode'] == 'deferred')}⟩"
    )


def render():
    lines = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by flashinfer.moe_ep.batch_invariant.a16_lean_cases; do not edit.",
        "import BIKernels.A16MegaMoE",
        "namespace BIK.A16MegaMoE",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 4000000",
        "",
    ]
    # Architecture scopes the opaque atoms but does not duplicate their
    # syntax. Reuse kernel-checked component pins when their full ordered
    # strings coincide, rather than re-evaluating the same long MMA fold.
    checked = {}
    for case in conformance_cases():
        name = case["name"]
        lines.append(f"def {name} : Params := {_params(case)}")
        for component, expression in case["spec"].items():
            field = FIELDS[component]
            lines.append(f"def {name}_{component}_py : String := {_string(expression)}")
            theorem = f"{name}_{component}_flat"
            key = component, expression
            proof = (
                "by decide +kernel"
                if key not in checked
                else "by exact " + checked[key]
            )
            lines.append(
                f"theorem {theorem} : "
                f"BIK.MegaMoE.sexpr (components {name} false).{field} = "
                f"{name}_{component}_py := {proof}"
            )
            checked.setdefault(key, theorem)
            lines.extend(
                (
                    f"theorem {name}_{component}_blocked : "
                    f"BIK.MegaMoE.sexpr (components {name} true).{field} = "
                    f"{name}_{component}_py := by",
                    "  rw [components_blocked_eq_flat]",
                    f"  exact {theorem}",
                )
            )
        lines.append("")
    lines.append(
        "def conformanceCases : List (String × Params) := ["
        + ", ".join(
            f'("{case["name"]}", {case["name"]})' for case in conformance_cases()
        )
        + "]"
    )
    lines.extend(("", "end BIK.A16MegaMoE", ""))
    return "\n".join(lines)


if __name__ == "__main__":
    Path(CASES_PATH).write_text(render())
