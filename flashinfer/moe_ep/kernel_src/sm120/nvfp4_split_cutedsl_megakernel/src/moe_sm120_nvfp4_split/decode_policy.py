def _config_key(config):
    values = asdict(config)
    values.pop('expected_rows_per_expert')
    values['k1_tile'] = tuple(values['k1_tile'])
    values['k2_tile'] = tuple(values['k2_tile'])
    return values


def _model(shape, contract, counts, eligible, clamp, tuning):
    if (not eligible or clamp != 10.0 or tuning is not None or counts is not None
            or contract != 'owner_bf16'
            or (shape.hidden, shape.intermediate) != (4096, 4096)
            or (shape.data_parallel_size, shape.tensor_parallel_size) != (1, 1)
            or (shape.num_sms, shape.sm_min_partition, shape.sm_partition_alignment) != (110, 8, 8)
            or shape.tokens_per_rank < 1):
        return None
    ep = shape.expert_parallel_size
    if ep not in (4, 8) or (shape.ep_same_numa_peer_count, shape.ep_cross_numa_peer_count) != (3, ep - 4):
        return None
    return {(6, 256): 'dsv', (8, 288): 'glm'}.get((shape.num_topk, shape.num_total_experts))


def _matches(rule, model, shape, config):
    return (rule['model'] == model and rule['ep'] == shape.expert_parallel_size
            and rule['lo'] <= shape.tokens_per_rank <= rule['hi']
            and _config_key(config) in rule['anchors'])


def select_decode_defaults(shape, config, overrides, jit, contract, counts=None,
                           *, eligible, clamp, tuning=None):
    """Shared API/native entry. Explicit kernel and JIT overrides take precedence."""
    model = _model(shape, contract, counts, eligible, clamp, tuning)
    if model is None:
        return config, jit
    expected_rows = shape.tokens_per_rank * shape.expert_parallel_size * shape.num_topk / shape.num_total_experts
    if abs(config.expected_rows_per_expert - expected_rows) > 1e-9:
        return config, jit
    from .tuning_config import overrides_match
    from .heuristic import legality_errors, semantic_errors, correctness_qualification_errors
    from .utility_policy import select_utility
    for rule in GEOMETRY_RULES:
        if not _matches(rule, model, shape, config):
            continue
        if jit.fc1_utility_postprocess not in (None, rule['utility']):
            continue
        candidate = replace(config, **rule['changes'])
        if not overrides_match(candidate, overrides):
            continue
        errors = (legality_errors(shape, candidate) + semantic_errors(candidate, contract)
                  + correctness_qualification_errors(shape, candidate))
        if errors:
            raise ValueError('; '.join(errors))
        config = candidate
        if jit.fc1_utility_postprocess is None:
            jit = replace(jit, fc1_utility_postprocess=rule['utility'])
        break
    # Cache qualification includes the final full geometry and utility mode.
    utility = jit.fc1_utility_postprocess
    if utility is None:
        utility = select_utility(shape, config, contract, eligible=True)
    for rule in CACHE_RULES:
        if _matches(rule, model, shape, config) and utility == rule['utility']:
            changes = {}
            if jit.weight_eviction_policy is None:
                changes['weight_eviction_policy'] = rule['weight']
            if jit.activation_eviction_policy is None:
                changes['activation_eviction_policy'] = rule['activation']
            jit = replace(jit, **changes)
            break
    return config, jit
