def _module(digest: str, row: dict[str, Any]) -> dict[str, Any]:
    """The ``MODULES`` record of program ``digest`` from its ``_PROGRAMS`` row.

    A row carries only what differs from the family default: the digests of the
    kernel / launcher translation units it builds (``kernel`` / ``binding``), its
    lever defines (``compile_flags``), ``fast_math`` False where the exporter
    compiled without ``--use_fast_math`` and, when it builds another record's
    launcher, the 16-hex id of its own host-shim namespace (``shim``).  The nvcc
    line is ``--use_fast_math``, the lever defines, then ``-DCAKE_PROGRAM_KERNEL``
    whenever a shared translation unit is built and ``-DCAKE_PROGRAM_SHIM`` for a
    shared launcher."""
    kernel = row.get("kernel", digest)
    binding = row.get("binding", digest)
    flags = [
        *(_FAST_MATH if row.get("fast_math", True) else ()),
        *row.get("compile_flags", ()),
    ]
    if kernel != digest or binding != digest:
        flags.append(
            f"-DCAKE_PROGRAM_KERNEL=kernel_cake_kimi_k3_fp8_projection_{digest}"
        )
    if binding != digest:
        flags.append(f"-DCAKE_PROGRAM_SHIM=cake_host_shim_{row['shim']}")
    return {
        "sources": [
            f"{_SOURCE_PREFIX}{kernel}_kernel.cu",
            f"{_SOURCE_PREFIX}{binding}_binding.cu",
        ],
        "arches": list(row["arches"]),
        "compile_flags": flags,
        "arg_plan": row["arg_plan"],
        "closure_sha256": row["closure_sha256"],
    }


