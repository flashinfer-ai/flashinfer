void Launch(TensorView receipt, int64_t stream_handle, int64_t slot_0, TensorView t_0, int64_t slot_1, TensorView t_1, int64_t slot_2, TensorView t_2, int64_t slot_3, TensorView t_3) {
  LaunchReceipt* header = ReceiptHeader(receipt);
  TVM_FFI_CHECK(header->chain.magic == kReceiptMagic && header->chain.slot_count == 20u, ValueError)
      << "launch receipt was not planned by this launcher";
  DLDevice dev = DLDevice{kDLCUDA, header->chain.device_id};
  tvm::ffi::CUDADeviceGuard device_guard(dev.device_id);
  {
    // Bind the primary context for the tensor-map encoders once per thread and device.
    static thread_local int encoder_context_device = -1;
    if (encoder_context_device != dev.device_id) {
      TVM_FFI_CHECK_CUDA_ERROR(cudaSetDevice(dev.device_id));
      encoder_context_device = dev.device_id;
    }
  }
  unsigned char* base = static_cast<unsigned char*>(receipt.data_ptr());
  void* kargs[20];
  ReceiptKargs(header, base, kargs);
  RebindReceiptSlot(kargs, slot_0, t_0);
  RebindReceiptSlot(kargs, slot_1, t_1);
  RebindReceiptSlot(kargs, slot_2, t_2);
  RebindReceiptSlot(kargs, slot_3, t_3);
  cudaStream_t stream = stream_handle != 0 ? reinterpret_cast<cudaStream_t>(static_cast<uintptr_t>(stream_handle))
                                           : (cudaStream_t)TVMFFIEnvGetStream(dev.device_type, dev.device_id);
  IssueReceipt(header, kargs, stream);
}

// The chain prefix of a receipt planned by any receipt-enabled launcher of this generator revision.
inline const ReceiptChainPrefix* ChainPrefix(const TensorView& receipt, int64_t* bytes) {
  TVM_FFI_CHECK(receipt.device().device_type == kDLCPU, ValueError) << "launch receipt must be a host tensor";
  check_dtype(receipt, DLDataType{kDLUInt, 8, 1}, "receipt");
  check_contiguous(receipt, "receipt");
  TVM_FFI_CHECK((size_t)receipt.numel() >= sizeof(ReceiptChainPrefix), ValueError)
      << "launch receipt needs at least " << sizeof(ReceiptChainPrefix) << " bytes, got " << receipt.numel();
  const ReceiptChainPrefix* prefix = static_cast<const ReceiptChainPrefix*>(receipt.data_ptr());
  TVM_FFI_CHECK(prefix->chain_abi == kReceiptChainAbi && prefix->chain_rebind != 0 && prefix->chain_launch != 0,
                ValueError)
      << "launch receipt was not planned by a launcher of this export";
  *bytes = receipt.numel();
  return prefix;
}

// Packed chain entry: (stream_handle, t_0, t_1, receipt_0, slots_0[, receipt_1, slots_1, ...]) replays one to
// kReceiptChainMaxStages receipts in order through their planning launchers' callees.  ``slots`` packs up to four
// 16-bit lanes; a lane is 0 (unused) or 1 + (FFI position << 1 | call-tensor index).  Every receipt is validated
// and required to share the device before anything is issued; the device context is bound and the stream resolved
// once (``0`` selects the FFI environment stream).  A callee's non-zero status is returned unchanged with the error
// it set.
int Chain(const tvm::ffi::AnyView* args, int32_t num_args) {
  TVM_FFI_SAFE_CALL_BEGIN();
  TVM_FFI_CHECK(num_args >= 5 && (num_args - 3) % 2 == 0 && num_args <= 3 + 2 * kReceiptChainMaxStages, TypeError)
      << "receipt chain expects (stream, tensor, tensor, receipt, slots[, receipt, slots]...) with 1 to "
      << kReceiptChainMaxStages << " stages, got " << num_args << " arguments";
  const int32_t num_stages = (num_args - 3) / 2;
  const int64_t stream_handle = args[0].cast<int64_t>();
  TensorView tensors[2] = {args[1].cast<TensorView>(), args[2].cast<TensorView>()};
  struct Stage {
    void* receipt;
    int64_t bytes;
    const ReceiptChainPrefix* prefix;
    int64_t slots;
  };
  Stage stages[kReceiptChainMaxStages];
  for (int32_t s = 0; s < num_stages; ++s) {
    TensorView receipt = args[3 + 2 * s].cast<TensorView>();
    int64_t bytes = 0;
    const ReceiptChainPrefix* prefix = ChainPrefix(receipt, &bytes);
    stages[s] = Stage{receipt.data_ptr(), bytes, prefix, args[4 + 2 * s].cast<int64_t>()};
    TVM_FFI_CHECK(prefix->device_id == stages[0].prefix->device_id, ValueError)
        << "receipt " << s << " was planned on device " << prefix->device_id << " but the chain runs on device "
        << stages[0].prefix->device_id;
  }
  DLDevice dev = DLDevice{kDLCUDA, stages[0].prefix->device_id};
  tvm::ffi::CUDADeviceGuard device_guard(dev.device_id);
  {
    // Bind the primary context for the tensor-map encoders once per thread and device.
    static thread_local int encoder_context_device = -1;
    if (encoder_context_device != dev.device_id) {
      TVM_FFI_CHECK_CUDA_ERROR(cudaSetDevice(dev.device_id));
      encoder_context_device = dev.device_id;
    }
  }
  cudaStream_t stream = stream_handle != 0 ? reinterpret_cast<cudaStream_t>(static_cast<uintptr_t>(stream_handle))
                                           : (cudaStream_t)TVMFFIEnvGetStream(dev.device_type, dev.device_id);
  for (int32_t s = 0; s < num_stages; ++s) {
    const Stage& stage = stages[s];
    ReceiptRebindFn rebind = reinterpret_cast<ReceiptRebindFn>(static_cast<uintptr_t>(stage.prefix->chain_rebind));
    ReceiptLaunchFn issue = reinterpret_cast<ReceiptLaunchFn>(static_cast<uintptr_t>(stage.prefix->chain_launch));
    for (int lane = 0; lane < 4; ++lane) {
      const int64_t code = (stage.slots >> (16 * lane)) & 0xffff;
      if (code == 0) continue;
      int status = rebind(stage.receipt, stage.bytes, (code - 1) >> 1, &tensors[(code - 1) & 1]);
      if (status != 0) return status;
    }
    int status = issue(stage.receipt, stage.bytes, stream);
    if (status != 0) return status;
  }
  TVM_FFI_SAFE_CALL_END();
}

