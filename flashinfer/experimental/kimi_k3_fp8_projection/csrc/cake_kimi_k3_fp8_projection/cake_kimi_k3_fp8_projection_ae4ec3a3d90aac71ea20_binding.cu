// A receipt handed over by address (the chain callees): size, magic and slot count of this launcher.
inline LaunchReceipt* OwnReceipt(void* receipt, int64_t bytes) {
  TVM_FFI_CHECK(bytes >= (int64_t)kReceiptStorageOffset, ValueError)
      << "launch receipt needs at least " << kReceiptStorageOffset << " bytes, got " << bytes;
  LaunchReceipt* header = static_cast<LaunchReceipt*>(receipt);
  TVM_FFI_CHECK(header->chain.magic == kReceiptMagic && header->chain.slot_count == 20u, ValueError)
      << "launch receipt was not planned by this launcher";
  return header;
}

// Chain callees (addresses stored in the prefix by Plan): one slot re-bind, one launch; the status of their
// safe-call frame is returned to the chain entry, which bound the device and resolved the stream.
int ChainRebind(void* receipt, int64_t bytes, int64_t slot, const TensorView* tensor) {
  TVM_FFI_SAFE_CALL_BEGIN();
  LaunchReceipt* header = OwnReceipt(receipt, bytes);
  void* kargs[20];
  ReceiptKargs(header, static_cast<unsigned char*>(receipt), kargs);
  RebindReceiptSlot(kargs, slot, *tensor);
  TVM_FFI_SAFE_CALL_END();
}

int ChainLaunch(void* receipt, int64_t bytes, void* stream) {
  TVM_FFI_SAFE_CALL_BEGIN();
  LaunchReceipt* header = OwnReceipt(receipt, bytes);
  void* kargs[20];
  ReceiptKargs(header, static_cast<unsigned char*>(receipt), kargs);
  IssueReceipt(header, kargs, static_cast<cudaStream_t>(stream));
  TVM_FFI_SAFE_CALL_END();
}

