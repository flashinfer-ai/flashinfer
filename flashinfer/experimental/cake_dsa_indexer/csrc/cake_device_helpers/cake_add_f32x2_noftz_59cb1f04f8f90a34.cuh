// Device helper of the Cake compiler's helper library, content-addressed (the first 16 hex digits of the
// sha256 of its definition) and shared by every generated kernel family that includes it; carried here by
// hand pending exporter support.  Not standalone: a family's device preamble includes it after its typedefs
// and the helpers it calls.
#pragma once

__device__ __forceinline__ float2 add_f32x2_noftz(float2 a, float2 b) {
    float2 r;
    asm("add.rn.f32x2 %0, %1, %2;"
        : "=l"(*(unsigned long long*)&r)
        : "l"(*(unsigned long long*)&a), "l"(*(unsigned long long*)&b));
    return r;
}
