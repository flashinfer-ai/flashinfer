def _unit(digest: str) -> dict[str, Any]:
    """The ``unit`` block of program ``digest`` from its rows (keys sorted, as exported)."""
    stage, _plan, dtypes, tma, _block, _cluster, _smem = _PROGRAMS[digest]
    unit: dict[str, Any] = {
        "arg_dtypes": dict(_ARG_DTYPES[dtypes]),
        "stage": stage,
        "tma_ranks": dict(_TMA_RANKS[tma]),
        **_STAGE_CONSTANTS[stage],
    }
    if stage == "routing":
        (routing_input, logits_dtype), row = _ROUTING_ROWS[digest]
        kind, variant, low, high = row
        grid, grid_rule, per_thread, cooperative = _ROUTING_KINDS[kind]
        pre, leads = _ROUTING_PRE.get(digest), _ROUTING_LEADS.get(digest)
        unit.update(
            cooperative=cooperative,
            grid=list(grid),
            grid_rule=grid_rule,
            input=routing_input,
            kind=kind,
            leads=None if leads is None else _PREFIX + leads,
            logits_dtype=logits_dtype,
            max_expanded_per_thread=per_thread,
            max_tokens=high,
            min_tokens=low,
            pre=None if pre is None else _PREFIX + pre,
            unit_key=[stage, variant],
            variant=variant,
        )
    elif stage == "fc1":
        family, tile_n, block_k = _FC1[digest]
        unit.update(_gemm_fields(stage, family, tile_n, block_k))
    elif stage == "fc2":
        family, tile_n, block_k, sf_layout_a = _FC2[digest]
        unit.update(_gemm_fields(stage, family, tile_n, block_k))
        unit["sf_layout_a"] = sf_layout_a
    elif stage == "requant":
        variant, sf_layout = _REQUANT[digest]
        unit.update(sf_layout=sf_layout, unit_key=[stage, variant], variant=variant)
    else:
        variant, kernel_variant, expert_weights_dtype, max_top_k = _FINALIZE[digest]
        unit.update(
            expert_weights_dtype=expert_weights_dtype,
            kernel_variant=kernel_variant,
            max_top_k=max_top_k,
            unit_key=[stage, variant],
            variant=variant,
        )
    return dict(sorted(unit.items()))


def _record(digest: str) -> dict[str, Any]:
    """The ``PROGRAMS`` record of program ``digest``: the seven keys the export writes."""
    name = _PREFIX + digest
    _stage, plan, _dtypes, _tma, block, cluster, smem = _PROGRAMS[digest]
    return {
        "kernel": _KERNEL_OVERRIDES.get(name, "kernel_" + name),
        "library": name,
        "ffi_entry": "run",
        "arg_plan": [list(slot) for slot in ARG_PLANS[plan]],
        "launch": {
            "block": list(block),
            "cluster": list(cluster),
            "dynamic_smem_bytes": smem,
        },
        "arches": list(ARCHES),
        "unit": _unit(digest),
    }


