    const uint64_t device_bit = dev.device_id < 64 ? uint64_t{1} << dev.device_id : uint64_t{0};
    if (device_bit == 0 || (prepared_devices & device_bit) == 0) {
      CheckCuda(cudaSetDevice(dev.device_id), "cudaSetDevice");
      CheckCuda(cudaFuncSetAttribute(Kernel(), cudaFuncAttributeMaxDynamicSharedMemorySize, 166912), "cudaFuncSetAttribute");
      prepared_devices |= device_bit;
    }
  }
  CUtensorMap v_kv_k = EncodeTma_kv_k(a_kv_k);
  CUtensorMap v_kv_v = EncodeTma_kv_v(a_kv_v);
  void* v_kv_sf = DataPtr(a_kv_sf);
  void* v_v_pool = DataPtr(a_v_pool);
  void* v_q = DataPtr(a_q);
  void* v_q_sf = DataPtr(a_q_sf);
  void* v_page_table = DataPtr(a_page_table);
  void* v_kv_lens = DataPtr(a_kv_lens);
  void* v_q_gs = DataPtr(a_q_gs);
  void* v_kv_gs = DataPtr(a_kv_gs);
  void* v_out = DataPtr(a_out);
  void* v_partial_O = DataPtr(a_partial_O);
  void* v_partial_max = DataPtr(a_partial_max);
  void* v_partial_sum = DataPtr(a_partial_sum);
  float v_sm_scale = static_cast<float>(a_sm_scale);
  int32_t v_num_heads = static_cast<int32_t>(a_num_heads);
  int32_t v_q_len = static_cast<int32_t>(a_q_len);
  int32_t v_num_split = static_cast<int32_t>(a_num_split);
  int32_t v_page_stride = static_cast<int32_t>(a_page_stride);
  int32_t v_page_offset = static_cast<int32_t>(a_page_offset);
  int32_t v_batch = static_cast<int32_t>(a_batch);
  CUtensorMap v_ksf_map = EncodeTma_ksf_map(a_kv_sf);
  CUtensorMap v_vsf_map = EncodeTma_vsf_map(a_v_pool);
  void* kernel_args[] = {&v_kv_k, &v_kv_v, &v_kv_sf, &v_v_pool, &v_q, &v_q_sf, &v_page_table, &v_kv_lens, &v_q_gs, &v_kv_gs, &v_out, &v_partial_O, &v_partial_max, &v_partial_sum, &v_sm_scale, &v_num_heads, &v_q_len, &v_num_split, &v_page_stride, &v_page_offset, &v_batch, &v_ksf_map, &v_vsf_map};
  cudaLaunchConfig_t config{};
  config.gridDim = dim3(static_cast<unsigned>(grid_x), static_cast<unsigned>(grid_y), static_cast<unsigned>(grid_z));
  config.blockDim = dim3(480, 1, 1);
  config.dynamicSmemBytes = 166912;
  config.stream = stream;
  cudaLaunchAttribute attrs[2] = {};
  attrs[0].id = cudaLaunchAttributeClusterDimension;
  attrs[0].val.clusterDim.x = 2;
  attrs[0].val.clusterDim.y = 1;
  attrs[0].val.clusterDim.z = 1;
  attrs[1].id = cudaLaunchAttributeClusterSchedulingPolicyPreference;
  attrs[1].val.clusterSchedulingPolicyPreference = cudaClusterSchedulingPolicySpread;
  config.attrs = attrs;
  config.numAttrs = 2;
  CheckCuda(cudaLaunchKernelExC(&config, Kernel(), kernel_args),
            "cudaLaunchKernelExC");
}

