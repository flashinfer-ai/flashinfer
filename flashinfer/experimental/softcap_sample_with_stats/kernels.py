def _f32hex(v):
    import struct

    return "0f%08X" % struct.unpack("<I", struct.pack("<f", v))[0]


def _asm(ret_types, args, text, cons, side=False, loc=None, ip=None):
    if ret_types is None:
        llvm.inline_asm(
            None,
            args,
            text,
            cons,
            has_side_effects=True,
            is_align_stack=False,
            asm_dialect=llvm.AsmDialect.AD_ATT,
            loc=loc,
            ip=ip,
        )
        return None
    if len(ret_types) == 1:
        return llvm.inline_asm(
            ret_types[0],
            args,
            text,
            cons,
            has_side_effects=side,
            is_align_stack=False,
            asm_dialect=llvm.AsmDialect.AD_ATT,
            loc=loc,
            ip=ip,
        )
    res = llvm.inline_asm(
        llvm.StructType.get_literal(ret_types),
        args,
        text,
        cons,
        has_side_effects=side,
        is_align_stack=False,
        asm_dialect=llvm.AsmDialect.AD_ATT,
        loc=loc,
        ip=ip,
    )
    return [
        llvm.extractvalue(t, res, [i], loc=loc, ip=ip) for i, t in enumerate(ret_types)
    ]


