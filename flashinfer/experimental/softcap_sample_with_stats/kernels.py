def _round_keys(rk, pSeed, seed_from_tensor):
    """Philox4x32-10 round keys (k0 + r * 0x9E3779B9, k1 + r * 0xBB67AE85) for key = (seed, 0).

    Host seed: the 20 words are launch parameters (constant bank). Device seed: k0 is the low
    32 bits of the int64 at pSeed, read once per thread; the k1 words are compile-time constants.
    Index 10 (round 0's k1 = 0) is never read: the round-zero Philox step is specialized for it.
    """
    if const_expr(seed_from_tensor):
        k0 = ld_global_u32(pSeed)
        return (
            [k0 + Uint32((r * PHILOX_KA) & 0xFFFFFFFF) for r in range(10)]
            + [Uint32(0)]
            + [Uint32((r * PHILOX_KB) & 0xFFFFFFFF) for r in range(1, 10)]
        )
    return [Uint32(rk[i]) for i in range(20)]


@dsl_user_op
def gumbel_L4(cnt: Uint32, rk, *, loc=None, ip=None):
    """Philox4x32-10 at counter cnt (round keys rk[0:10] / rk[10:20]) -> 4 uniforms u ->
    L = log2(u) <= 0, with a linear near-one correction for lg2.approx."""
    L = [
        "{",
        ".reg .b32 c0, c1, c2, c3, l0, l1, h0, h1, g0, g1;",
        ".reg .b64 w0, w1;",
        ".reg .f32 u, lu;",
        ".reg .pred pp;",
    ]
    L += _philox_ptx(
        "$4",
        [f"${5 + r}" for r in range(10)],
        [None] + [f"${14 + r}" for r in range(1, 10)],
        ["c0", "c1", "c2", "c3"],
    )
    for j in range(4):
        L.append(f"mov.b32 g0, c{j};")
        L += _LOG2U_TAIL
        L.append(f"mov.f32 ${j}, lu;")
    L.append("}")
    r = _asm(
        [T.f32()] * 4,
        [Uint32(cnt).ir_value(loc=loc, ip=ip)]
        + [Uint32(x).ir_value(loc=loc, ip=ip) for x in rk[:10]]
        + [Uint32(x).ir_value(loc=loc, ip=ip) for x in rk[11:]],
        "\n".join(L),
        ",".join(["=f"] * 4 + ["r"] * 20),
        loc=loc,
        ip=ip,
    )
    return [Float32(v) for v in r]


