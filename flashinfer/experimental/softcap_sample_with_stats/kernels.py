def _philox_ptx(cin, keys0, keys1, outs):
    """Philox4x32-10 on counter (cin, 0, 0, 0); keys0[r], keys1[r] are round r's key words
    (k0 + r * 0x9E3779B9, k1 + r * 0xBB67AE85). Emits PTX using regs c0..c3, l0, l1, h0, h1."""
    # Exact round-zero specialization: the input counter is (cin,0,0,0) and seed < 2^31 makes
    # key1[0] = seed >> 32 = 0, so the second multiply and both xor chains collapse to moves.
    L = [
        f"mul.wide.u32 w0, {cin}, {PHILOX_A};",
        "mov.b64 {l0, h0}, w0;",
        f"mov.b32 c0, {keys0[0]};",
        "mov.b32 c1, 0;",
        "mov.b32 c2, h0;",
        "mov.b32 c3, l0;",
    ]
    for rnd in range(1, 10):
        L.append(f"mul.wide.u32 w0, c0, {PHILOX_A};")
        L.append(f"mul.wide.u32 w1, c2, {PHILOX_B};")
        L.append("mov.b64 {l0, h0}, w0;")
        L.append("mov.b64 {l1, h1}, w1;")
        L.append("xor.b32 c0, h1, c1;")
        L.append(f"xor.b32 c0, c0, {keys0[rnd]};")
        L.append("xor.b32 c2, h0, c3;")
        L.append(f"xor.b32 c2, c2, {keys1[rnd]};")
        L.append("mov.b32 c1, l1;")
        L.append("mov.b32 c3, l0;")
    for i in range(4):
        L.append(f"mov.b32 {outs[i]}, c{i};")
    return L


# log2(u) for one Philox output word g0 (Triton uint_to_uniform_float + clamp), L <= 0.
_C1 = 1.0 / math.log(2.0)
_LOG2U_TAIL = [
    # o -> int32 fold -> u = float(i) * 4.6566127342e-10f (0x2FFFFFFF, one ulp below 2^-31), clamped
    "shr.u32 g1, g0, 31;",
    "add.s32 g1, g1, g0;",  # o<0: o+1 = -(~o), so |float(o+1)| == float(~o) exactly
    "cvt.rn.f32.s32 u, g1;",
    "abs.f32 u, u;",
    # Bit-identical to max(RN(u*c), 1e-20): nonzero integer u*c is a multiple of 2^-55 and never
    # a rounding midpoint, while adding 1e-20 supplies the clamp exactly when u is zero.
    "fma.rn.f32 u, u, 0f2FFFFFFF, 0f1E3CE508;",
    "setp.gt.f32 pp, u, 0f3F7E0000;",
    "lg2.approx.ftz.f32 lu, u;",
    # near one, lg2.approx has poor relative accuracy: log2(u) ~= (u-1)/ln(2) (one predicated FMA)
    f"@pp fma.rn.f32 lu, u, {_f32hex(_C1)}, {_f32hex(-_C1)};",
]


