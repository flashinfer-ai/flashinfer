@dsl_user_op
def ratio_pick(
    ea: Float32, Ea: Float32, ia, eb: Float32, Eb: Float32, ib, *, loc=None, ip=None
):
    """Select the larger e/E by cross multiplication; the first operand wins exact ties."""
    ins = [Float32(v).ir_value(loc=loc, ip=ip) for v in (ea, Ea, eb, Eb)]
    cons = ["=f", "=f", "=r", "f", "f", "f", "f"]

    def iop(v, n):
        if isinstance(v, int):
            return str(v)
        ins.append(Int32(v).ir_value(loc=loc, ip=ip))
        cons.append("r")
        return f"${n}"

    na = iop(ia, len(ins) + 3)
    nb = iop(ib, len(ins) + 3)
    r = _asm(
        [T.f32(), T.f32(), T.i32()],
        ins,
        "{\n.reg .pred p;\n.reg .f32 a, b;\nmul.rn.f32 a, $3, $6;\n"
        "mul.rn.f32 b, $5, $4;\nsetp.ge.f32 p, a, b;\n"
        "selp.f32 $0, $3, $5, p;\nselp.f32 $1, $4, $6, p;\n"
        f"selp.b32 $2, {na}, {nb}, p;\n}}",
        ",".join(cons),
        loc=loc,
        ip=ip,
    )
    return Float32(r[0]), Float32(r[1]), Int32(r[2])


