@dsl_user_op
def softcap8(
    w0: Uint32,
    w1: Uint32,
    w2: Uint32,
    w3: Uint32,
    rcap: Float32,
    kk: Float32,
    *,
    loc=None,
    ip=None,
):
    """8 packed bf16 logits -> y = K * tanh.approx(l / cap)."""
    lines = ["{", ".reg .b32 t<8>;", ".reg .f32 a<8>;"]
    for i in range(4):
        lines.append(f"shl.b32 t{2 * i}, ${8 + i}, 16;")
        lines.append(f"and.b32 t{2 * i + 1}, ${8 + i}, 0xFFFF0000;")
    for j in range(8):
        lines.append(f"mov.b32 a{j}, t{j};")
        lines.append(f"mul.rn.f32 a{j}, a{j}, $12;")
        lines.append(f"tanh.approx.f32 a{j}, a{j};")
        lines.append(f"mul.rn.f32 ${j}, a{j}, $13;")
    lines.append("}")
    r = _asm(
        [T.f32()] * 8,
        [Uint32(x).ir_value(loc=loc, ip=ip) for x in (w0, w1, w2, w3)]
        + [Float32(x).ir_value(loc=loc, ip=ip) for x in (rcap, kk)],
        "\n".join(lines),
        ",".join(["=f"] * 8 + ["r"] * 4 + ["f"] * 2),
        loc=loc,
        ip=ip,
    )
    return [Float32(v) for v in r]


