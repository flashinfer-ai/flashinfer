      << "TMA source 'V_scale' must have unit innermost stride, got " << t.stride(-1);
  int64_t d3 = t.size(t.ndim() - 3);
  int64_t d4 = t.size(t.ndim() - 4);
  TVM_FFI_CHECK(d3 > 0 && d4 > 0, ValueError)
      << "TMA source 'V_scale' trailing dims must be positive";
  int64_t s3 = t.stride(t.ndim() - 3) * 1;
  TVM_FFI_CHECK(s3 > 0, ValueError)
      << "TMA source 'V_scale' physical strides must be positive";
  int64_t s4 = t.stride(t.ndim() - 4) * 1;
  TVM_FFI_CHECK(s4 > 0, ValueError)
      << "TMA source 'V_scale' physical strides must be positive";
  uint64_t global_dim[4] = {(uint64_t)(256), (uint64_t)(4), (uint64_t)(d3), (uint64_t)(d4)};
  TVM_FFI_CHECK(global_dim[0] > 0 && global_dim[1] > 0 && global_dim[2] > 0 && global_dim[3] > 0, ValueError)
      << "TMA descriptor for 'V_scale' resolved a non-positive global dim";
  TVM_FFI_CHECK(256u <= global_dim[0] && 4u <= global_dim[1] && 1u <= global_dim[2] && 1u <= global_dim[3], ValueError)
      << "TMA box (256, 4, 1, 1) exceeds resolved global dims for 'V_scale'";
  int64_t carrier_stride_0 = 256;
  TVM_FFI_CHECK(carrier_stride_0 >= 0, ValueError)
      << "TMA descriptor for 'V_scale' resolved global stride 1 negative";
  TVM_FFI_CHECK(carrier_stride_0 != 0 || global_dim[1] == 1, ValueError)
      << "TMA descriptor for 'V_scale' resolved global stride 1 zero while global dimension 1 is not 1";
  TVM_FFI_CHECK((carrier_stride_0 * 8) % 8 == 0, ValueError)
      << "TMA descriptor for 'V_scale' resolved global stride 1 to a non-whole-byte offset";
  int64_t carrier_stride_1 = s3;
  TVM_FFI_CHECK(carrier_stride_1 >= 0, ValueError)
      << "TMA descriptor for 'V_scale' resolved global stride 2 negative";
