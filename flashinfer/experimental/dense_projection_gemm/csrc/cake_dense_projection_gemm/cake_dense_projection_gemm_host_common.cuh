      << "cuDeviceGetCount failed while configuring an oversized-smem kernel";
  int configured = 0;
  for (int ordinal = 0; ordinal < device_count; ++ordinal) {
    CUdevice device = 0;
    if (cuDeviceGet(&device, ordinal) != CUDA_SUCCESS) continue;
