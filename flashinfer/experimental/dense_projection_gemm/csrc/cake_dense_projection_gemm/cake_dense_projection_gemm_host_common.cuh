  cudaKernel_t runtime_kernel = nullptr;
  TVM_FFI_CHECK_CUDA_ERROR(cudaGetKernel(&runtime_kernel, symbol));
  CUkernel handle = reinterpret_cast<CUkernel>(runtime_kernel);
