    if (cuKernelSetAttribute(CU_FUNC_ATTRIBUTE_MAX_DYNAMIC_SHARED_SIZE_BYTES,
                             opt_in, handle, device) != CUDA_SUCCESS) {
      continue;
    }
    ++configured;
  }
  TVM_FFI_CHECK(configured > 0, RuntimeError)
      << "no CUDA device accepts the oversized shared-memory mode for the linked kernel ("
      << smem_bytes << " B of dynamic shared memory)";
  return true;
