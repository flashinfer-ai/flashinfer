# Explicit target-owned registration of the generated programs of the
# Kimi-K3 vision tower (MoonViT-3D encoder + PatchMergerV2; SM100 / SM103).
#
# ``MODULES`` holds one record per physical generated module (a kernel plus
# its host binding): translation units, compile flags, FFI entry, argument
# plan, closure identity and the TMA descriptor contract (``tma_abi``;
# for the pointer-ABI attention module the caller-owned workspace size
# ``tma_workspace_bytes`` and its ``tma_prepare_entry``, the exported
# ``run_prepare_tma`` the host calls once per plan before the first launch).
# ``KERNELS`` maps ``"<arch>"`` to the logical
# kernel key -> module assignment the host launcher resolves at preparation:
#
# * ``gemm:<variant>:<tile>``   the fused tcgen05 BF16 GEMM family
#   (``pos``, ``norm_qkv_rope``, ``residual_wo``, ``norm_gelu``,
#   ``residual_fc1``, ``gelu_erf``, ``rmsnorm``) on the production tile
#   configuration ``select_tile_config`` picks for the token count (the
#   stream-K twins ``l_sk`` / ``m_sk`` inside their tile-census windows, the
#   eight-warp 256 x 128 tiles ``m_e8`` / ``m_e8_cs`` of the norm GEMMs) in
#   its production PDL form;
# * ``gemm:<variant>:<tile>:pdle`` the same tile's ``PDL_EARLY`` binary
#   (round 5: the grid-dependency wait moved into the load / epilogue roles
#   so the first weight stages stream before it), which the host launches
#   only inside the form's census window (``cake_backend.pdl_early_on``) and
#   never on the stream-K / tail / multicast / ``pos`` tiles
#   (``cake_backend.pdl_early_selected``); same kernel parameters, same
#   numerics;
# * ``gemm:<variant>:<tile>`` with a ``*_h`` tile (round 6): the half-N tail
#   twin of a plain persistent tile, routed where the tile census leaves a
#   tail that fits one half-round (``cake_backend.half_tail_split``); its
#   ``:pdle`` form exists like the base tile's;
# * ``attention:<layout>[:wide][:split]``   the packed-varlen BF16 attention
#   kernel: ``<layout>`` = ``tiles2`` / ``tiles1`` / ``ring3`` (two-tile and
#   SPLIT_KV unit layouts, the host plan rule chooses per ``grid_thws`` batch;
#   ``ring3`` is the SPLIT_KV form with the shared-O three-deep score ring,
#   selected per architecture and longest segment,
#   ``cake_backend.ring3_selected``); ``:wide`` (round 6) = the build reading
#   the four-word unit table with the next-unit prefetch, selected on short
#   rows (``cake_backend.unit_prefetch_selected``); ``:split`` (round 6) = the
#   partial-output build of the rows whose tail-round units the plan splits
#   into K/V ranges (``cake_backend.select_layout_and_split``), followed by
# * ``attention_merge``           the exact fixed-order merge of those split
#   units (one launch after every attention launch of a split row);
# * ``merge``                     final RMSNorm + 2x2 spatial / temporal-mean merge;
# * ``rmsnorm_apply``             the post-projector RMSNorm apply pass.
#
# Every module is an exact-architecture program (tcgen05 / TMEM / 2-CTA MMA);
# the sm_103a attention additionally drains scores with ``tcgen05.ld.red``.
# Both literals are populated verbatim by the generated-program export; do
# not edit them by hand.
