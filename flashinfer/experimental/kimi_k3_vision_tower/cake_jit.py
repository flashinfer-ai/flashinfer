def load_cake_kimi_k3_vision_tower_module(name: str, arch: str):
    """Load (once per program and architecture) program ``name`` built for
    ``arch``: the prebuilt library under ``aot/`` when the package ships it,
    else FlashInfer's JIT build of its ``build.json`` entry."""
    return cake_build.load_library(library_name(name, arch))


