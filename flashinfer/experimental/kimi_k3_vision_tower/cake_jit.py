    if ring3:
        if int(tiles_per_cta) != 1:
            raise ValueError(
                "the ring3 attention form is the SPLIT_KV (one-tile) layout"
            )
        return "attention:ring3"
    return f"attention:tiles{int(tiles_per_cta)}"


