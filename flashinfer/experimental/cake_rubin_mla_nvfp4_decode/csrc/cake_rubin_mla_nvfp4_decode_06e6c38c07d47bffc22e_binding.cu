  TVM_FFI_CHECK(t.ndim() >= 2, ValueError)
      << KERNEL_NAME << ": descriptor 'O_T16' takes a source of at least 2 dims, got " << t.ndim();
  CheckUnitInnerStride(t, "O_T16");
  int64_t d1 = t.size(-1);
  int64_t outer1 = NumelAbove(t, 1);
  check_dense_leading_dims(t, 1, "O_T16");
  int64_t s2 = t.stride(-2) * 2;
  cuuint64_t global_dim[2] = {Extent(d1, "O_T16"), Extent(outer1, "O_T16")};
  cuuint64_t global_strides[1] = {Stride(s2, "O_T16")};
  cuuint32_t box_dim[2] = {64u, 16u};
  cuuint32_t elem_strides[2] = {1u, 1u};
