                               batch_idx_1, tma_full_addr + (load_stage) * 8);
            }
            tma_4d_gmem2smem(smem_b_addr + load_stage * 21504, (&B), 0, 0, iter_k_1, batch_idx_1,
                             tma_full_addr + (load_stage) * 8);
            tma_4d_gmem2smem(smem_sfb_cp_addr + load_stage * 21504, (&SFB), 0, 0, iter_k_1,
                             batch_idx_1, tma_full_addr + (load_stage) * 8);
            if (pf_issued == 0) {
              mbarrier_arrive_expect_tx(tma_full_addr + (load_stage) * 8, 21504);
            }
            load_stage += 1;
            if (load_stage == 8) {
              load_stage = 0;
              _phase_mma_done ^= 1;
            }
          }
        }
      }
    }
  }

  // Cleanup
  __syncthreads();  // barrier before TMEM dealloc

  if (warp == 0) {
    asm volatile(
        "tcgen05.dealloc.cta_group::1.sync.aligned.b32 %0, %1;" ::"r"(tmem_addr_storage[0]),
        "r"(64));
  }
}

