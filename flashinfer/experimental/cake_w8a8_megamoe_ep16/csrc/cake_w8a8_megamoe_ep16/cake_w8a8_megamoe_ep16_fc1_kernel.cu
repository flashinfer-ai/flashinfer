              uint64_t _tcgen05_cp_desc_2 =
                  ((((uint64_t)(smem_sfb_cp_addr + mma_tma_stage * 38400)) & 0x3FFFFULL) >> 4ULL) |
                  (((((uint64_t)(0)) & 0x3FFFFULL) >> 4ULL) << 16ULL) |
                  (((((uint64_t)(128)) & 0x3FFFFULL) >> 4ULL) << 32ULL) | (1ULL << 46ULL) |
                  (0ULL << 61ULL);
              asm volatile("tcgen05.cp.cta_group::1.32x128b.warpx4 [%0], %1;" ::"r"(
                               (uint32_t)(tmem_tmem_sfb)),
                           "l"(_tcgen05_cp_desc_2)
                           : "memory");
            }
            int _mma_a_lo_0 = (((smem_a_addr) >> 4) & 0x3FFF) + (mma_tma_stage) * 2400;
            int _mma_b_lo_0 = (((smem_b_addr) >> 4) & 0x3FFF) + (mma_tma_stage) * 2400;
            {
              uint64_t a_desc = ((uint64_t)(uint32_t)_mma_a_lo_0) | ((uint64_t)0x40004040 << 32);
              uint64_t b_desc = ((uint64_t)(uint32_t)_mma_b_lo_0) | ((uint64_t)0x40004040 << 32);

              tcgen05_mma_mxf8_bs(tmem_tmem_acc, a_desc + 0, b_desc + 0, 0x8880000U, tmem_tmem_sfa,
                                  tmem_tmem_sfb, ((init_flag) ? 0 : 1));
              tcgen05_mma_mxf8_bs(tmem_tmem_acc, a_desc + 2, b_desc + 2, 0x28880010U, tmem_tmem_sfa,
                                  tmem_tmem_sfb, 1);
              tcgen05_mma_mxf8_bs(tmem_tmem_acc, a_desc + 4, b_desc + 4, 0x48880020U, tmem_tmem_sfa,
                                  tmem_tmem_sfb, 1);
              tcgen05_mma_mxf8_bs(tmem_tmem_acc, a_desc + 6, b_desc + 6, 0x68880030U, tmem_tmem_sfa,
                                  tmem_tmem_sfb, 1);
            }
            int _mma_a_lo_1 = (((smem_a_addr + 16384) >> 4) & 0x3FFF) + (mma_tma_stage) * 2400;
            int _mma_b_lo_1 = (((smem_b_addr) >> 4) & 0x3FFF) + (mma_tma_stage) * 2400;
            {
              uint64_t a_desc = ((uint64_t)(uint32_t)_mma_a_lo_1) | ((uint64_t)0x40004040 << 32);
              uint64_t b_desc = ((uint64_t)(uint32_t)_mma_b_lo_1) | ((uint64_t)0x40004040 << 32);

              tcgen05_mma_mxf8_bs((tmem_tmem_acc + (32)), a_desc + 0, b_desc + 0, 0x8880000U,
                                  tmem_tmem_sfa + 4, tmem_tmem_sfb, ((init_flag) ? 0 : 1));
              tcgen05_mma_mxf8_bs((tmem_tmem_acc + (32)), a_desc + 2, b_desc + 2, 0x28880010U,
                                  tmem_tmem_sfa + 4, tmem_tmem_sfb, 1);
              tcgen05_mma_mxf8_bs((tmem_tmem_acc + (32)), a_desc + 4, b_desc + 4, 0x48880020U,
                                  tmem_tmem_sfa + 4, tmem_tmem_sfb, 1);
              tcgen05_mma_mxf8_bs((tmem_tmem_acc + (32)), a_desc + 6, b_desc + 6, 0x68880030U,
                                  tmem_tmem_sfa + 4, tmem_tmem_sfb, 1);
            }
          }
          elect_commit(mma_done_addr + (mma_tma_stage) * 8);
          mma_tma_stage += 1;
          if (mma_tma_stage == 4) {
            mma_tma_stage = 0;
            _phase_tma_full ^= 1;
          }
        }
        elect_commit(mainloop_done_addr + (mma_epi_stage) * 8);
        _phase_epilogue_done ^= 1;
      }
    }
  }
  // ---- Role: load ----
  if (warp == 5) {
    {  // load_main
      unsigned int load_stage = 0;
      unsigned int pf_first_tile = bid;
      if (elect_sync()) {
        if (bid < grid_m) {
          int pf_batch_idx = tile_expert[bid];
          int pf_packed_off = tile_m_local[bid] * 2;
#pragma unroll
          for (int pf_k = 0; pf_k < 4; pf_k++) {
            if (pf_k < K_tiles) {
              mbarrier_arrive_expect_tx(tma_full_addr + (pf_k) * 8, 38400);
              tma_4d_gmem2smem(smem_a_addr + (unsigned int)(pf_k * 38400), (&A), 0, 0, pf_k,
                               pf_batch_idx * (N / 256) + pf_packed_off / 256,
                               tma_full_addr + (pf_k) * 8);
              int pf_sfa_tile = pf_packed_off / 256 * K_tiles + pf_k;
              tma_4d_gmem2smem(smem_sfa_cp_addr + (unsigned int)(pf_k * 38400), (&SFA), 0, 0,
                               pf_sfa_tile, pf_batch_idx, tma_full_addr + (pf_k) * 8);
            }
          }
        }
      }
      asm volatile("griddepcontrol.wait;" ::: "memory");
      unsigned int _phase_mma_done = 1;
      if (elect_sync()) {
#pragma unroll 1
        for (unsigned int tile_idx_2 = bid; tile_idx_2 < grid_m; tile_idx_2 += num_bids) {
          if (num_bids + (int)tile_idx_2 >= grid_m) {
            asm volatile("griddepcontrol.launch_dependents;" ::: "memory");
          }
          int batch_idx_1 = tile_expert[tile_idx_2];
          int input_batch_idx = batch_idx_1;
          int off_n_out_1 = tile_m_local[tile_idx_2];
          int packed_off = off_n_out_1 * 2;
#pragma unroll 1
          for (int iter_k_1 = 0; iter_k_1 < K_tiles; iter_k_1++) {
            mbarrier_wait(mma_done_addr + (load_stage) * 8, _phase_mma_done);
            int pf_issued = 0;
            if (tile_idx_2 == pf_first_tile) {
              if (iter_k_1 < 4) {
                pf_issued = 1;
              }
            }
            if (pf_issued == 0) {
              tma_4d_gmem2smem(smem_a_addr + load_stage * 38400, (&A), 0, 0, iter_k_1,
                               batch_idx_1 * (N / 256) + packed_off / 256,
                               tma_full_addr + (load_stage) * 8);
              int pdl_sfa_tile = packed_off / 256 * K_tiles + iter_k_1;
              tma_4d_gmem2smem(smem_sfa_cp_addr + load_stage * 38400, (&SFA), 0, 0, pdl_sfa_tile,
                               batch_idx_1, tma_full_addr + (load_stage) * 8);
            }
            tma_4d_gmem2smem(smem_b_addr + load_stage * 38400, (&B), 0, 0, iter_k_1,
                             input_batch_idx, tma_full_addr + (load_stage) * 8);
            tma_4d_gmem2smem(smem_sfb_cp_addr + load_stage * 38400, (&SFB), 0, 0, iter_k_1,
                             input_batch_idx, tma_full_addr + (load_stage) * 8);
            if (pf_issued == 0) {
              mbarrier_arrive_expect_tx(tma_full_addr + (load_stage) * 8, 38400);
            }
            load_stage += 1;
            if (load_stage == 4) {
              load_stage = 0;
              _phase_mma_done ^= 1;
            }
          }
        }
      }
    }
  }

  // Cleanup
  asm volatile("tcgen05.fence::before_thread_sync;" ::: "memory");
  __syncthreads();  // barrier before TMEM dealloc

  if (warp == 0) {
    asm volatile(
        "tcgen05.dealloc.cta_group::1.sync.aligned.b32 %0, %1;" ::"r"(tmem_addr_storage[0]),
        "r"(128));
  }
}

