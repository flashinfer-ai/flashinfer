def registered_arches() -> tuple[str, ...]:
    """Architectures at least one registered program is compiled for."""
    return tuple(
        sorted({arch for record in MODULES.values() for arch in record["arches"]})
    )


def route_available(arch: str, required_keys: tuple[str, ...] = ()) -> bool:
    """True when every key in ``required_keys`` is registered and compiled for ``arch``."""
    return all(
        key in KERNELS and arch in MODULES[KERNELS[key]]["arches"]
        for key in required_keys
    )


def kernel_module_name(arch: str, key: str) -> str:
    """Return the registered program serving ``key`` on ``arch``."""
    name = KERNELS.get(key)
    if name is None:
        raise NotImplementedError(
            f"The generated Kimi-K3 LatentMoE kernel {key!r} is not registered in this "
            "checkout (see flashinfer-ai/flashinfer#4568)"
        )
    record = MODULES[name]
    if arch not in record["arches"]:
        raise NotImplementedError(
            f"The generated Kimi-K3 LatentMoE kernel {key!r} is registered for "
            f"{record['arches']}, not for {arch} (see flashinfer-ai/flashinfer#4568)"
        )
    return name


def kernel_defines(key: str) -> dict[str, int | str]:
    """Compile-line definitions ``key`` adds to its program: its ``SPECIALIZATIONS``
    constants and, for a key folded into a shared program, the kernel symbol it keeps
    (``KERNEL_SYMBOLS`` -> ``CAKE_PROGRAM_KERNEL``); empty for a fully specialised program.
    """
    defines: dict[str, int | str] = dict(SPECIALIZATIONS.get(key, {}))
    symbol = KERNEL_SYMBOLS.get(key)
    if symbol is not None:
        defines["CAKE_PROGRAM_KERNEL"] = symbol
    return defines


def _header_dirs():
    installed = [jit_env.FLASHINFER_CSRC_DIR, jit_env.FLASHINFER_INCLUDE_DIR]
    if (installed[0] / "tvm_ffi_utils.h").is_file() and (
        installed[1] / "flashinfer/layout.cuh"
    ).is_file():
        return installed
    checkout = Path(__file__).resolve().parents[3]
    source = [checkout / "csrc", checkout / "include"]
    if (source[0] / "tvm_ffi_utils.h").is_file() and (
        source[1] / "flashinfer/layout.cuh"
    ).is_file():
        return source
    raise FileNotFoundError("FlashInfer binding headers were not found")


@functools.cache
def gen_cake_kimi_k3_latent_moe_module(arch: str, key: str):
    """JIT spec of the program serving ``key`` on ``arch`` (one build per program, arch and define set)."""
    name = kernel_module_name(arch, key)
    record = MODULES[name]
    defines = kernel_defines(key)
    root = Path(__file__).resolve().parent / "csrc"
    sources = [root / relative for relative in record["sources"]]
    # The module name is salted with the specialisation constants only; the kernel
    # symbol of a folded key follows from its program and those constants.
    identity = f"{arch}_{record['closures'][arch][:16]}"
    for define, value in sorted(SPECIALIZATIONS.get(key, {}).items()):
        identity += f"_{define}{value}"
    return gen_jit_spec(
        name=f"{name}_{identity}",
        sources=sources,
        extra_cuda_cflags=[
            *ARCH_NVCC_FLAGS[arch],
            *record["compile_flags"],
            *[f"-D{define}={value}" for define, value in sorted(defines.items())],
        ],
        extra_ldflags=["-lcuda"],
        extra_include_paths=[
            root,
            *sorted({p.parent for p in sources}),
            *_header_dirs(),
        ],
        use_fast_math=False,
    )


@functools.cache
def load_cake_kimi_k3_latent_moe_module(arch: str, key: str):
    return gen_cake_kimi_k3_latent_moe_module(arch, key).build_and_load()
