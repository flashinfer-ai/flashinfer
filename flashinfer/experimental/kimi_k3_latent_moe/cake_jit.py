#
# ``MODULES`` holds one record per physical program: translation units
# (relative to ``csrc/``), the architectures it serves, compile flags, FFI
# entry, argument plan, launch geometry and per-architecture closure digests.
#
# ``KERNELS`` maps the logical kernel key the host planner resolves to its
# program; ``SPECIALIZATIONS`` carries the compile-line definitions a key
# adds to its program (one program serves several keys that differ only in
# those constants, e.g. the shared-intermediate width of the front GEMM):
#
# * ``decode:<symbol>``  one weight-streaming swapped-AB tcgen05 instance per
#   decode plan (T <= 128: N padding, ring depth, cluster pairs, fused norm,
#   resident B operand, staged rows, issue gate are baked into the symbol);
# * ``front:i<I_local>[e1]`` the persistent 2-CTA prefill front GEMM (T > 128)
#   per shared-intermediate width (TP1 6144, TP8 768); ``e1`` streams the
#   weights with the ``evict_first`` L2 policy (T <= 512);
# * ``tail_norm:e<0|1>`` the one-pass RMSNorm kernel with the late / early
#   ``griddepcontrol.launch_dependents`` trigger the host plan selects;
# * ``tail_gemm:tp<1|8>e<0|1>f<0|1>[s<stages>][n<block_n>][t1]`` the persistent
#   2-CTA prefill tail GEMM (PDL launch, trailing-wave stream-K) per
#   tensor-parallel degree; ``e1`` loads the weight boxes ``evict_first``
#   (single-wave grids); ``f1`` fuses the RMSNorm into the launch (TP1 T = 256 /
#   512); ``s6`` / ``s9n128`` are the 6-deep ring and the 128-wide 9-deep ring
#   instances; ``t1`` stages the final item through TMA stores.
#
# The literals are populated by the generated-program export; do not edit
# them by hand.
