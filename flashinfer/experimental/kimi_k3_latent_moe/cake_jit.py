def registered_arches() -> tuple[str, ...]:
    """Architectures at least one registered program is compiled for."""
    return tuple(
        sorted({arch for record in MODULES.values() for arch in record["arches"]})
    )


def route_available(arch: str, required_keys: tuple[str, ...] = ()) -> bool:
    """True when every key in ``required_keys`` is registered and compiled for ``arch``."""
    return all(
        key in KERNELS and arch in MODULES[KERNELS[key]]["arches"]
        for key in required_keys
    )


def kernel_module_name(arch: str, key: str) -> str:
    """Return the registered program serving ``key`` on ``arch``."""
    name = KERNELS.get(key)
    if name is None:
        raise NotImplementedError(
            f"The generated Kimi-K3 LatentMoE kernel {key!r} is not registered in this "
            "checkout (see flashinfer-ai/flashinfer#4568)"
        )
    record = MODULES[name]
    if arch not in record["arches"]:
        raise NotImplementedError(
            f"The generated Kimi-K3 LatentMoE kernel {key!r} is registered for "
            f"{record['arches']}, not for {arch} (see flashinfer-ai/flashinfer#4568)"
        )
    return name


