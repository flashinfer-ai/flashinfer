@functools.cache
def gen_cake_kimi_k3_latent_moe_module(arch: str, key: str):
    """JIT spec of the program serving ``key`` on ``arch`` (one build per program, arch and define set)."""
    name = kernel_module_name(arch, key)
    record = MODULES[name]
    defines = kernel_defines(key)
    root = Path(__file__).resolve().parent / "csrc"
    sources = [root / relative for relative in record["sources"]]
    identity = f"{arch}_{record['closures'][arch][:16]}"
    for define, value in sorted(defines.items()):
        identity += f"_{define}{value}"
    return gen_jit_spec(
        name=f"{name}_{identity}",
        sources=sources,
        extra_cuda_cflags=[
            *ARCH_NVCC_FLAGS[arch],
            *record["compile_flags"],
            *[f"-D{define}={value}" for define, value in sorted(defines.items())],
        ],
        extra_ldflags=["-lcuda"],
        extra_include_paths=[
            root,
            *sorted({p.parent for p in sources}),
            *_header_dirs(),
        ],
        use_fast_math=False,
    )


@functools.cache
def load_cake_kimi_k3_latent_moe_module(arch: str, key: str):
    return gen_cake_kimi_k3_latent_moe_module(arch, key).build_and_load()
