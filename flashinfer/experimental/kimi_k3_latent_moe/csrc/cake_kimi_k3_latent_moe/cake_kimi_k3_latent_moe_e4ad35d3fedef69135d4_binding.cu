  int32_t v_sk_ipc = static_cast<int32_t>(a_sk_ipc);
  int32_t v_sk_max_seg = static_cast<int32_t>(a_sk_max_seg);
  int32_t v_sk_total = static_cast<int32_t>(a_sk_total);
