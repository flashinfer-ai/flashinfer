"""Vendor the gated attention block's SERVING closure out of cuDNN Frontend into a self-contained package.

    vendor.py --fe <cudnn_frontend checkout> --target <dir of the vendored package> [--commit d8b0a7ed5]
              [--closure closure.json] [--package <dotted import path of the vendored package>] [--selftest]

Lives in ``flashinfer/experimental/qwen_3_5_block/_vendoring/`` next to ``closure.json`` (the closure list, produced by
``build_closure.py`` from the import traces of ``trace_closure.py``) and ``nanobind_enums.json`` (the extension's enum tables,
read live when a cuDNN Frontend install is importable, else from the recorded copy); the README there is the recipe.

* Every file of the closure is read with ``git show <commit>:<path>`` -- the copy is reproducible from the commit alone, never
  from a working tree.
* Every ``import cudnn...`` / ``from cudnn... import ...`` statement is rewritten to the vendored package path through an
  EXPLICIT import map (``cudnn`` -> ``<package>``, ``cudnn.X`` -> ``<package>.X``, ``cudnn._compiled_module`` -> the shim), by
  locating the ``ast.Import`` / ``ast.ImportFrom`` nodes and replacing exactly their source spans.  Relative imports are left
  alone (they resolve inside the vendored tree).  No regular expression touches anything that is not an import statement; the
  ONE string-literal site that importlib resolves at runtime (``engines/manifest.py``'s ``("cudnn._gemm_validate", ...)``
  family references) is rewritten by locating ``ast.Constant`` nodes in that one named file.
* Six declared PATCHES (P0-P3, P5-P6, listed in VENDOR.md): P0-P2, exact text, make the copy importable without the nanobind
  extension; P3, context-anchored regular expressions that name nothing themselves, rewords the comment / docstring lines that
  named internal hosts or internal file paths; P5-P6, exact text, prune what the vendored subset does not carry (the lazy
  exports outside the closure, the sm120 arch family); everything else is byte-identical to the commit, SPDX headers included.
  P4 (the cache-write launcher's one-device check, carried ahead of its upstream landing) was RETIRED at the d8b0a7ed5
  re-vendor: the same hunk is in the pinned commit, so ``kernels/cache_write.py`` is byte-faithful again; a patch id is never
  reused.
* The one file vendored from OUTSIDE ``python/cudnn`` (``EXTRA_FILES``) is pinned by digest like every closure file: ``closure.json``
  carries its blob's sha256 (``extra_files``, written by ``build_closure.py``) and the exporter stops when the blob moved.
* The generated files (the package root, the shim ``_compiled_module.py``, ``VENDOR.md``, ``VENDOR_MANIFEST.json``) carry a
  FlashInfer-side Apache-2.0 header and name the origin + commit.
* ``--selftest`` imports the vendored package in a SUBPROCESS with the real ``cudnn`` package shadowed
  (``sys.modules["cudnn"] = None``) and no GPU (``CUDA_VISIBLE_DEVICES=``), checks that no ``cudnn.*`` module was imported, and
  declares the three serving forms (dense prefill with write-through, EXTEND, DECODE) on host tensors.
"""

