def selftest(target: Path, package: str, python: str) -> int:
    parts = package.split(".")
    # the package's parents must be importable: build a scratch tree of namespace __init__s above the target when needed
    root = target  # <root>/<parts[0]>/.../<parts[-1]> == target, so the import root is len(parts) levels up
    for _ in parts:
        root = root.parent
    for i in range(1, len(parts)):
        init = root.joinpath(*parts[:i]) / "__init__.py"
        if not init.exists():
            init.parent.mkdir(parents=True, exist_ok=True)
            init.write_text("# scratch namespace for the vendor.py self-test\n")
    # the import root first; an inherited PYTHONPATH stays behind it (a caller may hand FlashInfer's pure dependencies that way)
    pythonpath = os.pathsep.join(
        p for p in (str(root), os.environ.get("PYTHONPATH", "")) if p
    )
    env = dict(
        os.environ,
        CUDA_VISIBLE_DEVICES="",
        VENDOR_PKG=package,
        PYTHONPATH=pythonpath,
        PYTHONDONTWRITEBYTECODE="1",
    )
    env.pop("CUDNN_FRONTEND_ENABLE_FROST_ENGINES", None)
    p = subprocess.run(
        [python, "-c", SELFTEST], env=env, capture_output=True, text=True, cwd=str(root)
    )
    sys.stdout.write(p.stdout[-4000:])
    if p.returncode:
        sys.stdout.write(p.stderr[-6000:])
    return p.returncode


