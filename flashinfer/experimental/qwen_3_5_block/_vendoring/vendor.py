def sh(*cmd, cwd=None) -> bytes:
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True).stdout


def git_blob(fe: Path, commit: str, path: str) -> bytes:
    return sh("git", "-C", str(fe), "show", f"{commit}:{path}")


# --------------------------------------------------------------------------- the AST import rewriter


class Rewriter:
    def __init__(self, package: str, closure_modules: set[str]):
        self.pkg = package
        self.closure = closure_modules
        self.map = {
            "cudnn": package,
            "cudnn._compiled_module": package + "._compiled_module",
        }
        for m in closure_modules:
            self.map[m] = package + m[len("cudnn") :]
        self.dangling: dict[str, set[str]] = {}
        self.string_edits = 0

    def target(self, mod: str, where: str) -> str:
        if mod in self.map:
            return self.map[mod]
        # an import of a module OUTSIDE the closure (a lazily imported excluded path): the same prefix rule, recorded
        self.dangling.setdefault(where, set()).add(mod)
        return self.pkg + mod[len("cudnn") :]

    def rewrite(self, src: str, where: str) -> tuple[str, int]:
        tree = ast.parse(src)
        lines = src.splitlines(keepends=True)
        offsets = [0]
        for ln in lines:
            offsets.append(offsets[-1] + len(ln))

        def span(node):
            return offsets[node.lineno - 1] + node.col_offset, offsets[
                node.end_lineno - 1
            ] + node.end_col_offset

        edits = []  # (start, end, new text)
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                if not any(
                    a.name == "cudnn" or a.name.startswith("cudnn.") for a in node.names
                ):
                    continue
                parts = []
                for a in node.names:
                    if a.name == "cudnn" or a.name.startswith("cudnn."):
                        t = self.target(a.name, where)
                        # `import cudnn` binds the name `cudnn`; keep that binding through `as` (a dotted `import a.b.c as cudnn` is valid)
                        alias = a.asname or ("cudnn" if a.name == "cudnn" else None)
                        if a.name != "cudnn" and a.asname is None:
                            # `import cudnn.gemm.frost` (side-effect import, or used as `cudnn.gemm.frost.X`): keep the side effect and the
                            # `cudnn` name both correct by importing the vendored module and binding the root under `cudnn`
                            parts.append(f"import {t}")
                            parts.append(f"import {self.pkg} as cudnn")
                            continue
                        parts.append(f"import {t}" + (f" as {alias}" if alias else ""))
                    else:
                        parts.append(
                            f"import {a.name}" + (f" as {a.asname}" if a.asname else "")
                        )
                s, e = span(node)
                edits.append((s, e, "; ".join(dict.fromkeys(parts))))
            elif (
                isinstance(node, ast.ImportFrom)
                and node.level == 0
                and node.module
                and (node.module == "cudnn" or node.module.startswith("cudnn."))
            ):
                t = self.target(node.module, where)
                names = ", ".join(
                    a.name + (f" as {a.asname}" if a.asname else "") for a in node.names
                )
                s, e = span(node)
                text = src[s:e]
                if (
                    "(" in text.split("import", 1)[1]
                ):  # keep a parenthesised multi-line list as written, only the module changes
                    head, tail = text.split("import", 1)
                    new = f"from {t} import" + tail
                else:
                    new = f"from {t} import {names}"
                edits.append((s, e, new))
            elif (
                isinstance(node, ast.Constant)
                and isinstance(node.value, str)
                and where in STRING_SITE_FILES
            ):
                v = node.value
                if v == "cudnn" or (
                    v.startswith("cudnn.")
                    and v.replace(".", "").replace("_", "").isalnum()
                ):
                    s, e = span(node)
                    edits.append((s, e, repr(self.target(v, where + " (string site)"))))
                    self.string_edits += 1
        out = src
        for s, e, new in sorted(edits, key=lambda x: -x[0]):
            out = out[:s] + new + out[e:]
        return out, len(edits)


