@functools.cache
def descriptor_vectors() -> torch.Tensor:
    grid = torch.tensor(
        list(b"".join(struct.pack("<Q", word) for word in _GRID_WORDS)),
        dtype=torch.int16,
    ).reshape(512, 8)
    descriptors = torch.arange(65536)
    sign_index = descriptors >> 9
    parity = torch.zeros_like(sign_index)
    for bit in range(7):
        parity ^= (sign_index >> bit) & 1
    mask = sign_index | (parity << 7)
    signs = 1 - 2 * ((mask[:, None] >> torch.arange(8)) & 1)
    return (grid[descriptors % 512] * signs).to(torch.int8)


def dequantize_blocks(blocks: torch.Tensor) -> torch.Tensor:
    """Decode source [..., K/256, 74] blocks to FP32 [..., K] on CPU."""
    if blocks.shape[-1] == 34:
        from .q8_0_reference import dequantize_blocks as decode_q8
        return decode_q8(blocks)
    if blocks.shape[-1] == 66:
        from .iq2_xxs_reference import dequantize_blocks as decode_xxs
        return decode_xxs(blocks)
    if blocks.dtype != torch.uint8 or blocks.shape[-1] != 74:
        raise ValueError("expected uint8 IQ2_XS blocks ending in 74 bytes")
    raw = blocks.cpu().contiguous()
    base = raw[..., :2].contiguous().view(torch.float16).float().squeeze(-1)
    q = raw[..., 2:66].contiguous().view(torch.uint16).long()
    vectors = descriptor_vectors()[q].float()
    pairs = raw[..., 66:]
    scales = torch.stack((pairs & 15, pairs >> 4), -1).flatten(-2).float()
    scales = (base[..., None] * (scales + 0.5)) * 0.25
    values = vectors * scales.repeat_interleave(2, -1)[..., None]
    return values.flatten(-3)


def moe_reference_iq2_xs(
    x,
    w13,
    w2,
    topk_ids,
    topk_weights,
    *,
    activation="silu",
    w13_layout="w31",
    expert_ids=None,
    swiglu_limit=None,
):
    """FP32 MoE oracle with BF16 decoded weights and materialized boundaries."""
    if activation not in {"silu", "relu2"} or w13_layout not in {"w13", "w31"}:
        raise ValueError("unsupported IQ2_XS oracle activation or projection order")
    output = torch.zeros_like(x, dtype=torch.float32)
    selected = range(w13.shape[0]) if expert_ids is None else expert_ids
    positions = {expert: local for local, expert in enumerate(selected)}
    for expert in topk_ids.unique().tolist():
        local = positions.get(expert)
        if local is None:
            continue
        row, slot = (topk_ids == expert).nonzero(as_tuple=True)
        first = dequantize_blocks(w13[local]).bfloat16().to(x.device).float()
        second = dequantize_blocks(w2[local]).bfloat16().to(x.device).float()
        projected = (x[row].float() @ first.T).bfloat16().float()
        if activation == "silu":
            left, right = projected.chunk(2, -1)
            gate, up = (left, right) if w13_layout == "w31" else (right, left)
            if swiglu_limit is not None:
                gate, up = (
                    gate.clamp(max=swiglu_limit),
                    up.clamp(-swiglu_limit, swiglu_limit),
                )
            intermediate = (torch.nn.functional.silu(gate) * up).bfloat16().float()
        else:
            intermediate = projected.relu().square().bfloat16().float()
        contribution = (
            ((intermediate @ second.T) * topk_weights[row, slot, None])
            .bfloat16()
            .float()
        )
        output.index_add_(0, row, contribution)
    return output.bfloat16()
