def library_name(name: str, arch: str) -> str:
    """``build.json`` library of record ``name`` built for ``arch``: ``<library>_<arch>``."""

    record = MODULES[name]
    if arch not in record["arches"]:
        raise RuntimeError(
            f"Cake Kimi-K3 AttnRes program {name} is not delivered for {arch}; "
            f"its architectures: {record['arches']}"
        )
    return f"{record['library']}_{arch}"


@functools.cache
def load(name: str, arch: str) -> Any:
    """The loaded tvm-ffi module of record ``name`` built for ``arch``.

    The prebuilt ``aot/`` library when a builder compiled it, else FlashInfer's
    JIT build of the same sources and flags (``cake_build.load_library``).
    """

    return cake_build.load_library(library_name(name, arch))


def specs_for_arch(arch: str) -> list[Any]:
    """JIT specifications of every ``arch`` library without a prebuilt file (for
    ahead-of-time warm-up through FlashInfer's ``build_jit_specs``)."""

    return cake_build.jit_specs(arch)


def record_of(arch: str, kernel_key: str) -> str:
    """The record the host policy's ``kernel_key`` resolves to on ``arch``."""

    table = KERNELS.get(arch)
    if table is None:
        raise RuntimeError(f"no Cake Kimi-K3 AttnRes programs are delivered for {arch}")
    name = table.get(kernel_key)
    if name is None:
        raise RuntimeError(
            f"the Cake Kimi-K3 AttnRes kernel {kernel_key!r} is not delivered for {arch}"
        )
    return name


