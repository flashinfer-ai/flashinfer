def q_tiles(q_len: int, ratio: int) -> int:
    """The 128-row Q tiles of one KV head for ``q_len`` draft tokens at GQA ratio ``ratio``."""
    return -(-int(q_len) * int(ratio) // TILE_ROWS)


def select_record(
    *, precision: str, cache: str, ratio: int, q_len: int, kernel: str = "auto"
) -> str:
    """The record that serves a D512 tree problem: ``kernel`` ``auto`` picks the
    ``pair`` schedule for an E4M3 cache whose KV heads have an even number of
    128-row Q tiles and the ``tmem`` schedule otherwise; ``tmem`` serves every
    precision, layout and parity; ``pair`` serves E4M3 caches at even tile
    counts only (``ValueError`` otherwise, as for a precision, layout, ratio or
    kernel outside the vocabulary)."""
    if precision not in PRECISIONS:
        raise ValueError(f"precision must be one of {PRECISIONS}, got {precision!r}")
    if cache not in CACHES:
        raise ValueError(f"cache must be one of {CACHES}, got {cache!r}")
    if ratio not in RATIOS:
        raise ValueError(f"Hq/Hkv must be one of {RATIOS}, got {ratio!r}")
    if kernel not in KERNELS:
        raise ValueError(f"kernel must be one of {KERNELS}")
    even = q_tiles(q_len, ratio) % 2 == 0
    if kernel == "auto":
        kernel = "pair" if precision == "fp8" and even else "tmem"
    if kernel == "pair":
        if precision != "fp8":
            raise ValueError(
                "pair serves E4M3 KV (contiguous or page128); use tmem or auto for FP16 KV"
            )
        if not even:
            raise ValueError(
                "pair needs an even number of 128-row Q tiles per KV head (ceil(q_len * ratio / 128)); use tmem or auto"
            )
        name = f"tree_{precision}_{cache}_g{ratio}_pair"
    else:
        name = f"tree_{precision}_{cache}_g{ratio}_tmem_{'even' if even else 'odd'}"
    if name not in MODULES:
        raise ValueError(f"no delivered program serves {name}")
    return name


def select_decode_record(
    *,
    ratio: int,
    precision: str = "fp16",
    cache: str = "contig",
    partitions: int | None = None,
) -> str:
    """The record that serves a D128 decode problem (one query token per request)
    at a GQA ratio of ``DECODE_RATIOS`` over a contiguous FP16 cache
    (``ValueError`` otherwise).  ``partitions`` (:func:`decode_partitions`)
    picks the record: the one whose variant's ``cluster_partitions`` equals the
    count when the registry ships such a program, else the record without
    ``cluster_partitions``, which merges any count through the workspace; one
    such record is expected."""
    if ratio not in DECODE_RATIOS:
        raise ValueError(
            f"the D128 decode route serves Hq/Hkv in {DECODE_RATIOS}, got {ratio!r}"
        )
    if precision != "fp16" or cache != "contig":
        raise ValueError("the D128 decode route serves a contiguous FP16 KV cache")
    if partitions is not None and (
        isinstance(partitions, bool) or type(partitions) is not int or partitions < 1
    ):
        raise ValueError("partitions must be None or a positive integer")
    served = {
        name: record["variant"].get("cluster_partitions")
        for name, record in MODULES.items()
        if record["stage"] == "decode"
        and record["variant"].get("precision") == precision
        and record["variant"].get("cache") == cache
    }
    if partitions is not None:
        clustered = [name for name, count in served.items() if count == partitions]
        if len(clustered) > 1:
            raise ValueError(
                f"the registry has {len(clustered)} decode records for {partitions} cluster partitions; one is expected"
            )
        if clustered:
            return clustered[0]
    matches = [name for name, count in served.items() if count in (None, 1)]
    if len(matches) != 1:
        raise ValueError(
            f"the registry has {len(matches)} decode records for {precision}/{cache} without cluster_partitions; one is expected"
        )
    return matches[0]


def decode_partitions(
    capacity: int, partition_tokens: int | None = None
) -> tuple[int, int]:
    """``(partitions, partition_tokens)`` of a D128 decode launch over a cache of
    ``capacity`` keys: the partition length is the caller's, else the record's
    default, and must be a positive multiple of ``PARTITION_UNIT`` fitting
    uint32; the count is ``ceil(capacity / partition_tokens)``."""
    if capacity < 1:
        raise ValueError("capacity must be positive")
    tokens = DEFAULT_PARTITION_TOKENS if partition_tokens is None else partition_tokens
    if (
        type(tokens) is not int
        or not 0 < tokens <= (1 << 32) - 1
        or tokens % PARTITION_UNIT
    ):
        raise ValueError(
            f"partition_tokens must fit uint32 and be a positive multiple of {PARTITION_UNIT}"
        )
    return -(-int(capacity) // tokens), tokens


def launch_grid(
    name: str,
    *,
    num_kv_heads: int,
    batch: int,
    q_len: int | None = None,
    partitions: int | None = None,
) -> tuple[int, int, int]:
    """The launch grid of record ``name``: under its ``tree`` grid rule
    ``(ctas_per_tile * tiles_per_cluster, Hkv * q_tiles / tiles_per_cluster, B)``
    of ``q_len`` draft tokens (the pair schedule covers two Q tiles per cluster,
    so it needs an even tile count per KV head); under its ``decode_partitions``
    rule ``(partitions, Hkv, B)`` (:func:`decode_partitions`)."""
    record = MODULES[name]
    rule = record["grid_rule"]
    if rule["kind"] == "tree":
        if q_len is None:
            raise ValueError(f"record {name}: a tree launch needs q_len")
        tiles = q_tiles(q_len, record["variant"]["ratio"])
        per_cluster = int(rule["tiles_per_cluster"])
        if tiles % per_cluster:
            raise ValueError(
                f"record {name}: {tiles} Q tiles per KV head is not a multiple of {per_cluster}"
            )
        return (
            int(rule["ctas_per_tile"]) * per_cluster,
            int(num_kv_heads) * (tiles // per_cluster),
            int(batch),
        )
    if rule["kind"] == "decode_partitions":
        if partitions is None or isinstance(partitions, bool) or int(partitions) < 1:
            raise ValueError(
                f"record {name}: a decode launch needs a positive partitions count"
            )
        # A cluster program covers one (request, KV head) per cluster of its
        # ``cluster_partitions`` CTAs along x; its grid.x is that count.
        clustered = record["variant"].get("cluster_partitions")
        if clustered not in (None, 1) and int(partitions) != int(clustered):
            raise ValueError(
                f"record {name}: its cluster merges exactly {clustered} partitions, got {partitions}"
            )
        return (int(partitions), int(num_kv_heads), int(batch))
    raise ValueError(f"unknown Cake SM110 XQA grid rule: {rule['kind']!r}")


def arch_for_capability(capability: tuple[int, int]) -> str | None:
    """The exported architecture of one device capability, if any."""
    values = tuple(int(value) for value in capability)
    if len(values) != 2:
        return None
    return ARCH_BY_CAPABILITY.get((values[0], values[1]))


def device_arch(device_index: int) -> str:
    """Exported architecture of one CUDA device (``RuntimeError`` when the device
    is not an exported target)."""
    import torch

    capability = tuple(torch.cuda.get_device_capability(device_index))
    arch = arch_for_capability(capability)
    if arch is None:
        raise RuntimeError(
            f"device {device_index} (capability {capability}) is not an exported "
            f"Cake SM110 XQA target; the exported architectures are {ARCHES}"
        )
    return arch


def library_name(name: str, arch: str) -> str:
    """``build.json`` library of record ``name`` built for ``arch``: ``<library>_<arch>``."""
    record = MODULES[name]
    if arch not in record["arches"]:
        raise RuntimeError(
            f"Cake SM110 XQA record {name} is not delivered for {arch}; its architectures: {record['arches']}"
        )
    return f"{record['library']}_{arch}"


@functools.cache
def load(name: str, arch: str) -> Any:
    """The loaded tvm-ffi module of record ``name`` built for ``arch``: the
    prebuilt ``aot/`` library when a builder compiled it, else FlashInfer's JIT
    build of the same sources and flags (``cake_build.load_library``)."""
    return cake_build.load_library(library_name(name, arch))


@functools.cache
def _argument_plan(name: str) -> tuple[tuple[str | None, int], ...]:
    """The record's plan as ``(logical name, -1)`` per kernel parameter and
    ``(None, axis)`` per grid argument, in ``run`` order; computed once."""
    record = MODULES[name]
    logical = record["logical"]
    plan: list[tuple[str | None, int]] = []
    for kind, key in record["arg_plan"]:
        if kind == "grid":
            plan.append((None, "xyz".index(key[-1])))
        else:
            if key not in logical:
                raise ValueError(
                    f"record {name}: kernel parameter {key!r} has no logical name"
                )
            plan.append((logical[key], -1))
    return tuple(plan)


def argument_list(
    name: str, values: dict[str, Any], *, grid: tuple[int, int, int]
) -> list[Any]:
    """The positional arguments of record ``name``'s ``run`` entry: ``values``
    (logical name -> tensor or Python scalar) in the plan's order, the three
    grid extents in place.  Bound once at prepare time so a replay interprets
    no plan."""
    args: list[Any] = []
    for logical_name, axis in _argument_plan(name):
        if logical_name is None:
            args.append(int(grid[axis]))
        else:
            try:
                args.append(values[logical_name])
            except KeyError:
                raise ValueError(
                    f"record {name} needs logical argument {logical_name!r}"
                ) from None
    return args


def entry(name: str, device_index: int) -> Any:
    """The ``run`` entry of record ``name`` for the device's architecture."""
    return getattr(load(name, device_arch(device_index)), MODULES[name]["ffi_entry"])


