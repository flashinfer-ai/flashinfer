# Logical argument names the host backend binds; every record maps its kernel
# parameter names onto this vocabulary (``record["logical"]``).  ``Q`` and
# ``KV`` (``KVV``: the pair schedule's second view of the same cache) are the
# TMA descriptor sources: Q as ``[B * Q, Hq, 512]`` FP16, an E4M3 cache as its
# bytes.  The by-value cache record is bound member by member under dotted
# names: ``kv_cache_list.data`` / ``.sequence_lengths`` / ``.capacity`` for a
# contiguous cache, ``kv_cache_list.pool`` / ``.page_list`` /
# ``.sequence_lengths`` / ``.max_pages`` for 128-token pages.  The decode
# record binds ``Q`` as ``[B, Hkv, ratio, 128]``, ``KV`` as the contiguous cache
# ``[B, 2, Hkv, capacity, 128]``, the ``sequence_lengths`` int32 ``[B]``, the
# workspace ``partial`` / ``statistics`` / ``counters`` and the scalars
# ``heads`` (Hkv), ``ratio``, ``capacity``, ``partitions``, ``partition_tokens``
# and ``attention_scale``.
