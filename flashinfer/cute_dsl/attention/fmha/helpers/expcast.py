"""Direct approximate exp2-to-E4M3 encoding for FP8 PV attention.

Adapted from HAO's expcast_helpers.py (FlashAttention, BSD-3-Clause).
For base-2 scores x, encode round(8*x + 56 - 0.35) into positive E4M3
bytes. This is an approximation to exp2, not an FP8 conversion of exp2(x).
Decode the exact generated bytes for the denominator so numerator and
normalizer use the same weights. QK precision is independent of this mapping.
"""

import cutlass.cute as cute
from cutlass import Float32, Int32, Constexpr, const_expr
from cutlass.cutlass_dsl import T
from cutlass._mlir.dialects import llvm

# Paired mapping and saturating byte packing. Native E4M3 -> FP16 -> FP32
# conversion is exact, including zero/subnormals, and avoids integer decoding.
_CLAMPED_ASM = """
{
    .reg .f32 f0,f1,f2,f3;
    .reg .b32 c0,c1,c2,c3,packed;
    .reg .b64 pair,scale_pair,bias_pair;
    mov.b64 scale_pair, 0x4100000041000000;
    mov.b64 bias_pair, {$9, $9};
    mov.b64 pair, {$5, $6};
    fma.rn.f32x2 pair, pair, scale_pair, bias_pair;
    mov.b64 {f0, f1}, pair;
    mov.b64 pair, {$7, $8};
    fma.rn.f32x2 pair, pair, scale_pair, bias_pair;
    mov.b64 {f2, f3}, pair;
    max.f32 f0, f0, 0f00000000;
    min.f32 f0, f0, $10;
    cvt.rni.s32.f32 c0, f0;
    max.f32 f1, f1, 0f00000000;
    min.f32 f1, f1, $10;
    cvt.rni.s32.f32 c1, f1;
    max.f32 f2, f2, 0f00000000;
    min.f32 f2, f2, $10;
    cvt.rni.s32.f32 c2, f2;
    max.f32 f3, f3, 0f00000000;
    min.f32 f3, f3, $10;
    cvt.rni.s32.f32 c3, f3;
    cvt.pack.sat.u8.s32.b32 packed, c3, c2, 0;
    cvt.pack.sat.u8.s32.b32 packed, c1, c0, packed;
    {
        .reg .b32 native_source,half01,half23;
        .reg .b16 byte01,byte23,h0,h1,h2,h3;
        mov.b32 native_source, packed;
        mov.b32 {byte01,byte23}, native_source;
        cvt.rn.f16x2.e4m3x2 half01, byte01;
        cvt.rn.f16x2.e4m3x2 half23, byte23;
        mov.b32 {h0,h1}, half01;
        mov.b32 {h2,h3}, half23;
        cvt.f32.f16 $1, h0;
        cvt.f32.f16 $2, h1;
        cvt.f32.f16 $3, h2;
        cvt.f32.f16 $4, h3;
    }
    mov.b32 $0, packed;
}
"""

_UNCLAMPED_ASM = """
{
    .reg .f32 f0,f1,f2,f3;
    .reg .b32 c0,c1,c2,c3,packed;
    .reg .b64 pair,scale_pair,bias_pair;
    mov.b64 scale_pair, 0x4100000041000000;
    mov.b64 bias_pair, {$9, $9};
    mov.b64 pair, {$5, $6};
    fma.rn.f32x2 pair, pair, scale_pair, bias_pair;
    mov.b64 {f0, f1}, pair;
    mov.b64 pair, {$7, $8};
    fma.rn.f32x2 pair, pair, scale_pair, bias_pair;
    mov.b64 {f2, f3}, pair;
    cvt.rni.s32.f32 c0, f0;
    cvt.rni.s32.f32 c1, f1;
    cvt.rni.s32.f32 c2, f2;
    cvt.rni.s32.f32 c3, f3;
    cvt.pack.sat.u8.s32.b32 packed, c3, c2, 0;
    cvt.pack.sat.u8.s32.b32 packed, c1, c0, packed;
    {
        .reg .b32 native_source,half01,half23;
        .reg .b16 byte01,byte23,h0,h1,h2,h3;
        mov.b32 native_source, packed;
        mov.b32 {byte01,byte23}, native_source;
        cvt.rn.f16x2.e4m3x2 half01, byte01;
        cvt.rn.f16x2.e4m3x2 half23, byte23;
        mov.b32 {h0,h1}, half01;
        mov.b32 {h2,h3}, half23;
        cvt.f32.f16 $1, h0;
        cvt.f32.f16 $2, h1;
        cvt.f32.f16 $3, h2;
        cvt.f32.f16 $4, h3;
    }
    mov.b32 $0, packed;
}
"""


@cute.jit
def expcast_pack_decode4(
    x0: Float32,
    x1: Float32,
    x2: Float32,
    x3: Float32,
    *,
    remove_clamps: Constexpr[bool] = False,
    loc=None,
    ip=None,
) -> tuple[Int32, Float32, Float32, Float32, Float32]:
    """Return four E4M3 bytes and their exact FP32 values.

    Clamp removal requires the caller to prove round(8*x + 55.65) <= 126.
    Saturating packing supplies zero for negative codes, including masked -inf.
    """
    selected = _UNCLAMPED_ASM if const_expr(remove_clamps) else _CLAMPED_ASM
    result = llvm.inline_asm(
        llvm.StructType.get_literal([T.i32(), T.f32(), T.f32(), T.f32(), T.f32()]),
        [Float32(x).ir_value(loc=loc, ip=ip) for x in (x0, x1, x2, x3, 55.65, 126.0)],
        selected,
        "=r,=f,=f,=f,=f,f,f,f,f,f,f",
        has_side_effects=False,
        is_align_stack=False,
        asm_dialect=llvm.AsmDialect.AD_ATT,
    )
    return (
        Int32(llvm.extractvalue(T.i32(), result, [0], loc=loc, ip=ip)),
        Float32(llvm.extractvalue(T.f32(), result, [1], loc=loc, ip=ip)),
        Float32(llvm.extractvalue(T.f32(), result, [2], loc=loc, ip=ip)),
        Float32(llvm.extractvalue(T.f32(), result, [3], loc=loc, ip=ip)),
        Float32(llvm.extractvalue(T.f32(), result, [4], loc=loc, ip=ip)),
    )
