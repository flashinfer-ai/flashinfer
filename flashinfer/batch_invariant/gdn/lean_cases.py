"""Generate ``lean/BIKernels/GdnCases.lean`` from the Python side: the arithmetic of the class ``gdn.bf16.c64``
(:mod:`.spec`) on a set of positions (chunk boundaries, their neighbours, a long position and the last chunk of a
4096-token sequence) and of calls appending tokens to an open chunk, pinned in Lean by kernel ``decide`` against the
model of ``Gdn.lean``. No ``native_decide``: the file adds nothing to the axiom policy.

    python -m flashinfer.batch_invariant.gdn.lean_cases     # rewrite lean/BIKernels/GdnCases.lean
"""

from __future__ import annotations

import os
from typing import List, Tuple

from . import spec

LEAN_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lean"
)
CASES_PATH = os.path.join(LEAN_DIR, "BIKernels", "GdnCases.lean")

POSITIONS = [0, 1, 63, 64, 65, 127, 128, 129, 1000, 4031, 4032, 4095, 4096, 32767]
#: ``(open rows, tokens appended)``: decode steps, both sides of the placement rule, calls that cross a boundary.
EXTENDS = [
    (0, 1),
    (62, 1),
    (63, 1),
    (0, 15),
    (0, 16),
    (60, 8),
    (32, 32),
    (63, 64),
    (5, 200),
    (0, 4096),
    (17, 4079),
]


def cases() -> List[Tuple[int, int, int, bool]]:
    return [
        (p, spec.boundary(p), spec.phase(p), spec.commits(spec.phase(p)))
        for p in POSITIONS
    ]


def extend_cases() -> List[Tuple[int, int, int, int, bool]]:
    return spec.extend_cases(EXTENDS)


def conformance_lines() -> List[str]:
    """What ``lake exe gdnconformance`` prints, from the Python specification."""
    lines = [
        f"gdn {p} boundary {b} phase {n} commit {str(c).lower()}"
        for p, b, n, c in cases()
    ]
    lines += [
        f"gdnextend {c} {n} whole {w} tail {t} step {str(s).lower()}"
        for c, n, w, t, s in extend_cases()
    ]
    return lines


def _rows(rows: List[str]) -> List[str]:
    return [f"  {r}{',' if i + 1 < len(rows) else ''}" for i, r in enumerate(rows)]


def render() -> str:
    L = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by python -m flashinfer.batch_invariant.gdn.lean_cases; do not edit.",
        "import BIKernels.Gdn",
        "namespace BIK",
        "",
        "/-- `(position, boundary, phase, commits)` of the Python specification (`gdn/spec.py`). -/",
        "def gdnCases : List (Nat × Nat × Nat × Bool) := [",
    ]
    L += _rows([f"({p}, {b}, {n}, {str(c).lower()})" for p, b, n, c in cases()])
    L += [
        "]",
        "",
        "/-- `(open rows, tokens, whole, tail, step kernel)` of a call that appends tokens to an open chunk. -/",
        "def gdnExtendCases : List (Nat × Nat × Nat × Nat × Bool) := [",
    ]
    L += _rows(
        [f"({c}, {n}, {w}, {t}, {str(s).lower()})" for c, n, w, t, s in extend_cases()]
    )
    L += [
        "]",
        "",
        "theorem gdn_cases_ok : gdnCases.all (fun c =>",
        "    Gdn.boundary c.1 == c.2.1 && Gdn.phase c.1 == c.2.2.1 && Gdn.commits c.2.2.1 == c.2.2.2) = true := by",
        "  decide",
        "",
        "theorem gdn_extend_cases_ok : gdnExtendCases.all (fun c =>",
        "    (Gdn.extendSplit c.1 c.2.1).1 == c.2.2.1 && (Gdn.extendSplit c.1 c.2.1).2 == c.2.2.2.1",
        "      && Gdn.usesStepKernel c.2.1 == c.2.2.2.2) = true := by",
        "  decide",
        "",
        "end BIK",
        "",
    ]
    return "\n".join(L)


def main(out_path: str = CASES_PATH) -> str:
    text = render()
    with open(out_path, "w") as f:
        f.write(text)
    return out_path


if __name__ == "__main__":
    print(main())
