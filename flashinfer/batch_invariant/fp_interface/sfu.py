"""The two hardware special-function primitives of the fp4 MoE classes' activation chains, and their CPU model.

``ex2.approx.ftz.f32`` and ``rcp.approx.ftz.f32`` (MUFU.EX2 / MUFU.RCP) are deterministic functions of their binary32 input
on one architecture, with results PTX leaves implementation-specific. The CPU model takes them as data: on each part the
device evaluates ``ex2`` over every fraction ``j / 2^23`` of ``[0, 1)`` and ``rcp`` over every significand ``1 + j / 2^23``
of ``[1, 2)``, and the model composes the result from the table entry and an exact exponent shift (``ex2(n + f) = 2^n ex2(f)``,
``rcp(2^e m) = 2^-e rcp(m)``), with the flush-to-zero and the special values as the instructions define them. Whether the
shift is exact on a part is itself tested against the device (:func:`check_model`); the tables are regenerated by
:func:`dump_tables` on the part the tests run on (too large to check in) and pinned by their digest in the test data.
"""

from __future__ import annotations

import hashlib
from typing import Callable, Dict, Optional, Tuple

import cutlass
import cutlass.cute as cute
import torch
from cutlass import Float32, Int64
from .cute import ex2_approx_ftz, rcp_approx_ftz

__all__ = [
    "FRACTION_BITS",
    "SfuTables",
    "check_model",
    "dump_tables",
    "ex2_hw",
    "rcp_approx_ftz",
    "rcp_hw",
    "tables_for",
]

#: Binary32 significand bits: the tables index the fraction / significand field.
FRACTION_BITS = 23
_N = 1 << FRACTION_BITS
#: The smallest normal exponent: results below 2^-126 flush to +0 (ftz).
_FLT_MIN_EXP = -126


class SfuEvalKernel:
    """``y[i] = f(x[i])`` for ``f`` the exponential (``which = 0``) or the reciprocal (``which = 1``): one thread per element."""

    THREADS = 256

    def __init__(self, which: int):
        assert which in (0, 1), which
        self.which = which

    @cute.jit
    def __call__(self, mX: cute.Tensor, mY: cute.Tensor, n: Int64, stream):
        self.kernel(mX, mY, n).launch(
            grid=[cute.ceil_div(n, self.THREADS), 1, 1],
            block=[self.THREADS, 1, 1],
            stream=stream,
        )

    @cute.kernel
    def kernel(self, mX: cute.Tensor, mY: cute.Tensor, n: Int64):
        tidx, _, _ = cute.arch.thread_idx()
        bidx, _, _ = cute.arch.block_idx()
        i = bidx.to(Int64) * Int64(self.THREADS) + tidx.to(Int64)
        if i < n:
            x = mX[i]
            if cutlass.const_expr(self.which == 0):
                mY[i] = ex2_approx_ftz(x)
            else:
                mY[i] = rcp_approx_ftz(x)


_KERNELS: Dict[Tuple[int, str], Callable[..., None]] = {}


def _kernel_key(which: int, device: torch.device) -> Tuple[int, str]:
    """The in-process key of an evaluation kernel: the primitive and the device's architecture family (the compiled object
    is the family's, as :func:`tables_for` keys the tables), so one process evaluating two parts never reuses the other
    part's callable."""
    from ...gemm.batch_invariant.api import part_of

    return which, part_of(device)[1]


def _kernel(which: int, device: torch.device) -> Callable[..., None]:
    """The evaluation kernel of the primitive ``which`` for ``device``'s architecture family, built and loaded with
    ``device`` current: the JIT cache's artifact directory and the compiled object's target are the current device's
    (:mod:`flashinfer.jit.cute_dsl_core`), so a tensor on a device that is not current never files the current device's
    object under its own family's key."""
    from ..jit import build_and_load

    key = _kernel_key(which, device)
    kernel = _KERNELS.get(key)
    if kernel is None:
        name = "sfu_ex2" if which == 0 else "sfu_rcp"

        def compile_fn():
            k = SfuEvalKernel(which)
            fx = cute.runtime.make_fake_tensor(
                Float32, (cute.sym_int(64),), (1,), assumed_align=16
            )
            fy = cute.runtime.make_fake_tensor(
                Float32, (cute.sym_int(64),), (1,), assumed_align=16
            )
            return cute.compile(
                k,
                fx,
                fy,
                Int64(1),
                cute.runtime.make_fake_stream(use_tvm_ffi_env_stream=True),
                options="--enable-tvm-ffi",
            )

        with torch.cuda.device(device):
            kernel = _KERNELS[key] = build_and_load(
                "batch_invariant_sfu", name, compile_fn
            )
    return kernel


def _eval(which: int, x: torch.Tensor) -> torch.Tensor:
    """The device's ``ex2`` (0) or ``rcp`` (1) of every element of the float32 tensor ``x``, its kernel built and launched
    with ``x``'s device current."""
    assert x.dtype == torch.float32 and x.is_cuda and x.is_contiguous(), x
    y = torch.empty_like(x)
    kernel = _kernel(which, x.device)
    with torch.cuda.device(x.device):
        kernel(x.view(-1), y.view(-1), x.numel())
    return y


class SfuTables:
    """The part's two tables (float32, ``2^23`` entries each): ``ex2[j] = ex2(j / 2^23)`` and ``rcp[j] = rcp(1 + j / 2^23)``,
    with the part's architecture name and the tables' digest."""

    def __init__(self, arch: str, ex2: torch.Tensor, rcp: torch.Tensor):
        assert ex2.shape == (_N,) and rcp.shape == (_N,), (ex2.shape, rcp.shape)
        self.arch = arch
        self.ex2 = ex2.to(torch.float32).cpu().contiguous()
        self.rcp = rcp.to(torch.float32).cpu().contiguous()

    @property
    def digest(self) -> str:
        h = hashlib.sha256()
        h.update(self.ex2.view(torch.int32).numpy().tobytes())
        h.update(self.rcp.view(torch.int32).numpy().tobytes())
        return h.hexdigest()[:16]

    def eval(self, op: str, x: float) -> float:
        """The part's ``ex2`` or ``rcp`` of one binary32 value by the CPU model (:func:`ex2_hw` / :func:`rcp_hw`); the term
        evaluators call the bound tables, so this module stays out of the kernel modules' import closure."""
        t = torch.tensor([x], dtype=torch.float32)
        y = ex2_hw(t, self) if op == "ex2" else rcp_hw(t, self)
        return float(y[0].item())


def dump_tables(device: torch.device) -> SfuTables:
    """Evaluate both primitives on the device over their tables' arguments."""
    from ...gemm.batch_invariant.api import part_of

    _, arch = part_of(device)
    j = torch.arange(_N, dtype=torch.int64, device=device)
    frac = (j.to(torch.float64) / float(_N)).to(torch.float32)  # exact: j / 2^23
    # exact: 1 + j / 2^23
    sig = (1.0 + j.to(torch.float64) / float(_N)).to(torch.float32)
    return SfuTables(arch, _eval(0, frac.contiguous()), _eval(1, sig.contiguous()))


_TABLES: Dict[Tuple[int, str], SfuTables] = {}


def tables_for(device: torch.device) -> SfuTables:
    """The tables of ``device``'s part, dumped once per process."""
    from ...gemm.batch_invariant.api import part_of

    index = device.index if device.index is not None else torch.cuda.current_device()
    _, arch = part_of(device)
    key = (index, arch)
    if key not in _TABLES:
        _TABLES[key] = dump_tables(torch.device("cuda", index))
    return _TABLES[key]


def _bits(x: torch.Tensor) -> torch.Tensor:
    return x.contiguous().view(torch.int32)


def ex2_hw(x: torch.Tensor, tables: SfuTables) -> torch.Tensor:
    """The CPU model of ``ex2.approx.ftz.f32``, as the device evaluates it (measured on the part, :func:`check_model`): the
    magnitude ``|x| = i + f`` with ``i`` its integer part and ``q`` its fraction truncated to 23 bits; for ``x >= 0`` the result
    is ``2^i ex2(q)`` from the table at ``q``; for ``x < 0`` with a non-zero fraction it is ``2^(-i-1)`` times the table at the
    one's complement ``2^23 - 1 - q`` (the device's fixed-point fraction of a negative input), and ``2^-i`` exactly when the
    truncated fraction is zero (an integer, or a magnitude below ``2^-23``). Results below the normal range flush to ``+0``, above it they are ``+inf``; ``ex2(NaN)`` is NaN."""
    xd = x.to(torch.float64)
    m = torch.abs(xd)
    i = torch.floor(m)
    q = torch.floor((m - i) * _N).to(torch.int64).clamp_(0, _N - 1)
    neg = xd < 0
    idx = torch.where(neg, (_N - 1) - q, q)
    base = tables.ex2[idx].to(torch.float64)
    expo = torch.where(neg, -i - 1.0, i)
    out = base * torch.pow(2.0, expo.clamp(-200, 200))
    # a negative input whose truncated fraction is zero (an integer, or a magnitude below 2^-23): 2^-i exactly
    exact_neg = neg & (q == 0)
    out = torch.where(exact_neg, torch.pow(2.0, (-i).clamp(-200, 200)), out)
    y = out.to(torch.float32)
    y = torch.where(torch.abs(out) < 2.0**_FLT_MIN_EXP, torch.zeros_like(y), y)
    y = torch.where(torch.isinf(xd) & (xd > 0), torch.full_like(y, float("inf")), y)
    y = torch.where(torch.isinf(xd) & (xd < 0), torch.zeros_like(y), y)
    y = torch.where(torch.isnan(xd), xd.to(torch.float32), y)
    return y


def rcp_hw(x: torch.Tensor, tables: SfuTables) -> torch.Tensor:
    """The CPU model of ``rcp.approx.ftz.f32``: ``x = 2^e m`` with ``m`` the significand in ``[1, 2)``, the result
    ``2^-e rcp(m)`` from the table at ``m``'s index; a subnormal input is a signed zero (its reciprocal a signed infinity),
    results below the normal range flush to a signed zero, ``rcp(+-inf) = +-0``, ``rcp(NaN)`` is NaN."""
    b = _bits(x)
    sign = (b >> 31) & 1
    exp = (b >> 23) & 0xFF
    man = b & 0x7FFFFF
    is_nan = (exp == 255) & (man != 0)
    is_inf = (exp == 255) & (man == 0)
    is_zero_or_sub = exp == 0  # ftz: subnormal inputs are zeros
    e = (exp - 127).to(torch.int64)
    base = tables.rcp[man.to(torch.int64)].to(torch.float64)
    out = base * torch.pow(2.0, (-e).clamp(-200, 200).to(torch.float64))
    y = out.to(torch.float32)
    y = torch.where(torch.abs(out) < 2.0**_FLT_MIN_EXP, torch.zeros_like(y), y)
    y = torch.where(is_zero_or_sub, torch.full_like(y, float("inf")), y)
    y = torch.where(is_inf, torch.zeros_like(y), y)
    y = torch.where(sign == 1, -y, y)
    y = torch.where(is_nan, x, y)
    return y


def check_model(
    device: torch.device,
    n: int = 1 << 22,
    seed: int = 0,
    tables: Optional[SfuTables] = None,
) -> Dict[str, int]:
    """The device's primitives against the CPU model over ``n`` random binary32 inputs of every exponent (the finite
    non-NaN patterns), plus the special values: the number of mismatching bit patterns per primitive (0 = the model is the
    part's function)."""
    tables = tables or tables_for(device)
    g = torch.Generator().manual_seed(seed)
    bits = torch.randint(-(2**31), 2**31 - 1, (n,), dtype=torch.int64, generator=g).to(
        torch.int32
    )
    x = bits.view(torch.float32)
    x = torch.where(torch.isnan(x), torch.ones_like(x), x)
    special = torch.tensor(
        [
            0.0,
            -0.0,
            1.0,
            -1.0,
            -2.0,
            -3.0,
            -7.0,
            0.5,
            -0.5,
            2.0,
            127.5,
            -126.0,
            -127.0,
            -149.0,
            -150.0,
            128.0,
            127.0,
            1e-40,
            -1e-40,
            1e-30,
            -1e-30,
            0.3,
            -0.3,
            float("inf"),
            -float("inf"),
            float("nan"),
        ],
        dtype=torch.float32,
    )
    x = torch.cat([x, special])
    xd = x.to(device).contiguous()
    out = {}
    for which, model in ((0, ex2_hw), (1, rcp_hw)):
        dev = _eval(which, xd).cpu()
        cpu = model(x, tables)
        same = _bits(dev) == _bits(cpu)
        both_nan = torch.isnan(dev) & torch.isnan(cpu)
        out["ex2" if which == 0 else "rcp"] = int((~(same | both_nan)).sum().item())
    return out
