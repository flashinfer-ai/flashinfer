"""Generate ``lean/BIKernels/KdaCases.lean`` from the Python side: the replay arithmetic of the class ``kda.bf16.c16``
(:mod:`.spec`) on a set of positions (chunk boundaries, their neighbours, a long position and the chunk before it) and the
pool's count transitions, pinned in Lean by kernel ``decide`` against the model of ``Kda.lean``. No ``native_decide``:
the file adds nothing to the axiom policy.

    python -m flashinfer.batch_invariant.kda.lean_cases     # rewrite lean/BIKernels/KdaCases.lean
"""

from __future__ import annotations

import os
from typing import List, Tuple

from . import spec

LEAN_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lean"
)
CASES_PATH = os.path.join(LEAN_DIR, "BIKernels", "KdaCases.lean")

#: The positions: the first chunk, both sides of the first two boundaries, a long position and the last chunk of a
#: 4096-token sequence.
POSITIONS = [0, 1, 15, 16, 17, 31, 32, 33, 1000, 4079, 4080, 4095, 4096]
COUNTS = list(range(spec.CHUNK))


def cases() -> List[Tuple[int, int, int, bool]]:
    return spec.replay_cases(POSITIONS)


def count_cases() -> List[Tuple[int, int]]:
    return [(c, spec.next_count(c)) for c in COUNTS]


def conformance_lines() -> List[str]:
    """What ``lake exe kdaconformance`` prints, from the Python specification."""
    lines = [
        f"kda {p} boundary {b} hist {n} commit {str(c).lower()}"
        for p, b, n, c in cases()
    ]
    lines += [f"kdacount {c} next {n}" for c, n in count_cases()]
    return lines


def render() -> str:
    L = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by python -m flashinfer.batch_invariant.kda.lean_cases; do not edit.",
        "import BIKernels.Kda",
        "namespace BIK",
        "",
        "/-- `(position, boundary, history length, commits)` of the Python specification (`kda/spec.py`). -/",
        "def kdaCases : List (Nat × Nat × Nat × Bool) := [",
    ]
    L += [
        f"  ({p}, {b}, {n}, {str(c).lower()}){',' if i + 1 < len(cases()) else ''}"
        for i, (p, b, n, c) in enumerate(cases())
    ]
    L += [
        "]",
        "",
        "/-- `(count, next count)` of the pool's append rule. -/",
        "def kdaCountCases : List (Nat × Nat) := [",
    ]
    cc = count_cases()
    L += [
        f"  ({c}, {n}){',' if i + 1 < len(cc) else ''}" for i, (c, n) in enumerate(cc)
    ]
    L += [
        "]",
        "",
        "theorem kda_cases_ok : kdaCases.all (fun c =>",
        "    Kda.boundary c.1 == c.2.1 && Kda.historyLen c.1 == c.2.2.1 && Kda.commits c.2.2.1 == c.2.2.2) = true := by",
        "  decide",
        "",
        "theorem kda_count_cases_ok : kdaCountCases.all (fun c => Kda.nextCount c.1 == c.2) = true := by",
        "  decide",
        "",
        "end BIK",
        "",
    ]
    return "\n".join(L)


def main(out_path: str = CASES_PATH) -> str:
    text = render()
    with open(out_path, "w") as f:
        f.write(text)
    return out_path


if __name__ == "__main__":
    print(main())
