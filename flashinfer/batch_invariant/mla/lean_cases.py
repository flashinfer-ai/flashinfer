"""Generate ``lean/BIKernels/MlaSparseCases.lean`` from the Python side, and the Python mirror of the placements.

The cases are the tile arithmetic of the classes ``mla.sparse.*`` (:mod:`.spec`) on a set of live lengths (empty, one
key, both sides of the first tile edges, the GLM-5.3 width and the GLM-5.3-Flash tail widths), pinned in Lean by kernel
``decide`` against the model of ``MlaSparse.lean``. No ``native_decide``: the file adds nothing to the axiom policy.

    python -m flashinfer.batch_invariant.mla.lean_cases     # rewrite lean/BIKernels/MlaSparseCases.lean
"""

from __future__ import annotations

import os
from typing import Callable, List, Sequence, Tuple

from . import spec

LEAN_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lean"
)
CASES_PATH = os.path.join(LEAN_DIR, "BIKernels", "MlaSparseCases.lean")

LENGTHS = [
    0,
    1,
    2,
    127,
    128,
    129,
    255,
    256,
    257,
    300,
    2047,
    2048,
    2049,
    2050,
    2051,
    2052,
    4096,
]


def last_live(length: int) -> int:
    """Live keys in the row's last tile (0 for an empty list)."""
    return length - spec.KEY_TILE * max(spec.key_tiles(length) - 1, 0)


def cases() -> List[Tuple[int, int, int]]:
    return [(n, spec.key_tiles(n), last_live(n)) for n in LENGTHS]


def conformance_lines() -> List[str]:
    """What ``lake exe mlasparseconformance`` prints, from the Python specification."""
    return [f"mlasparse {n} tiles {t} last {l}" for n, t, l in cases()]


# Python mirror of the Lean placements, for reading next to ``MlaSparse.lean``; it is not evidence about the kernel.
Row = Tuple[object, Sequence[object]]
Term = Callable[[object, Sequence[object]], object]


def place_decode(term: Term, row: Row):
    """A one-row decode call (``call_single``)."""
    return term(*row)


def place_batch(term: Term, rows: Sequence[Row]) -> list:
    """One call with one query token per request, in the caller's order (``call``)."""
    return [term(*row) for row in rows]


def place_prefill(term: Term, rows: Sequence[Row]) -> list:
    """One request whose query tokens are the rows (``call``)."""
    return place_batch(term, rows)


def place_chunked(term: Term, rows: Sequence[Row], sizes: Sequence[int]) -> list:
    """The prefill cut into consecutive calls of the given sizes (``chunked_eq_call``)."""
    out, start = [], 0
    for size in sizes:
        out += place_batch(term, rows[start : start + size])
        start += size
    return out


def place_mtp(term: Term, requests: Sequence[Sequence[Row]]) -> list:
    """Several query tokens per request (``grouped_eq_call``)."""
    return [place_batch(term, rows) for rows in requests]


def render() -> str:
    L = [
        "-- Copyright (c) 2026 by FlashInfer team.",
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- GENERATED by python -m flashinfer.batch_invariant.mla.lean_cases; do not edit.",
        "import BIKernels.MlaSparse",
        "namespace BIK",
        "",
        "/-- `(live length, key tiles, live keys of the last tile)` of the Python specification (`mla/spec.py`). -/",
        "def mlaSparseCases : List (Nat × Nat × Nat) := [",
    ]
    cc = cases()
    L += [
        f"  ({n}, {t}, {l}){',' if i + 1 < len(cc) else ''}"
        for i, (n, t, l) in enumerate(cc)
    ]
    L += [
        "]",
        "",
        "theorem mla_sparse_cases_ok : mlaSparseCases.all (fun c =>",
        "    MlaSparse.keyTiles c.1 == c.2.1 && MlaSparse.lastLive c.1 == c.2.2) = true := by",
        "  decide +kernel",
        "",
        "end BIK",
        "",
    ]
    return "\n".join(L)


def main(out_path: str = CASES_PATH) -> str:
    text = render()
    with open(out_path, "w") as f:
        f.write(text)
    return out_path


if __name__ == "__main__":
    print(main())
