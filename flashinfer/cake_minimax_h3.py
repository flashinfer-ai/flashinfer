class MiniMaxH3QkvQuantizePack:
    """Prepare and run the one-pass MiniMax-H3 QKV quantize-and-pack helper.

    BF16 ``q``, ``k``, ``v`` ``[M, 56, 128]`` (contiguous, or the kind slices
    of one ``[M, 56, 3, 128]`` projection output) are routed into the
    destination-major Ulysses send buffer ``[P, M, 56 / P, 3, 128]`` and
    quantized per destination in one HBM pass, producing byte for byte the
    ``(out_q, out_sf)`` send-buffer layout of
    :class:`MiniMaxH3Nvfp4PreAttention` (``format="nvfp4"``) or
    :class:`MiniMaxH3Mxfp8PreAttention` (``format="mxfp8"``), including the
    zero scale-tile padding rows.

    All outputs are supplied by the caller. Preparation resolves the exact
    SM100a or SM103a route for ``(P, format)``. :meth:`run` launches one
    kernel, performs no tensor allocation and no host-side clears, and can be
    captured by a CUDA Graph after preparation.

    The tensors passed to :meth:`run` must be the same objects supplied here.
    Their contents may be updated between launches, including on independent
    CUDA streams.
    """

    def __init__(
        self,
        *,
        q: torch.Tensor,
        k: torch.Tensor,
        v: torch.Tensor,
        out_q: torch.Tensor,
        out_sf: torch.Tensor,
        P: int,
        format: str,
        out_global_scale: Optional[torch.Tensor] = None,
    ) -> None:
        # Generated by the exact-architecture export. Keep the import lazy so
        # source-only tooling can import the stable API before CUDA artifacts
        # are materialized.
        from .diffusion_ops.cake_minimax_h3_qkv_pack import (
            prepare_minimax_h3_qkv_quantize_pack,
        )

        self._bound_tensors = {
            "q": q,
            "k": k,
            "v": v,
            "out_global_scale": out_global_scale,
            "out_q": out_q,
            "out_sf": out_sf,
        }
        self._prepared = prepare_minimax_h3_qkv_quantize_pack(
            q=q,
            k=k,
            v=v,
            out_q=out_q,
            out_sf=out_sf,
            P=P,
            format=format,
            out_global_scale=out_global_scale,
        )

    @property
    def format(self) -> str:
        return self._prepared.format

    @flashinfer_api(trace=minimax_h3_qkv_quantize_pack_trace)
    def run(
        self,
        *,
        q: torch.Tensor,
        k: torch.Tensor,
        v: torch.Tensor,
        out_q: torch.Tensor,
        out_sf: torch.Tensor,
        out_global_scale: Optional[torch.Tensor] = None,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Run the prepared pack into the caller-owned output tensors.

        Parameters
        ----------
        q, k, v : torch.Tensor
            BF16 sources with shape ``[M, 56, 128]`` sharing the same token
            and head strides (contiguous head_dim, 32-byte aligned rows).
        out_q : torch.Tensor
            Caller-owned packed values: uint8 E2M1 nibble pairs with shape
            ``[P, M, 56 / P, 3, 64]`` (``nvfp4``) or float8_e4m3fn with shape
            ``[P, M, 56 / P, 3, 128]`` (``mxfp8``).
        out_sf : torch.Tensor
            Caller-owned per-destination swizzled-128x4 uint8 scale tile with
            shape ``[P, round_up(M * (56 / P) * 3, 128) * C]`` where ``C`` is
            8 (E4M3, ``nvfp4``) or 4 (UE8M0, ``mxfp8``).
        out_global_scale : torch.Tensor, optional
            Float32 static NVFP4 global encode scale ``(448 * 6) / amax`` with
            shape ``[1]``; required for ``nvfp4`` and absent for ``mxfp8``.

        Returns
        -------
        tuple[torch.Tensor, torch.Tensor]
            The same ``(out_q, out_sf)`` objects supplied by the caller.

        Notes
        -----
        Every tensor must be the same object passed when constructing this
        prepared operation; rebinding any tensor requires a new instance.
        """

        current = {
            "q": q,
            "k": k,
            "v": v,
            "out_global_scale": out_global_scale,
            "out_q": out_q,
            "out_sf": out_sf,
        }
        rebound = [
            name
            for name, value in current.items()
            if value is not self._bound_tensors[name]
        ]
        if rebound:
            raise ValueError(
                "MiniMax-H3 prepared tensors cannot be rebound; prepare a new "
                f"instance for: {', '.join(rebound)}"
            )
        result = self._prepared()
        if result[0] is not out_q or result[1] is not out_sf:
            raise RuntimeError(
                "MiniMax-H3 prepared route replaced caller-owned outputs"
            )
        return result

    __call__ = run


