class MiniMaxH3Mxfp8PreAttention:
    """Prepare and run the fixed MiniMax-H3 MXFP8 pre-attention pipeline.

    All outputs, intermediate tensors, and workspaces are supplied by the
    caller. Preparation resolves the exact SM100a or SM103a route and selects
    the CUTLASS MXFP8 GEMM tactic. :meth:`run` performs no tensor allocation and
    can be captured by a CUDA Graph after preparation.

    The tensors passed to :meth:`run` must be the same objects supplied here.
    Their contents may be updated between launches, including on independent
    CUDA streams.
    """

    def __init__(
        self,
        *,
        x: torch.Tensor,
        x_norm_weight: torch.Tensor,
        adaln_scale: torch.Tensor,
        adaln_shift: torch.Tensor,
        adaln_index: torch.Tensor,
        qkv_weight_q: torch.Tensor,
        qkv_weight_sf: torch.Tensor,
        q_norm_weight: torch.Tensor,
        k_norm_weight: torch.Tensor,
        rope_cos_sin: torch.Tensor,
        out_q: torch.Tensor,
        out_sf: torch.Tensor,
        activation_q: torch.Tensor,
        activation_sf: torch.Tensor,
        qkv_bf16: torch.Tensor,
        gemm_workspace: torch.Tensor,
        P: int,
        norm_descriptor_workspace: Optional[torch.Tensor] = None,
        post_descriptor_workspace: Optional[torch.Tensor] = None,
        debug_q_bf16: Optional[torch.Tensor] = None,
        debug_k_bf16: Optional[torch.Tensor] = None,
        eps: float = 1.0e-5,
    ) -> None:
        # Generated by the exact-architecture export. Keep the import lazy so
        # source-only tooling can import the stable API before CUDA artifacts
        # are materialized.
        from .diffusion_ops.cake_minimax_h3_mxfp8 import (
            prepare_minimax_h3_mxfp8_pre_attention,
        )

        self._bound_tensors = {
            "x": x,
            "x_norm_weight": x_norm_weight,
            "adaln_scale": adaln_scale,
            "adaln_shift": adaln_shift,
            "adaln_index": adaln_index,
            "qkv_weight_q": qkv_weight_q,
            "qkv_weight_sf": qkv_weight_sf,
            "q_norm_weight": q_norm_weight,
            "k_norm_weight": k_norm_weight,
            "rope_cos_sin": rope_cos_sin,
            "out_q": out_q,
            "out_sf": out_sf,
            "debug_q_bf16": debug_q_bf16,
            "debug_k_bf16": debug_k_bf16,
        }
        self._prepared = prepare_minimax_h3_mxfp8_pre_attention(
            x=x,
            x_norm_weight=x_norm_weight,
            adaln_scale=adaln_scale,
            adaln_shift=adaln_shift,
            adaln_index=adaln_index,
            qkv_weight_q=qkv_weight_q,
            qkv_weight_sf=qkv_weight_sf,
            q_norm_weight=q_norm_weight,
            k_norm_weight=k_norm_weight,
            rope_cos_sin=rope_cos_sin,
            out_q=out_q,
            out_sf=out_sf,
            activation_q=activation_q,
            activation_sf=activation_sf,
            qkv_bf16=qkv_bf16,
            gemm_workspace=gemm_workspace,
            P=P,
            norm_descriptor_workspace=norm_descriptor_workspace,
            post_descriptor_workspace=post_descriptor_workspace,
            debug_q_bf16=debug_q_bf16,
            debug_k_bf16=debug_k_bf16,
            eps=eps,
        )

    @flashinfer_api(trace=minimax_h3_mxfp8_pre_attention_trace)
    def run(
        self,
        *,
        x: torch.Tensor,
        x_norm_weight: torch.Tensor,
        adaln_scale: torch.Tensor,
        adaln_shift: torch.Tensor,
        adaln_index: torch.Tensor,
        qkv_weight_q: torch.Tensor,
        qkv_weight_sf: torch.Tensor,
        q_norm_weight: torch.Tensor,
        k_norm_weight: torch.Tensor,
        rope_cos_sin: torch.Tensor,
        out_q: torch.Tensor,
        out_sf: torch.Tensor,
        debug_q_bf16: Optional[torch.Tensor] = None,
        debug_k_bf16: Optional[torch.Tensor] = None,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Run the prepared pipeline into the caller-owned output tensors.

        Parameters
        ----------
        x : torch.Tensor
            BF16 hidden states with shape ``[M, 5376]``.
        x_norm_weight : torch.Tensor
            BF16 RMSNorm weight with shape ``[5376]``.
        adaln_scale, adaln_shift : torch.Tensor
            BF16 AdaLN scale and shift tables with shape ``[9, 5376]``.
        adaln_index : torch.Tensor
            Contiguous int32 AdaLN row indices with shape ``[M]``.
        qkv_weight_q : torch.Tensor
            E4M3-quantized QKV projection weight with shape ``[21504, 5376]``.
        qkv_weight_sf : torch.Tensor
            Packed uint8 MXFP8 scales for ``qkv_weight_q``.
        q_norm_weight, k_norm_weight : torch.Tensor
            BF16 Q and K RMSNorm weights with shape ``[128]``.
        rope_cos_sin : torch.Tensor
            BF16 split-half NeoX RoPE values with shape ``[M, 96]``.
        out_q : torch.Tensor
            Caller-owned E4M3 output with shape ``[P, M, 56 / P, 3, 128]``.
        out_sf : torch.Tensor
            Caller-owned packed uint8 MXFP8 output scales.
        debug_q_bf16, debug_k_bf16 : torch.Tensor, optional
            Optional caller-owned BF16 Q and K debug outputs. Supply both or
            neither.

        Returns
        -------
        tuple[torch.Tensor, torch.Tensor]
            The same ``(out_q, out_sf)`` objects supplied by the caller.

        Notes
        -----
        Every tensor must be the same object passed when constructing this
        prepared operation; rebinding any tensor requires a new instance.
        """

        current = {
            "x": x,
            "x_norm_weight": x_norm_weight,
            "adaln_scale": adaln_scale,
            "adaln_shift": adaln_shift,
            "adaln_index": adaln_index,
            "qkv_weight_q": qkv_weight_q,
            "qkv_weight_sf": qkv_weight_sf,
            "q_norm_weight": q_norm_weight,
            "k_norm_weight": k_norm_weight,
            "rope_cos_sin": rope_cos_sin,
            "out_q": out_q,
            "out_sf": out_sf,
            "debug_q_bf16": debug_q_bf16,
            "debug_k_bf16": debug_k_bf16,
        }
        rebound = [
            name
            for name, value in current.items()
            if value is not self._bound_tensors[name]
        ]
        if rebound:
            raise ValueError(
                "MiniMax-H3 prepared tensors cannot be rebound; prepare a new "
                f"instance for: {', '.join(rebound)}"
            )
        result = self._prepared()
        if result[0] is not out_q or result[1] is not out_sf:
            raise RuntimeError(
                "MiniMax-H3 prepared route replaced caller-owned outputs"
            )
        return result

    __call__ = run


