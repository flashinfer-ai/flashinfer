"""Guardword checks for NVIDIA contributors.

FlashInfer is public, but NVIDIA contributors also work with names and details
that must not be published. For them, this script runs two checks with NVIDIA's
internal guardword scanner; for everyone else every command returns without
doing anything.

* The push check, a git pre-push hook this script installs, scans what a push
  to GitHub publishes. It is the gate: content becomes public when pushed.
* The commit check, the ``guardwords`` hook in .pre-commit-config.yaml, scans
  staged changes next to the formatters, for earlier feedback.

The pre-commit framework can run pre-push hooks too, but the push check must
not be one: the framework hands its hooks only the first pushed ref with new
commits, so the other branches and tags in a push would go unscanned, and it
runs only what the checked-out branch's .pre-commit-config.yaml lists. The
commit check is only feedback, so those limits are fine for it.

Both hand the commit or push to ``flashinfer_hooks.py`` in the scanner
checkout the way git hands it to a hook; it decides what to scan, and updates
together with the rules. This script recognizes NVIDIA contributors, installs
the push hook, clones the scanner and applies the settings described in
CONTRIBUTING.md.

The scanner is cloned from an internal repository whose location must never
appear in this public repository. Setup asks for it, or reads it from the
FLASHINFER_SCAN_REPO_URL environment variable for unattended setup; afterwards
it is kept only as the origin of the scanner checkout.

Commands:
    setup                one-time setup and tool checks; --non-interactive for
                         agents and automation
    status               report whether the checks protect this checkout
    ensure               install the push hook if this is an NVIDIA contributor
    check-commit         the commit check, run by the pre-commit framework
    pre-push REMOTE URL  the push check, run by the installed pre-push hook
"""

from __future__ import annotations

import argparse
import contextlib
import fcntl
import importlib.util
import ipaddress
import os
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import Iterator

PREFIX = "[guardwords]"
NVIDIA_GITHUB_ORG = "NVIDIA"
# Hostnames listed here are published with the repository. Add one only after
# security review confirms that it may appear in public code.
INTERNAL_HOSTNAMES: tuple[str, ...] = ()

RUNNER = "flashinfer_hooks.py"
HOOK_COPY = "flashinfer_guardword_hooks.py"
LOCK_FILE = "flashinfer-guardwords.lock"
DETECTION_MARKER = "flashinfer-guardwords-checked"
SHIM_MARKER = "flashinfer-guardword-shim"
SCANNER_HOOK_MARKER = "FlashInfer Guardwords Pre-Push Hook"
PRE_COMMIT_MARKER = "File generated by pre-commit"

DETECTION_TTL_S = 24 * 3600
NETWORK_TIMEOUT_S = 60

# The hook runs a copy of this script kept in the git directory, so branches
# that predate the script are protected too.
PUSH_HOOK = f"""#!/bin/sh
# {SHIM_MARKER}: installed by scripts/guardword_hooks.py
hook="$(git rev-parse --git-common-dir)/{HOOK_COPY}"
if [ ! -f "$hook" ]; then
    echo "{PREFIX} $hook is missing; run: python3 scripts/guardword_hooks.py setup" >&2
    exit 1
fi
exec python3 "$hook" pre-push "$@"
"""
# The same, for a core.hooksPath hook that other repositories may share.
HOOKS_PATH_LINE = (
    f'hook="$(git rev-parse --git-common-dir)/{HOOK_COPY}"; '
    '[ ! -f "$hook" ] || python3 "$hook" pre-push "$@" || exit'
)

OPT_OUT_TIP = "Not an NVIDIA contributor: git config --global flashinfer.internal false"
SKIP_TIPS = (
    "Skip once: SKIP=guardwords git commit, or git push --no-verify",
    "Stop scanning commits (pushes stay scanned): "
    "git config flashinfer.guardwords.scanCommits false",
    OPT_OUT_TIP,
)
SETUP_HINT = "python3 scripts/guardword_hooks.py setup"


def _say(line: str) -> None:
    print(f"{PREFIX} {line}", file=sys.stderr)


def _in_ci() -> bool:
    return bool(os.environ.get("CI"))


def _run_git(
    root: Path, *args: str, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(root), *args], capture_output=True, text=True, env=env
    )


def _git(root: Path, *args: str, env: dict[str, str] | None = None) -> str:
    result = _run_git(root, *args, env=env)
    return result.stdout.strip() if result.returncode == 0 else ""


def _config(root: Path, key: str) -> str:
    return _git(root, "config", "--get", key)


def _config_bool(root: Path, key: str) -> bool | None:
    value = _git(root, "config", "--type=bool", "--get", key)
    return None if not value else value == "true"


def _repo_root(start: Path) -> Path | None:
    top = _git(start, "rev-parse", "--show-toplevel")
    return Path(top) if top else None


def _git_path(root: Path, name: str) -> Path:
    return root / _git(root, "rev-parse", "--git-path", name)


def _common_dir(root: Path) -> Path:
    return (root / _git(root, "rev-parse", "--git-common-dir")).resolve()


@contextlib.contextmanager
def _locked(root: Path) -> Iterator[None]:
    with open(_common_dir(root) / LOCK_FILE, "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        yield


def _read(path: Path) -> str:
    return path.read_text(errors="replace") if path.is_file() else ""


def _write_if_different(path: Path, content: str, *, executable: bool = False) -> None:
    if _read(path) == content:
        return
    tmp = path.with_name(f".{path.name}.{os.getpid()}")
    tmp.write_text(content)
    if executable:
        tmp.chmod(0o755)
    os.replace(tmp, path)


def _age_s(path: Path) -> float:
    try:
        return time.time() - path.stat().st_mtime
    except OSError:
        return float("inf")


