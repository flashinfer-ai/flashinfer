def _push_hook_path(hooks_dir: Path) -> Path:
    hook = hooks_dir / "pre-push"
    # The pre-commit framework runs the hook it replaced first, from
    # pre-push.legacy, so the push hook can stay behind the framework's.
    if PRE_COMMIT_MARKER in _read(hook):
        return hook.with_name("pre-push.legacy")
    return hook


def _push_hook_installed(root: Path) -> bool:
    if not (_common_dir(root) / HOOK_COPY).is_file():
        return False
    hooks_dir = _git_path(root, "hooks")
    if _config(root, "core.hooksPath"):
        return HOOK_COPY in _read(hooks_dir / "pre-push")
    return SHIM_MARKER in _read(_push_hook_path(hooks_dir))


def _install_push_hook(hooks_dir: Path) -> tuple[list[str], list[str]]:
    hook = _push_hook_path(hooks_dir)
    current = _read(hook)
    if SHIM_MARKER in current:
        _write_if_different(hook, PUSH_HOOK, executable=True)
        return [], []
    installed = [
        "  pre-push: guardword scan of the commits, messages and branch or tag "
        "names pushed to GitHub"
    ]
    # The scanner's own hook, from its install.sh, is replaced rather than
    # chained: this one does what it did.
    if current and SCANNER_HOOK_MARKER not in current:
        chained = hooks_dir / "pre-push.chained"
        if chained.exists():
            return [], [
                f"Not installing the pre-push hook: both {hook} and {chained} "
                "exist. Merge them into one, then run setup again."
            ]
        os.replace(hook, chained)
        installed.append(
            f"  your previous pre-push hook now runs after the scan, from {chained}"
        )
    _write_if_different(hook, PUSH_HOOK, executable=True)
    return installed, []


def _pre_commit_command() -> list[str] | None:
    executable = shutil.which("pre-commit")
    if executable:
        return [executable]
    if importlib.util.find_spec("pre_commit") is not None:
        return [sys.executable, "-m", "pre_commit"]
    return None


def _install_pre_commit(root: Path, hooks_dir: Path) -> tuple[list[str], list[str]]:
    if PRE_COMMIT_MARKER in _read(hooks_dir / "pre-commit"):
        return [], []
    command = _pre_commit_command()
    if command is None:
        return [], [
            "pre-commit is not installed, so commits are neither formatted nor "
            f"scanned. Install it with `{sys.executable} -m pip install "
            "pre-commit`, then run: pre-commit install"
        ]
    result = subprocess.run(
        [*command, "install"], cwd=root, capture_output=True, text=True
    )
    if result.returncode != 0:
        return [], [
            f"pre-commit install failed: {(result.stdout + result.stderr).strip()}"
        ]
    return [
        "  pre-commit, by the pre-commit framework: the formatters and the "
        "guardword scan of staged changes (`pre-commit uninstall` turns both off)"
    ], []


def ensure_installed(root: Path, *, setup: bool = False) -> None:
    """Install the hooks if this checkout belongs to an NVIDIA contributor.

    Prints nothing when nothing changed and nothing needs the user's attention.
    """
    reason = detect(root)
    if not reason:
        return
    hooks_dir = _git_path(root, "hooks")
    installed: list[str] = []
    warnings: list[str] = []
    with _locked(root):
        _write_if_different(_common_dir(root) / HOOK_COPY, Path(__file__).read_text())
        if _config(root, "core.hooksPath"):
            if not _push_hook_installed(root):
                warnings += [
                    "NVIDIA contributor detected, but core.hooksPath is set, so the "
                    "guardword pre-push hook was not installed. Add this line to "
                    f"the top of {hooks_dir / 'pre-push'}:",
                    f"  {HOOKS_PATH_LINE}",
                ]
        else:
            hooks_dir.mkdir(parents=True, exist_ok=True)
            installed, warnings = _install_push_hook(hooks_dir)
            # Installed along with the push hook, then left to the contributor:
            # `pre-commit uninstall` stays uninstalled.
            if installed or setup:
                more_installed, more_warnings = _install_pre_commit(root, hooks_dir)
                installed += more_installed
                warnings += more_warnings
    # Setup sets the scanner up next, and says what went wrong itself.
    if _runner() is None and not setup:
        warnings += [
            f"Guardword scan unavailable: {_scanner_problem(root)}. Run: {SETUP_HINT}",
            OPT_OUT_TIP,
        ]
    if installed:
        _say(f"NVIDIA contributor detected ({reason}); installed guardword checks:")
        for line in (*installed, *SKIP_TIPS):
            _say(line)
    for line in warnings:
        _say(line)


