def _cache_dir() -> Path:
    configured = os.environ.get("FLASHINFER_SCAN_CACHE_DIR")
    return (
        Path(configured) if configured else Path.home() / ".flashinfer-guardwords-scan"
    )


def _is_checkout(cache: Path) -> bool:
    return (cache / "flashinfer_scan.py").is_file()


def _runner() -> Path | None:
    runner = _cache_dir() / RUNNER
    return runner if runner.is_file() else None


def _clean_env(root: Path) -> dict[str, str]:
    # Hooks inherit GIT_DIR and GIT_INDEX_FILE for this checkout (in linked
    # worktrees, and for `git commit -a`); they must not reach the scanner's.
    local = _git(root, "rev-parse", "--local-env-vars").split()
    return {name: value for name, value in os.environ.items() if name not in local}


def _network_env(root: Path, *, prompt: bool) -> dict[str, str]:
    env = _clean_env(root)
    if not prompt:
        env["GIT_TERMINAL_PROMPT"] = "0"
    if not (
        env.get("GIT_SSH_COMMAND")
        or env.get("GIT_SSH")
        or _config(root, "core.sshCommand")
    ):
        # Off VPN, an SSH connection would otherwise hang until the TCP timeout.
        env["GIT_SSH_COMMAND"] = "ssh -o ConnectTimeout=10" + (
            "" if prompt else " -o BatchMode=yes"
        )
    return env


def _has_terminal() -> bool:
    try:
        os.close(os.open("/dev/tty", os.O_RDWR))
    except OSError:
        return False
    return True


def _scanner_url(root: Path) -> str:
    url = os.environ.get("FLASHINFER_SCAN_REPO_URL")
    if url:
        return url
    cache = _cache_dir()
    if not (cache / ".git").exists():
        return ""
    return _git(cache, "remote", "get-url", "origin", env=_clean_env(root))


def _can_clone_into(cache: Path) -> bool:
    # A volume mounted for the checkout, as in the devcontainers, starts out
    # as an empty directory.
    try:
        return not any(cache.iterdir())
    except FileNotFoundError:
        return True
    except OSError:
        return False


def _fetch_scanner(
    root: Path, *, url: str = "", prompt: bool = False, quiet: bool = True
) -> Path | None:
    """Clone the scanner, or update a checkout without the runner; return the runner.

    Once the runner is there it keeps the checkout up to date itself. With
    `prompt`, ssh may ask for a key's passphrase; `quiet` hides git's messages.
    """
    cache = _cache_dir()
    branch = os.environ.get("FLASHINFER_SCAN_REPO_BRANCH") or "main"
    cloning = not _is_checkout(cache)
    if not cloning:
        cmd = [
            "git",
            "-C",
            str(cache),
            "pull",
            "--ff-only",
            "--quiet",
            "origin",
            branch,
        ]
    else:
        url = url or _scanner_url(root)
        if not url or not _can_clone_into(cache):
            return None
        cmd = ["git", "clone", "--quiet", "--branch", branch, url, str(cache)]
    # Someone at a terminal may be typing a passphrase, and can interrupt; a
    # timeout would kill git but leave ssh reading from their terminal.
    attended = prompt and _has_terminal()
    try:
        subprocess.run(
            cmd,
            env=_network_env(root, prompt=prompt),
            capture_output=quiet,
            timeout=None if attended else NETWORK_TIMEOUT_S,
        )
    except subprocess.TimeoutExpired:
        if cloning:
            shutil.rmtree(cache, ignore_errors=True)
    return _runner()


def _scanner_problem(root: Path, url: str = "") -> str:
    """Say why the runner is missing; `url` is a location setup just tried."""
    cache = _cache_dir()
    if _is_checkout(cache):
        return (
            f"the scanner checkout in {cache} predates the hook runner; updating "
            "it needs VPN access and access to the scanner repository"
        )
    if not _can_clone_into(cache):
        return f"{cache} is not a scanner checkout; remove it"
    if url or _scanner_url(root):
        return (
            "the scanner is not cloned yet; cloning it needs the right location, "
            "VPN access, and access to the scanner repository"
        )
    return (
        "the scanner location is not configured; setup asks for it, or reads "
        "FLASHINFER_SCAN_REPO_URL"
    )


def _call_runner(
    root: Path, runner: Path, *args: str, stdin: bytes | None = None
) -> int:
    # The hook's environment passes through unchanged: the runner needs this
    # checkout's GIT_INDEX_FILE to see what a commit contains.
    return subprocess.run(
        [sys.executable, str(runner), *args], cwd=root, input=stdin
    ).returncode


