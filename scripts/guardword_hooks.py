def _resolves_privately(host: str) -> bool:
    try:
        infos = socket.getaddrinfo(host, 443, proto=socket.IPPROTO_TCP)
    except OSError:
        return False
    return any(ipaddress.ip_address(info[4][0]).is_private for info in infos)


def _is_nvidia_org_member() -> bool:
    if shutil.which("gh") is None:
        return False
    try:
        result = subprocess.run(
            [
                "gh",
                "api",
                f"user/memberships/orgs/{NVIDIA_GITHUB_ORG}",
                "--jq",
                ".state",
            ],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0 and result.stdout.strip() == "active"


def detect(root: Path) -> str:
    """Return why this checkout belongs to an NVIDIA contributor, or ""."""
    explicit = _config_bool(root, "flashinfer.internal")
    if explicit is not None:
        return "git config flashinfer.internal" if explicit else ""
    if _config(root, "user.email").lower().endswith("@nvidia.com"):
        return "NVIDIA commit email"
    # Only NVIDIA environments can have the internal scanner, or its location.
    if _is_checkout(_cache_dir()):
        return "guardword scanner checkout on this machine"
    if os.environ.get("FLASHINFER_SCAN_REPO_URL"):
        return "FLASHINFER_SCAN_REPO_URL is set"
    checked = _common_dir(root) / DETECTION_MARKER
    if _age_s(checked) < DETECTION_TTL_S:
        return ""
    if any(_resolves_privately(host) for host in INTERNAL_HOSTNAMES):
        reason = "NVIDIA network"
    elif _is_nvidia_org_member():
        reason = f"member of the {NVIDIA_GITHUB_ORG} GitHub org"
    else:
        with contextlib.suppress(OSError):
            checked.touch()
        return ""
    # Recorded where the opt-out goes, so leaving the network or an expired gh
    # login does not turn the checks off, in this clone or any other.
    _run_git(root, "config", "--global", "flashinfer.internal", "true")
    return reason


