def _ask(question: str, *, default: bool) -> bool:
    suffix = "[Y/n]" if default else "[y/N]"
    answer = input(f"{PREFIX} {question} {suffix} ").strip().lower()
    return default if not answer else answer in ("y", "yes")


def _offer_gh_login() -> None:
    if shutil.which("gh") is None:
        _say(
            "Optional: with the GitHub CLI (https://cli.github.com) logged in, "
            "checkouts on other machines detect you automatically."
        )
    elif subprocess.run(["gh", "auth", "status"], capture_output=True).returncode != 0:
        if _ask(
            "The GitHub CLI is not logged in. Run `gh auth login` now?", default=False
        ):
            subprocess.run(["gh", "auth", "login"])


def _set_up_scanner(root: Path, *, interactive: bool) -> bool:
    url = _scanner_url(root)
    if not url and interactive:
        url = input(
            f"{PREFIX} Paste the scanner repository location from the internal "
            "setup instructions: "
        ).strip()
    if (
        url
        and _fetch_scanner(root, url=url, prompt=interactive, quiet=not interactive)
        is not None
    ):
        return True
    _say(f"Setup is incomplete: {_scanner_problem(root, url)}.")
    return False


def _opt_back_in_command(root: Path) -> str:
    scope = _git(root, "config", "--show-scope", "--get", "flashinfer.internal")
    option = {"global": " --global", "system": " --system"}.get(
        scope.partition("\t")[0], ""
    )
    return f"git config{option} --unset flashinfer.internal"


def run_setup(root: Path, *, interactive: bool = True) -> int:
    if interactive and not sys.stdin.isatty():
        _say("setup is interactive; run it from a terminal, or pass --non-interactive.")
        return 1
    if _config_bool(root, "flashinfer.internal") is False:
        _say(
            "Opted out with flashinfer.internal false, so there is nothing to set "
            f"up. To opt back in: {_opt_back_in_command(root)}"
        )
        return 1
    reason = detect(root)
    if reason:
        _say(f"NVIDIA contributor detected ({reason}).")
    elif interactive and not _ask(
        "Are you an NVIDIA employee contributing to FlashInfer?", default=False
    ):
        _say("Nothing to set up.")
        return 0
    # A setting in this clone stays there, and leaves the other clones alone.
    if _config_bool(root, "flashinfer.internal") is None:
        _run_git(root, "config", "--global", "flashinfer.internal", "true")

    if interactive:
        install = [sys.executable, "-m", "pip", "install", "pre-commit"]
        if _pre_commit_command() is None and _ask(
            f"pre-commit is not installed. Install it with `{' '.join(install)}`?",
            default=True,
        ):
            subprocess.run(install)
        _offer_gh_login()

    # Installed first: until the scanner is set up, they block pushes to GitHub.
    ensure_installed(root, setup=True)
    if _runner() is None and not _set_up_scanner(root, interactive=interactive):
        return 1
    return run_status(root)


def run_status(root: Path) -> int:
    """Report whether the guardword checks protect this checkout; 0 if they do."""
    reason = detect(root)
    hooks_dir = _git_path(root, "hooks")
    hooks_path = bool(_config(root, "core.hooksPath"))
    problems = []
    notes = []
    opted_out = _config_bool(root, "flashinfer.internal") is False
    if opted_out:
        problems.append("opted out: flashinfer.internal is false")
    elif not reason:
        problems.append("not recognized as an NVIDIA contributor")
    if not _push_hook_installed(root):
        problems.append(
            f"core.hooksPath is set, and {hooks_dir / 'pre-push'} does not run "
            "the guardword hook"
            if hooks_path
            else "the pre-push hook is not installed"
        )
    runner = _runner()
    if runner is None:
        problems.append(_scanner_problem(root))
    else:
        report = subprocess.run(
            [sys.executable, str(runner), "check"],
            capture_output=True,
            text=True,
            env=_clean_env(root),
        )
        reported = False
        for line in report.stdout.splitlines():
            kind, _, text = line.partition(": ")
            if kind == "problem":
                problems.append(text)
                reported = True
            elif kind == "note":
                notes.append(text)
        if report.returncode != 0 and not reported:
            problems.append("the hook runner's check failed")

    if _config_bool(root, "flashinfer.guardwords.scanCommits") is False:
        notes.append(
            "commits are only scanned when pushed: "
            "flashinfer.guardwords.scanCommits is false"
        )
    elif "guardword_hooks.py check-commit" not in _read(
        root / ".pre-commit-config.yaml"
    ):
        notes.append(
            "this branch's .pre-commit-config.yaml predates the commit check, so "
            "commits are only scanned when pushed"
        )
    elif not hooks_path and PRE_COMMIT_MARKER not in _read(hooks_dir / "pre-commit"):
        notes.append(
            "commits are neither formatted nor scanned until the pre-commit "
            "framework's hook is installed: pre-commit install"
        )

    if not problems:
        _say(f"Guardword checks are active ({reason}).")
        for note in notes:
            _say(f"  Note: {note}")
        return 0
    _say("Guardword checks are NOT active:")
    for problem in problems:
        _say(f"  {problem}")
    if opted_out:
        _say(f"To opt back in: {_opt_back_in_command(root)}")
        return 1
    _say(f"Fix: {SETUP_HINT} (agents and automation: setup --non-interactive)")
    _say(OPT_OUT_TIP)
    return 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    setup = commands.add_parser("setup", help="one-time setup and tool checks")
    setup.add_argument(
        "--non-interactive",
        action="store_true",
        help="never prompt; reads the scanner location from FLASHINFER_SCAN_REPO_URL",
    )
    commands.add_parser(
        "status", help="report whether the checks protect this checkout"
    )
    commands.add_parser(
        "ensure", help="install the push hook if this is an NVIDIA contributor"
    )
    commands.add_parser(
        "check-commit", help="the commit check, run by the pre-commit framework"
    )
    pre_push = commands.add_parser(
        "pre-push", help="the push check, run by the installed pre-push hook"
    )
    pre_push.add_argument("remote_name")
    pre_push.add_argument("remote_url")
    args = parser.parse_args(argv)
    # Only the automatic installs skip CI; an explicit setup still installs.
    if args.command == "ensure" and _in_ci():
        return 0

    root = _repo_root(Path.cwd())
    if root is None:
        # pip and pytest also run `ensure` in source trees without git
        # history, such as the copies in the Docker images.
        if args.command in ("ensure", "check-commit"):
            return 0
        _say("not inside a git checkout")
        return 1
    if args.command == "setup":
        return run_setup(root, interactive=not args.non_interactive)
    if args.command == "status":
        return run_status(root)
    if args.command == "ensure":
        ensure_installed(root)
        return 0
    if args.command == "check-commit":
        return run_check_commit(root)
    return run_pre_push(root, args.remote_name, args.remote_url)


if __name__ == "__main__":
    sys.exit(main())
