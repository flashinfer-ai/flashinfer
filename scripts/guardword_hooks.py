def run_check_commit(root: Path) -> int:
    if _in_ci():
        return 0
    ensure_installed(root)
    if (
        not detect(root)
        or _config_bool(root, "flashinfer.guardwords.scanCommits") is False
    ):
        return 0
    runner = _runner()
    if runner is None:
        _say("Committing without a guardword scan; pushes to GitHub stay blocked.")
        return 0
    if _call_runner(root, runner, "pre-commit") == 0:
        return 0
    _say(
        "Commit blocked by the guardword scan (see above). Remove the flagged text, or:"
    )
    for tip in SKIP_TIPS[:2]:
        _say(f"  {tip}")
    return 1


def _ssh_host(url: str) -> str:
    """Return the host an SSH remote URL names, or "" for other URLs."""
    if "://" in url:
        scheme, _, rest = url.partition("://")
        if "ssh" not in scheme:
            return ""
        return rest.split("/", 1)[0].rpartition("@")[2].split(":", 1)[0]
    if ":" in url.split("/", 1)[0]:
        return url.split(":", 1)[0].rpartition("@")[2]
    return ""


def _is_github(url: str) -> bool:
    """Whether a remote URL points at GitHub, following SSH host aliases."""
    if "github" in url.lower():
        return True
    host = _ssh_host(url)
    if not host or host.startswith("-") or shutil.which("ssh") is None:
        return False
    try:
        config = subprocess.run(
            ["ssh", "-G", host], capture_output=True, text=True, timeout=10
        ).stdout
    except (OSError, subprocess.TimeoutExpired):
        return False
    return any(
        line.lower().startswith("hostname ") and "github" in line.lower()
        for line in config.splitlines()
    )


def _scan_push(root: Path, remote_name: str, remote_url: str, pushed: bytes) -> int:
    runner = _runner()
    if runner is None:
        # The runner decides which pushes to scan; until it is cloned, these
        # are the ones it would scan.
        if not _is_github(remote_url):
            return 0
        # Someone is pushing, so ssh may ask for a passphrase, as it does for
        # the push itself.
        _say("Fetching the guardword scanner before scanning the push...")
        runner = _fetch_scanner(root, prompt=True)
    if runner is None:
        _say(f"Guardword scan unavailable: {_scanner_problem(root)}.")
        _say(f"Push blocked until: {SETUP_HINT}")
        _say("Emergency bypass: git push --no-verify")
        _say(OPT_OUT_TIP)
        return 1
    if (
        _call_runner(root, runner, "pre-push", remote_name, remote_url, stdin=pushed)
        == 0
    ):
        return 0
    _say(
        "Push blocked by the guardword scan (see above). Remove the flagged text "
        "and amend or rewrite the commits."
    )
    _say("If it is a false positive, or the scan could not run: git push --no-verify")
    return 1


def run_pre_push(root: Path, remote_name: str, remote_url: str) -> int:
    pushed = sys.stdin.buffer.read()
    if _config_bool(root, "flashinfer.internal") is not False:
        returncode = _scan_push(root, remote_name, remote_url, pushed)
        if returncode != 0:
            return returncode
    chained = _git_path(root, "hooks") / "pre-push.chained"
    if not os.access(chained, os.X_OK):
        return 0
    return subprocess.run(
        [str(chained), remote_name, remote_url], input=pushed
    ).returncode


