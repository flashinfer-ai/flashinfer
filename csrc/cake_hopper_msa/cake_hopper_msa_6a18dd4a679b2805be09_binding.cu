void Run(TensorView a_Q, TensorView a_K, TensorView a_out, TensorView a_page_table,
         TensorView a_seqused_k, TensorView a_q_offset, int64_t a_has_qoff, int64_t a_pt_stride,
         int64_t a_max_k_tiles, int64_t a_total_q, int64_t a_batch_fast, int64_t a_evict_first,
         int64_t grid_x, int64_t grid_y, int64_t grid_z) {
  DLDevice dev = a_Q.device();
  tvm::ffi::CUDADeviceGuard device_guard(dev.device_id);
  check_cuda_tensor(a_Q, "Q");
  check_dtype(a_Q, DLDataType{kDLBfloat, 16, 1}, "Q");
  check_cuda_tensor(a_K, "K");
  check_dtype(a_K, DLDataType{kDLBfloat, 16, 1}, "K");
  check_cuda_tensor(a_out, "out");
  check_dtype(a_out, DLDataType{kDLFloat, 32, 1}, "out");
  check_cuda_tensor(a_page_table, "page_table");
  check_dtype(a_page_table, DLDataType{kDLInt, 32, 1}, "page_table");
  check_cuda_tensor(a_seqused_k, "seqused_k");
  check_dtype(a_seqused_k, DLDataType{kDLInt, 32, 1}, "seqused_k");
  check_cuda_tensor(a_q_offset, "q_offset");
  check_dtype(a_q_offset, DLDataType{kDLInt, 32, 1}, "q_offset");
  TVM_FFI_CHECK(a_has_qoff >= -2147483648LL && a_has_qoff <= 2147483647LL, ValueError)
      << KERNEL_NAME << ": 'has_qoff' = " << a_has_qoff
      << " is outside the i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(a_pt_stride >= -2147483648LL && a_pt_stride <= 2147483647LL, ValueError)
      << KERNEL_NAME << ": 'pt_stride' = " << a_pt_stride
      << " is outside the i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(a_max_k_tiles >= -2147483648LL && a_max_k_tiles <= 2147483647LL, ValueError)
      << KERNEL_NAME << ": 'max_k_tiles' = " << a_max_k_tiles
      << " is outside the i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(a_total_q >= -2147483648LL && a_total_q <= 2147483647LL, ValueError)
      << KERNEL_NAME << ": 'total_q' = " << a_total_q
      << " is outside the i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(a_batch_fast >= -2147483648LL && a_batch_fast <= 2147483647LL, ValueError)
      << KERNEL_NAME << ": 'batch_fast' = " << a_batch_fast
      << " is outside the i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(a_evict_first >= -2147483648LL && a_evict_first <= 2147483647LL, ValueError)
      << KERNEL_NAME << ": 'evict_first' = " << a_evict_first
      << " is outside the i32 range [-2147483648, 2147483647]";
  check_same_device(a_K, a_Q, "K", "Q");
  check_contiguous(a_out, "out");
  check_same_device(a_out, a_Q, "out", "Q");
  check_contiguous(a_page_table, "page_table");
  check_same_device(a_page_table, a_Q, "page_table", "Q");
  check_contiguous(a_seqused_k, "seqused_k");
  check_same_device(a_seqused_k, a_Q, "seqused_k", "Q");
  check_contiguous(a_q_offset, "q_offset");
  check_same_device(a_q_offset, a_Q, "q_offset", "Q");
  TVM_FFI_CHECK(grid_x > 0 && grid_y > 0 && grid_z > 0, ValueError)
      << KERNEL_NAME << ": the grid (" << grid_x << ", " << grid_y << ", " << grid_z
      << ") must be positive";
  TVM_FFI_CHECK(grid_x <= 2147483647 && grid_y <= 65535 && grid_z <= 65535, ValueError)
      << KERNEL_NAME << ": the grid (" << grid_x << ", " << grid_y << ", " << grid_z
      << ") exceeds CUDA's limits";
  cudaStream_t stream =
      static_cast<cudaStream_t>(TVMFFIEnvGetStream(dev.device_type, dev.device_id));
  {
    // Once per thread per device: the tensor-map encoders need this thread's context of the device
    // bound.
    static thread_local uint64_t prepared_devices = 0;
    const uint64_t device_bit = dev.device_id < 64 ? uint64_t{1} << dev.device_id : uint64_t{0};
    if (device_bit == 0 || (prepared_devices & device_bit) == 0) {
      CheckCuda(cudaSetDevice(dev.device_id), "cudaSetDevice");
      prepared_devices |= device_bit;
    }
  }
  CUtensorMap v_Q = EncodeTma_Q(a_Q);
  CUtensorMap v_K = EncodeTma_K(a_K);
  void* v_out = DataPtr(a_out);
  void* v_page_table = DataPtr(a_page_table);
  void* v_seqused_k = DataPtr(a_seqused_k);
  void* v_q_offset = DataPtr(a_q_offset);
  int32_t v_has_qoff = static_cast<int32_t>(a_has_qoff);
  int32_t v_pt_stride = static_cast<int32_t>(a_pt_stride);
  int32_t v_max_k_tiles = static_cast<int32_t>(a_max_k_tiles);
  int32_t v_total_q = static_cast<int32_t>(a_total_q);
  int32_t v_batch_fast = static_cast<int32_t>(a_batch_fast);
  int32_t v_evict_first = static_cast<int32_t>(a_evict_first);
  void* kernel_args[] = {&v_Q,           &v_K,        &v_out,        &v_page_table,
                         &v_seqused_k,   &v_q_offset, &v_has_qoff,   &v_pt_stride,
                         &v_max_k_tiles, &v_total_q,  &v_batch_fast, &v_evict_first};
  cudaLaunchConfig_t config{};
  config.gridDim = dim3(static_cast<unsigned>(grid_x), static_cast<unsigned>(grid_y),
                        static_cast<unsigned>(grid_z));
  config.blockDim = dim3(CAKE_BIND_THREADS, 1, 1);
  config.dynamicSmemBytes = CAKE_BIND_SMEM;
  config.stream = stream;
  CheckCuda(
      cudaLaunchKernelExC(&config, reinterpret_cast<const void*>(CAKE_PROGRAM_KERNEL), kernel_args),
      "cudaLaunchKernelExC");
}

