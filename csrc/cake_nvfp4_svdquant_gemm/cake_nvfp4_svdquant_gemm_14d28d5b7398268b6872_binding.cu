      CU_TENSOR_MAP_INTERLEAVE_NONE, CU_TENSOR_MAP_SWIZZLE_128B, CU_TENSOR_MAP_L2_PROMOTION_NONE,
      CU_TENSOR_MAP_FLOAT_OOB_FILL_NAN_REQUEST_ZERO_FMA);
  TVM_FFI_CHECK(r == CUDA_SUCCESS, RuntimeError)
      << "cuTensorMapEncodeTiled (2D, 'L1') failed: CUresult=" << (int)r;
  return tm;
}

// 2D TMA descriptor for buffer 'out' — compiled from the
// descriptor's std.Expr global_dim/global_strides/checks record.
inline CUtensorMap EncodeTma_out(const TensorView& t) {
  TVM_FFI_CHECK(t.ndim() >= 2, ValueError)
      << "TMA source 'out' must have at least 2 dimensions, got ndim=" << t.ndim();
  TVM_FFI_CHECK(t.stride(-1) == 1, ValueError)
      << "TMA source 'out' must have unit innermost stride, got " << t.stride(-1);
  int64_t d1 = t.size(t.ndim() - 1);
  TVM_FFI_CHECK(d1 > 0, ValueError)
      << "TMA source 'out' trailing dims must be positive";
  int64_t outer1 = t.numel() / (d1);
  check_dense_leading_dims(t, 1, "out");
  int64_t s2 = t.stride(t.ndim() - 2) * 1;
  TVM_FFI_CHECK(s2 > 0, ValueError)
      << "TMA source 'out' physical strides must be positive";
  uint64_t global_dim[2] = {(uint64_t)(d1), (uint64_t)(outer1)};
  TVM_FFI_CHECK(global_dim[0] > 0 && global_dim[1] > 0, ValueError)
      << "TMA descriptor for 'out' resolved a non-positive global dim";
  uint32_t box_dim[2] = {32u, 128u};
  TVM_FFI_CHECK(box_dim[0] <= global_dim[0] && box_dim[1] <= global_dim[1], ValueError)
      << "TMA box (" << box_dim[0] << ", " << box_dim[1] << ") exceeds resolved global dims for 'out'";
  int64_t carrier_stride_0 = s2;
  TVM_FFI_CHECK(carrier_stride_0 >= 0, ValueError)
      << "TMA descriptor for 'out' resolved global stride 1 negative";
  TVM_FFI_CHECK(carrier_stride_0 != 0 || global_dim[1] == 1, ValueError)
      << "TMA descriptor for 'out' resolved global stride 1 zero while global dimension 1 is not 1";
  TVM_FFI_CHECK((carrier_stride_0 * 16) % 8 == 0, ValueError)
      << "TMA descriptor for 'out' resolved global stride 1 to a non-whole-byte offset";
  uint64_t global_strides[1] = {
      (uint64_t)((carrier_stride_0 * 16) / 8),
  };
  uint32_t elem_strides[2] = {1u, 1u};
  CUtensorMap tm{};
  const void* tensor_base = static_cast<const char*>(t.data_ptr()) + 0u;
  CUresult r = cuTensorMapEncodeTiled(
      &tm, CU_TENSOR_MAP_DATA_TYPE_BFLOAT16, 2, const_cast<void*>(tensor_base), global_dim, global_strides, box_dim, elem_strides,
      CU_TENSOR_MAP_INTERLEAVE_NONE, CU_TENSOR_MAP_SWIZZLE_64B, CU_TENSOR_MAP_L2_PROMOTION_NONE,
      CU_TENSOR_MAP_FLOAT_OOB_FILL_NONE);
  TVM_FFI_CHECK(r == CUDA_SUCCESS, RuntimeError)
      << "cuTensorMapEncodeTiled (2D, 'out') failed: CUresult=" << (int)r;
  return tm;
}

void Run(TensorView arg_A, TensorView arg_B, TensorView arg_SFA, TensorView arg_SFB, TensorView arg_D, TensorView arg_L1, TensorView arg_alpha, TensorView arg_out, int64_t arg_K_tiles, int64_t grid_x, int64_t grid_y, int64_t grid_z) {
  DLDevice dev = arg_A.device();
  tvm::ffi::CUDADeviceGuard device_guard(dev.device_id);
  TVM_FFI_CHECK_CUDA_ERROR(cudaSetDevice(dev.device_id));  // binds the context for the encoders
  check_cuda_tensor(arg_A, "A");
  check_dtype(arg_A, DLDataType{kDLUInt, 8, 1}, "A");
  check_cuda_tensor(arg_B, "B");
  check_dtype(arg_B, DLDataType{kDLUInt, 8, 1}, "B");
  check_cuda_tensor(arg_SFA, "SFA");
  check_dtype(arg_SFA, DLDataType{kDLUInt, 16, 1}, "SFA");
  check_cuda_tensor(arg_SFB, "SFB");
  check_dtype(arg_SFB, DLDataType{kDLUInt, 16, 1}, "SFB");
  check_cuda_tensor(arg_D, "D");
  check_dtype(arg_D, DLDataType{kDLBfloat, 16, 1}, "D");
  check_cuda_tensor(arg_L1, "L1");
  check_dtype(arg_L1, DLDataType{kDLBfloat, 16, 1}, "L1");
  check_cuda_tensor(arg_alpha, "alpha");
  check_dtype(arg_alpha, DLDataType{kDLFloat, 32, 1}, "alpha");
  check_contiguous(arg_alpha, "alpha");
  check_cuda_tensor(arg_out, "out");
  check_dtype(arg_out, DLDataType{kDLBfloat, 16, 1}, "out");
  TVM_FFI_CHECK(arg_K_tiles >= -2147483648LL && arg_K_tiles <= 2147483647LL, ValueError)
      << "scalar 'K_tiles' value " << arg_K_tiles
      << " is outside i32 range [-2147483648, 2147483647]";
  check_same_device(arg_B, arg_A, "B", "A");
  check_same_device(arg_SFA, arg_A, "SFA", "A");
  check_same_device(arg_SFB, arg_A, "SFB", "A");
  check_same_device(arg_D, arg_A, "D", "A");
  check_same_device(arg_L1, arg_A, "L1", "A");
  check_same_device(arg_alpha, arg_A, "alpha", "A");
  check_same_device(arg_out, arg_A, "out", "A");
  TVM_FFI_CHECK(grid_x > 0 && grid_y > 0 && grid_z > 0, ValueError)
      << "launch grid dimensions must be positive, got (" << grid_x << ", " << grid_y
      << ", " << grid_z << ")";
  TVM_FFI_CHECK(grid_x % 2 == 0 && grid_y % 1 == 0 && grid_z % 1 == 0, ValueError)
      << "launch grid (" << grid_x << ", " << grid_y << ", " << grid_z
      << ") must be divisible by cluster dims (2, 1, 1)";

  cudaStream_t stream = (cudaStream_t)TVMFFIEnvGetStream(dev.device_type, dev.device_id);
  CUtensorMap p_A = EncodeTma_A(arg_A);
  CUtensorMap p_B = EncodeTma_B(arg_B);
  CUtensorMap p_SFA = EncodeTma_SFA(arg_SFA);
  CUtensorMap p_SFB = EncodeTma_SFB(arg_SFB);
  CUtensorMap p_D = EncodeTma_D(arg_D);
  CUtensorMap p_L1 = EncodeTma_L1(arg_L1);
  float* p_alpha = static_cast<float*>(arg_alpha.data_ptr());
  CUtensorMap p_out = EncodeTma_out(arg_out);
  int32_t v_K_tiles = (int32_t)arg_K_tiles;
  void* kargs[] = {&p_A, &p_B, &p_SFA, &p_SFB, &p_D, &p_L1, &p_alpha, &p_out, &v_K_tiles};

  static const bool smem_ready = CakeSetMaxDynamicSmem(
      reinterpret_cast<const void*>(kernel_cake_nvfp4_svdquant_gemm_14d28d5b7398268b6872), 218112);
  (void)smem_ready;
  dim3 grid((uint32_t)grid_x, (uint32_t)grid_y, (uint32_t)grid_z);
  dim3 block(256u, 1u, 1u);

  // Extended direct-source launch for a linked CUDA kernel symbol.
  cudaLaunchAttribute attrs[2]{};
  int n = 0;
  attrs[n].id = cudaLaunchAttributeClusterDimension;
  attrs[n].val.clusterDim.x = 2u;
  attrs[n].val.clusterDim.y = 1u;
  attrs[n].val.clusterDim.z = 1u;
  ++n;
  attrs[n].id = cudaLaunchAttributeClusterSchedulingPolicyPreference;
  attrs[n].val.clusterSchedulingPolicyPreference = cudaClusterSchedulingPolicySpread;
  ++n;
  cudaLaunchConfig_t config{};
  config.gridDim = grid;
  config.blockDim = block;
  config.dynamicSmemBytes = 218112u;
  config.stream = stream;
  config.attrs = attrs;
  config.numAttrs = n;
  cudaError_t launch_status = cudaLaunchKernelExC(
      &config, reinterpret_cast<const void*>(kernel_cake_nvfp4_svdquant_gemm_14d28d5b7398268b6872), kargs);
  TVM_FFI_CHECK(launch_status == cudaSuccess, RuntimeError)
      << "cudaLaunchKernelExC for kernel_cake_nvfp4_svdquant_gemm_14d28d5b7398268b6872 failed: "
      << cudaGetErrorString(launch_status);
}

