void Run(TensorView arg_A, TensorView arg_B, TensorView arg_SFA, TensorView arg_SFB, TensorView arg_D, TensorView arg_L1, TensorView arg_alpha, TensorView arg_bias, TensorView arg_out, int64_t arg_M, int64_t arg_N, int64_t arg_K_tiles, int64_t arg_rank_tiles, int64_t arg_grid_n, int64_t arg_has_bias, int64_t grid_x, int64_t grid_y, int64_t grid_z) {
  DLDevice dev = arg_A.device();
  tvm::ffi::CUDADeviceGuard device_guard(dev.device_id);
  TVM_FFI_CHECK_CUDA_ERROR(cudaSetDevice(dev.device_id));  // binds the context for the encoders
  check_cuda_tensor(arg_A, "A");
  check_dtype(arg_A, DLDataType{kDLUInt, 8, 1}, "A");
  check_cuda_tensor(arg_B, "B");
  check_dtype(arg_B, DLDataType{kDLUInt, 8, 1}, "B");
  check_cuda_tensor(arg_SFA, "SFA");
  check_dtype(arg_SFA, DLDataType{kDLUInt, 8, 1}, "SFA");
  check_cuda_tensor(arg_SFB, "SFB");
  check_dtype(arg_SFB, DLDataType{kDLUInt, 8, 1}, "SFB");
  check_cuda_tensor(arg_D, "D");
  check_dtype(arg_D, DLDataType{kDLBfloat, 16, 1}, "D");
  check_cuda_tensor(arg_L1, "L1");
  check_dtype(arg_L1, DLDataType{kDLBfloat, 16, 1}, "L1");
  check_cuda_tensor(arg_alpha, "alpha");
  check_dtype(arg_alpha, DLDataType{kDLFloat, 32, 1}, "alpha");
  check_contiguous(arg_alpha, "alpha");
  check_cuda_tensor(arg_bias, "bias");
  check_dtype(arg_bias, DLDataType{kDLBfloat, 16, 1}, "bias");
  check_contiguous(arg_bias, "bias");
  check_cuda_tensor(arg_out, "out");
  check_dtype(arg_out, DLDataType{kDLBfloat, 16, 1}, "out");
  TVM_FFI_CHECK(arg_M >= -2147483648LL && arg_M <= 2147483647LL, ValueError)
      << "scalar 'M' value " << arg_M
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_N >= -2147483648LL && arg_N <= 2147483647LL, ValueError)
      << "scalar 'N' value " << arg_N
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_K_tiles >= -2147483648LL && arg_K_tiles <= 2147483647LL, ValueError)
      << "scalar 'K_tiles' value " << arg_K_tiles
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_rank_tiles >= -2147483648LL && arg_rank_tiles <= 2147483647LL, ValueError)
      << "scalar 'rank_tiles' value " << arg_rank_tiles
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_grid_n >= -2147483648LL && arg_grid_n <= 2147483647LL, ValueError)
      << "scalar 'grid_n' value " << arg_grid_n
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_has_bias >= -2147483648LL && arg_has_bias <= 2147483647LL, ValueError)
      << "scalar 'has_bias' value " << arg_has_bias
      << " is outside i32 range [-2147483648, 2147483647]";
