  TVM_FFI_CHECK(launch_status == cudaSuccess, RuntimeError)
      << "cudaLaunchKernel for kernel_cake_nvfp4_svdquant_gemm_ffc7cbc225f9c3e46796 failed: "
      << cudaGetErrorString(launch_status);
