  CheckSameCudaDevice(arg_C_tma, arg_A, "C_tma", "A");
  CheckSameCudaDevice(arg_C, arg_A, "C", "A");
  CheckSameCudaDevice(arg_a_scale, arg_A, "a_scale", "A");
  CheckSameCudaDevice(arg_b_scale, arg_A, "b_scale", "A");
  CheckSameCudaDevice(arg_m_indices, arg_A, "m_indices", "A");
  CheckCurrentCudaDevice(arg_A, "A");
  CheckCudaTensor(arg_tma_descriptor_workspace, "tma_descriptor_workspace");
  CheckSameCudaDevice(arg_tma_descriptor_workspace, arg_A, "tma_descriptor_workspace", "A");
  CheckContiguous(arg_tma_descriptor_workspace, "tma_descriptor_workspace");
  CheckDtype(arg_tma_descriptor_workspace, "tma_descriptor_workspace", 1, 8, 1);
