      << "TMA descriptor for 'b_scale' resolved a non-positive global dim";
  TVM_FFI_CHECK(4u <= global_dim[0] && 1u <= global_dim[1] && 1u <= global_dim[2], ValueError)
      << "TMA box (4, 1, 1) exceeds resolved global dims for 'b_scale'";
  int64_t carrier_stride_0 = d1;
  TVM_FFI_CHECK(carrier_stride_0 >= 0, ValueError)
      << "TMA descriptor for 'b_scale' resolved global stride 1 negative";
  TVM_FFI_CHECK(carrier_stride_0 != 0 || global_dim[1] == 1, ValueError)
      << "TMA descriptor for 'b_scale' resolved global stride 1 zero while global dimension 1 is not 1";
  TVM_FFI_CHECK((carrier_stride_0 * 32) % 8 == 0, ValueError)
      << "TMA descriptor for 'b_scale' resolved global stride 1 to a non-whole-byte offset";
  int64_t carrier_stride_1 = (d2 * d1);
  TVM_FFI_CHECK(carrier_stride_1 >= 0, ValueError)
      << "TMA descriptor for 'b_scale' resolved global stride 2 negative";
  TVM_FFI_CHECK(carrier_stride_1 != 0 || global_dim[2] == 1, ValueError)
      << "TMA descriptor for 'b_scale' resolved global stride 2 zero while global dimension 2 is not 1";
  TVM_FFI_CHECK((carrier_stride_1 * 32) % 8 == 0, ValueError)
      << "TMA descriptor for 'b_scale' resolved global stride 2 to a non-whole-byte offset";
  uint64_t global_strides[2] = {
      (uint64_t)((carrier_stride_0 * 32) / 8),
      (uint64_t)((carrier_stride_1 * 32) / 8),
  };
  uint32_t box_dim[3] = {4u, 1u, 1u};
  uint32_t elem_strides[3] = {1u, 1u, 1u};
  CUtensorMap tm{};
  const void* tensor_base = static_cast<const char*>(t.data_ptr()) + 0u;
  CUresult r = cuTensorMapEncodeTiled(
      &tm, CU_TENSOR_MAP_DATA_TYPE_FLOAT32, 3, const_cast<void*>(tensor_base), global_dim, global_strides, box_dim, elem_strides,
      CU_TENSOR_MAP_INTERLEAVE_NONE, CU_TENSOR_MAP_SWIZZLE_NONE, CU_TENSOR_MAP_L2_PROMOTION_NONE,
      CU_TENSOR_MAP_FLOAT_OOB_FILL_NONE);
  TVM_FFI_CHECK(r == CUDA_SUCCESS, RuntimeError)
      << "cuTensorMapEncodeTiled (3D, 'b_scale') failed: CUresult=" << (int)r;
  return tm;
}

