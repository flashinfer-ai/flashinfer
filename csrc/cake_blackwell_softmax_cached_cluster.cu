    float pair_sum[3];
    #pragma unroll
    for (int k_1 = 0; k_1 < 3; k_1++) {
        int g = lane + k_1 * 32;
        pair_max[k_1] = -CUDART_INF_F;
        pair_sum[k_1] = 0.0f;
        if (g < 96) {
            pair_max[k_1] = cluster_table[g * 2];
            pair_sum[k_1] = cluster_table[g * 2 + 1];
        }
    }
    float lane_max = pair_max[0];
    #pragma unroll
    for (int k_2 = 1; k_2 < 3; k_2++) {
        lane_max = max_noftz(lane_max, pair_max[k_2]);
    }
    float row_max;
    asm volatile("redux.sync.max.f32 %0, %1, 0xffffffff;" : "=f"(row_max) : "f"(lane_max));
    float lane_sum = 0.0f;
    #pragma unroll
    for (int k_3 = 0; k_3 < 3; k_3++) {
        float _exp2_5 = approx_exp2((pair_max[k_3] - row_max) * 1.442695f);
        lane_sum = __fmaf_rn(pair_sum[k_3], _exp2_5, lane_sum);
    }
    float row_sum = lane_sum;
    #pragma unroll
    for (int offset = 16; offset > 0; offset >>= 1)
        row_sum += __shfl_xor_sync(0xFFFFFFFF, row_sum, offset);
    float inv_sum = approx_rcp(row_sum);
    #pragma unroll
    for (int tile_2 = 0; tile_2 < 10; tile_2++) {
        int elem_2 = chunk_begin + (tile_2 * 256 + tid) * 8;
        if (elem_2 < chunk_end) {
            unsigned long long index_1 = row_base + (unsigned long long)elem_2;
            float _exp2_6 = approx_exp2((tile_max[tile_2] - row_max) * 1.442695f);
            float scale = _exp2_6 * inv_sum;
            float out_values[8];
            #pragma unroll
            for (int j_3 = 0; j_3 < 8; j_3++) {
                out_values[j_3] = cache[tile_2 * 8 + j_3] * scale;
            }
            {
                unsigned _stv8_7_0 = __float_as_uint(out_values[0 + 0]);
                unsigned _stv8_7_1 = __float_as_uint(out_values[0 + 1]);
                unsigned _stv8_7_2 = __float_as_uint(out_values[0 + 2]);
                unsigned _stv8_7_3 = __float_as_uint(out_values[0 + 3]);
                unsigned _stv8_7_4 = __float_as_uint(out_values[0 + 4]);
                unsigned _stv8_7_5 = __float_as_uint(out_values[0 + 5]);
                unsigned _stv8_7_6 = __float_as_uint(out_values[0 + 6]);
                unsigned _stv8_7_7 = __float_as_uint(out_values[0 + 7]);
                #if __CUDACC_VER_MAJOR__ > 12 || (__CUDACC_VER_MAJOR__ == 12 && __CUDACC_VER_MINOR__ >= 9)
                asm volatile(
                    "st.global.v8.b32 [%0], {%1, %2, %3, %4, %5, %6, %7, %8};"
                    :: "l"((void*)(output + (index_1))), "r"(_stv8_7_0), "r"(_stv8_7_1), "r"(_stv8_7_2), "r"(_stv8_7_3), "r"(_stv8_7_4), "r"(_stv8_7_5), "r"(_stv8_7_6), "r"(_stv8_7_7) : "memory");
                #else
