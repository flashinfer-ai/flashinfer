                asm volatile(
                    "st.global.v4.b32 [%0], {%1, %2, %3, %4};"
                    :: "l"((void*)(output + (index_1) + 4)), "r"(_stv8_7_4), "r"(_stv8_7_5), "r"(_stv8_7_6), "r"(_stv8_7_7) : "memory");
                #endif
            }
        }
    }
    if constexpr (kPdl) {
        asm volatile("griddepcontrol.launch_dependents;" ::: "memory");
    }
}

