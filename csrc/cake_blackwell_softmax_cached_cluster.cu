    for (int offset = 16; offset > 0; offset >>= 1)
        warp_sum += __shfl_xor_sync(0xFFFFFFFF, warp_sum, offset);
    if (lane == 0) {
        table[warp * 2] = warp_max;
        table[warp * 2 + 1] = warp_sum;
    }
    __syncthreads();
    asm volatile("barrier.cluster.wait.acquire.aligned;" ::: "memory");
    if (warp == 0) {
        #pragma unroll
        for (int k = 0; k < 6; k++) {
