    const int num_bids = gridDim.x;
    const unsigned int clusters_x = gridDim.x / 12;
    const unsigned int cluster_id = ((blockIdx.z * gridDim.y + blockIdx.y) * clusters_x) + blockIdx.x / 12;
    const unsigned int num_clusters = clusters_x * gridDim.y * gridDim.z;

