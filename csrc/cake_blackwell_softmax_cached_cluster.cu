            int peer = piece / 4;
            int q = piece % 4;
            unsigned int slot = (unsigned int)(rank * 64 + q * 16);
            uint32_t _cluster_mapa_3;
            asm volatile(
                "mapa.shared::cluster.u32 %0, %1, %2;"
