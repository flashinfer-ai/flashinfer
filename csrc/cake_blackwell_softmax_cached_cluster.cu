    float* table = reinterpret_cast<float*>(smem_raw + 1024);
    const int table_addr = smem + 1024;
    float* cluster_table = reinterpret_cast<float*>(smem_raw + 1088);
    const int cluster_table_addr = smem + 1088;

    // Mbarrier init (1 pipeline groups, 0 ordered-sequence groups, 1 barriers)
    // Mbarriers at smem_raw[0..8)

    if (warp == 0) {
        uint32_t leader = elect_sync();
