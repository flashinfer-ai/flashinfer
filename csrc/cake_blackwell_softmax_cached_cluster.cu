                asm volatile(
                    "ld.global.v4.b32 {%0, %1, %2, %3}, [%4];"
                    : "=r"(_ldv8_0_0), "=r"(_ldv8_0_1), "=r"(_ldv8_0_2), "=r"(_ldv8_0_3) : "l"((const void*)(x + (index))) : "memory");
                asm volatile(
                    "ld.global.v4.b32 {%0, %1, %2, %3}, [%4];"
                    : "=r"(_ldv8_0_4), "=r"(_ldv8_0_5), "=r"(_ldv8_0_6), "=r"(_ldv8_0_7) : "l"((const void*)(x + (index) + 4)) : "memory");
                #endif
                _vec_load_0[0 + 0] = __uint_as_float(_ldv8_0_0);
                _vec_load_0[0 + 1] = __uint_as_float(_ldv8_0_1);
                _vec_load_0[0 + 2] = __uint_as_float(_ldv8_0_2);
                _vec_load_0[0 + 3] = __uint_as_float(_ldv8_0_3);
                _vec_load_0[0 + 4] = __uint_as_float(_ldv8_0_4);
                _vec_load_0[0 + 5] = __uint_as_float(_ldv8_0_5);
                _vec_load_0[0 + 6] = __uint_as_float(_ldv8_0_6);
                _vec_load_0[0 + 7] = __uint_as_float(_ldv8_0_7);
            }
            #pragma unroll
            for (int j = 0; j < 8; j++) {
                cache[tile * 8 + j] = _vec_load_0[j];
            }
        }
    }
    float run_max = -CUDART_INF_F;
    float run_sum = 0.0f;
    #pragma unroll
    for (int tile_1 = 0; tile_1 < 4; tile_1++) {
        int elem_1 = chunk_begin + (tile_1 * 256 + tid) * 8;
        tile_max[tile_1] = -CUDART_INF_F;
        if (elem_1 < chunk_end) {
            float max_here = -CUDART_INF_F;
            #pragma unroll
            for (int j_1 = 0; j_1 < 8; j_1++) {
                float scaled = cache[tile_1 * 8 + j_1] / temperature;
                cache[tile_1 * 8 + j_1] = scaled;
                max_here = max_noftz(max_here, scaled);
            }
            float new_max;
            asm("max.f32 %0, %1, %2;" : "=f"(new_max) : "f"(run_max), "f"(max_here));
            float safe_max = ((new_max == -CUDART_INF_F) ? 0.0f : new_max);
            float _exp2_1 = approx_exp2((run_max - safe_max) * 1.442695f);
            float acc = run_sum * _exp2_1;
            #pragma unroll
            for (int j_2 = 0; j_2 < 8; j_2++) {
                float p = approx_exp2((cache[tile_1 * 8 + j_2] - safe_max) * 1.442695f);
                cache[tile_1 * 8 + j_2] = p;
                acc += p;
            }
            run_sum = acc;
            run_max = new_max;
            tile_max[tile_1] = new_max;
        }
    }
    float warp_max;
    asm volatile("redux.sync.max.f32 %0, %1, 0xffffffff;" : "=f"(warp_max) : "f"(run_max));
    float safe_warp_max = ((warp_max == -CUDART_INF_F) ? 0.0f : warp_max);
    float _exp2_2 = approx_exp2((run_max - safe_warp_max) * 1.442695f);
    float warp_sum = run_sum * _exp2_2;
    #pragma unroll
    for (int offset = 16; offset > 0; offset >>= 1)
        warp_sum += __shfl_xor_sync(0xFFFFFFFF, warp_sum, offset);
    if (lane == 0) {
        table[warp * 2] = warp_max;
        table[warp * 2 + 1] = warp_sum;
    }
    __syncthreads();
    asm volatile("barrier.cluster.wait.acquire.aligned;" ::: "memory");
    if (warp == 0) {
        #pragma unroll
        for (int k = 0; k < 1; k++) {
            int piece = lane + k * 32;
            int peer = piece / 16;
            int q = piece % 16;
            unsigned int slot = (unsigned int)(rank * 64 + q * 4);
            uint32_t _cluster_mapa_3;
            asm volatile(
                "mapa.shared::cluster.u32 %0, %1, %2;"
                : "=r"(_cluster_mapa_3) : "r"(cluster_table_addr + slot), "r"(peer));
            uint32_t _mbar_peer_4;
            asm(
                "mapa.shared::cluster.u32 %0, %1, %2;"
                : "=r"(_mbar_peer_4) : "r"(exchange_addr), "r"(peer));
            asm volatile(
                "st.async.shared::cluster.mbarrier::complete_tx::bytes.f32 [%0], %1, [%2];"
                :: "r"(_cluster_mapa_3), "f"(table[q]), "r"(_mbar_peer_4) : "memory");
        }
    }
    if (tid == 0) {
        mbarrier_arrive(exchange_addr);
    }
    asm volatile("{ .reg .pred P1; WAIT: mbarrier.try_wait.parity.relaxed.cluster.shared::cta.b64 P1, [%0], %1, %2; @P1 bra.uni DONE; bra.uni WAIT; DONE: }" :: "r"(exchange_addr), "r"(uint32_t(0)), "r"(uint32_t(10000000)) : "memory");
