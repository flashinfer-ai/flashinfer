    asm volatile("barrier.cluster.arrive.relaxed.aligned;" ::: "memory");
    int rank = cta_rank;
    int row = bid / 12;
    float temperature = ((parameter_kind == 2) ? parameter[row] : scalar_temperature);
    unsigned long long row_base = (unsigned long long)row * (unsigned long long)vocab_size;
    int chunk_begin = rank * chunk_elements;
    int chunk_end = ((chunk_begin + chunk_elements) < (vocab_size) ? (chunk_begin + chunk_elements) : (vocab_size));
    float cache[80];
    float tile_max[10];
    #pragma unroll
    for (int tile = 0; tile < 10; tile++) {
        int elem = chunk_begin + (tile * 256 + tid) * 8;
        if (elem < chunk_end) {
            unsigned long long index = row_base + (unsigned long long)elem;
            float _vec_load_0[8];
            {
                unsigned _ldv8_0_0;
                unsigned _ldv8_0_1;
                unsigned _ldv8_0_2;
                unsigned _ldv8_0_3;
                unsigned _ldv8_0_4;
                unsigned _ldv8_0_5;
                unsigned _ldv8_0_6;
                unsigned _ldv8_0_7;
