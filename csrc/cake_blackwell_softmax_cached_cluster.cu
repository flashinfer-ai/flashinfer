template <bool kPdl>
__device__ __forceinline__ void flashinfer_blackwell_softmax_cached_cluster_c16_t8_body(float* __restrict__ x, float* __restrict__ parameter, float* __restrict__ output, int rows, int vocab_size, int chunk_elements, int parameter_kind, float scalar_temperature)
