  DLDevice dev = arg_Q.device();
  tvm::ffi::CUDADeviceGuard device_guard(dev.device_id);
  {
    // The encoders need a current context on this thread: bind the primary context once per thread per device.
    static thread_local uint64_t bound_devices = 0;
    const uint64_t device_bit = dev.device_id < 64 ? uint64_t{1} << dev.device_id : uint64_t{0};
    if (device_bit == 0 || (bound_devices & device_bit) == 0) {
      TVM_FFI_CHECK_CUDA_ERROR(cudaSetDevice(dev.device_id));  // binds the context for the encoders
      bound_devices |= device_bit;
    }
  }
  check_cuda_tensor(arg_Q, "Q");
  check_dtype(arg_Q, DLDataType{kDLBfloat, 16, 1}, "Q");
  check_contiguous(arg_Q, "Q");
  check_cuda_tensor(arg_K, "K");
  check_dtype(arg_K, DLDataType{kDLBfloat, 16, 1}, "K");
  check_contiguous(arg_K, "K");
  check_cuda_tensor(arg_V, "V");
  check_dtype(arg_V, DLDataType{kDLBfloat, 16, 1}, "V");
  check_contiguous(arg_V, "V");
  check_cuda_tensor(arg_T, "T");
  check_dtype(arg_T, DLDataType{kDLBfloat, 16, 1}, "T");
  check_contiguous(arg_T, "T");
  check_cuda_tensor(arg_O, "O");
  check_dtype(arg_O, DLDataType{kDLBfloat, 16, 1}, "O");
  check_contiguous(arg_O, "O");
  check_cuda_tensor(arg_alpha, "alpha");
  check_dtype(arg_alpha, DLDataType{kDLFloat, 32, 1}, "alpha");
  check_contiguous(arg_alpha, "alpha");
  check_cuda_tensor(arg_cu_seqlens, "cu_seqlens");
  check_dtype(arg_cu_seqlens, DLDataType{kDLInt, 64, 1}, "cu_seqlens");
  check_contiguous(arg_cu_seqlens, "cu_seqlens");
  check_cuda_tensor(arg_fixed_state, "fixed_state");
  check_dtype(arg_fixed_state, DLDataType{kDLFloat, 32, 1}, "fixed_state");
  check_contiguous(arg_fixed_state, "fixed_state");
  check_cuda_tensor(arg_initial_state_workspace, "initial_state_workspace");
  check_dtype(arg_initial_state_workspace, DLDataType{kDLFloat, 32, 1}, "initial_state_workspace");
  check_contiguous(arg_initial_state_workspace, "initial_state_workspace");
  check_cuda_tensor(arg_tensormap_workspace, "tensormap_workspace");
  check_dtype(arg_tensormap_workspace, DLDataType{kDLUInt, 8, 1}, "tensormap_workspace");
  check_contiguous(arg_tensormap_workspace, "tensormap_workspace");
  TVM_FFI_CHECK(arg_cp_chunk_len >= -2147483648LL && arg_cp_chunk_len <= 2147483647LL, ValueError)
      << "scalar 'cp_chunk_len' value " << arg_cp_chunk_len
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_source_cp_chunk_len >= -2147483648LL && arg_source_cp_chunk_len <= 2147483647LL, ValueError)
      << "scalar 'source_cp_chunk_len' value " << arg_source_cp_chunk_len
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_num_q_heads >= -2147483648LL && arg_num_q_heads <= 2147483647LL, ValueError)
      << "scalar 'num_q_heads' value " << arg_num_q_heads
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_num_k_heads >= -2147483648LL && arg_num_k_heads <= 2147483647LL, ValueError)
      << "scalar 'num_k_heads' value " << arg_num_k_heads
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_num_v_heads >= -2147483648LL && arg_num_v_heads <= 2147483647LL, ValueError)
      << "scalar 'num_v_heads' value " << arg_num_v_heads
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_num_sab_heads >= -2147483648LL && arg_num_sab_heads <= 2147483647LL, ValueError)
      << "scalar 'num_sab_heads' value " << arg_num_sab_heads
      << " is outside i32 range [-2147483648, 2147483647]";
  TVM_FFI_CHECK(arg_cp_chunk_len >= 1LL && arg_cp_chunk_len <= 2147483647LL, ValueError)
      << "scalar 'cp_chunk_len' value " << arg_cp_chunk_len
      << " must be in [1, 2147483647] (fast-divmod divisor of 'cp_chunk_len_fdd')";
  TVM_FFI_CHECK(arg_num_sab_heads >= 1LL && arg_num_sab_heads <= 2147483647LL, ValueError)
      << "scalar 'num_sab_heads' value " << arg_num_sab_heads
      << " must be in [1, 2147483647] (fast-divmod divisor of 'num_sab_heads_fdd')";
