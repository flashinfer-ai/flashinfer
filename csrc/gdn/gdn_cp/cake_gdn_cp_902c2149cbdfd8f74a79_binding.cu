  CakeFastDivmod v_num_sab_heads_fdd = CakeFastDivmodFromDivisor((int32_t)arg_num_sab_heads);
  void* kargs[] = {&p_Q, &p_K, &p_V, &p_T, &p_O, &p_alpha, &p_cu_seqlens, &p_fixed_state, &p_initial_state_workspace, &p_tensormap_workspace, &v_cp_chunk_len, &v_source_cp_chunk_len, &v_num_q_heads, &v_num_k_heads, &v_num_v_heads, &v_num_sab_heads, &v_cp_chunk_len_fdd, &v_num_sab_heads_fdd, &v_scale};

  static const bool smem_ready = CakeSetMaxDynamicSmem(
      reinterpret_cast<const void*>(kernel_cake_gdn_cp_902c2149cbdfd8f74a79), 224768);
  (void)smem_ready;
  dim3 grid((uint32_t)grid_x, (uint32_t)grid_y, (uint32_t)grid_z);
  dim3 block(384u, 1u, 1u);

  cudaError_t launch_status = cudaLaunchKernel(
      reinterpret_cast<const void*>(kernel_cake_gdn_cp_902c2149cbdfd8f74a79), grid, block, kargs, 224768u, stream);
  TVM_FFI_CHECK(launch_status == cudaSuccess, RuntimeError)
      << "cudaLaunchKernel for kernel_cake_gdn_cp_902c2149cbdfd8f74a79 failed: "
      << cudaGetErrorString(launch_status);
}

