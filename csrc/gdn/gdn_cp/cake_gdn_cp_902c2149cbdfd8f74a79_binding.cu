  float* p_alpha = static_cast<float*>(arg_alpha.data_ptr());
  long long* p_cu_seqlens = static_cast<long long*>(arg_cu_seqlens.data_ptr());
  float* p_fixed_state = static_cast<float*>(arg_fixed_state.data_ptr());
  float* p_initial_state_workspace = static_cast<float*>(arg_initial_state_workspace.data_ptr());
  uint8_t* p_tensormap_workspace = static_cast<uint8_t*>(arg_tensormap_workspace.data_ptr());
  int32_t v_cp_chunk_len = (int32_t)arg_cp_chunk_len;
  int32_t v_source_cp_chunk_len = (int32_t)arg_source_cp_chunk_len;
  int32_t v_num_q_heads = (int32_t)arg_num_q_heads;
  int32_t v_num_k_heads = (int32_t)arg_num_k_heads;
  int32_t v_num_v_heads = (int32_t)arg_num_v_heads;
  int32_t v_num_sab_heads = (int32_t)arg_num_sab_heads;
