    const unsigned int f64c_xb = __float_as_uint(f64c_x);
    const unsigned int f64c_xe = (f64c_xb >> 23) & 0xFFu;
    const unsigned int f64c_sign = (f64c_xb ^ (unsigned int)(f64c_cb >> 32)) & 0x80000000u;
