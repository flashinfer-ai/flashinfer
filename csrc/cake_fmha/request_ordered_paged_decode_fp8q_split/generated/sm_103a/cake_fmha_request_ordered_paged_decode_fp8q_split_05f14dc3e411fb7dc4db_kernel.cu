extern "C" {

__global__ __launch_bounds__(32) void
kernel_cake_fmha_request_ordered_paged_decode_fp8q_split_05f14dc3e411fb7dc4db(float* __restrict__ partial_O, float* __restrict__ partial_max, float* __restrict__ partial_sum, __nv_bfloat16* __restrict__ O, float* __restrict__ LSE, float* __restrict__ bmm2_scale_ptr)
{
    const int tid = threadIdx.x;
    const uint32_t warp = __shfl_sync(0xffffffff, threadIdx.x / 32, 0);
    uint32_t lane;
    asm("mov.u32 %0, %%laneid;" : "=r"(lane));


    const int bid = blockIdx.x;
    const int num_bids = gridDim.x;

    // === Task calls (dependency order) ===
    int row = blockIdx.x;
    int stat_base = row * NUM_SPLITS;
    float max_m = -CAKE_INF;
    #pragma unroll
    for (int split = 0; split < NUM_SPLITS; split++) {
        float _max_0 = max_noftz(max_m, partial_max[stat_base + split]);
        max_m = _max_0;
    }
    float total = 0.0f;
    float acc[8];
    #pragma unroll
    for (int d = 0; d < 8; d++) {
        acc[d] = 0.0f;
    }
    #pragma unroll
    for (int split_1 = 0; split_1 < NUM_SPLITS; split_1++) {
        float maximum = partial_max[stat_base + split_1];
        if (maximum != -CAKE_INF) {
            float _exp2_0 = approx_exp2(maximum - max_m);
