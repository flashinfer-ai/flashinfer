// The merge is the programmatic dependent of the decode grid: launched with the Programmatic Dependent Launch
// attribute its CTAs are scheduled while the decode grid drains (the decode signals `griddepcontrol.launch_dependents`
// at its entry, the merge waits on `griddepcontrol.wait` before its first global load); without the attribute the
// wait is a no-op and the merge simply follows the decode in stream order.
cudaError_t launch(const MergeArgs& a, dim3 grid, bool enable_pdl, cudaStream_t stream) {
  cudaLaunchConfig_t config{};
  config.gridDim = grid;
  config.blockDim = dim3(64, 1, 1);
  config.dynamicSmemBytes = 0;
  config.stream = stream;
  cudaLaunchAttribute attribute[1];
  attribute[0].id = cudaLaunchAttributeProgrammaticStreamSerialization;
  attribute[0].val.programmaticStreamSerializationAllowed = enable_pdl ? 1 : 0;
  config.attrs = attribute;
  config.numAttrs = 1;
  return cudaLaunchKernelEx(&config, kernel_sm120_dsv41_mixed_sparse_mla_merge_h8_mo2, a.mid_out, a.mid_lse, a.attn_sink, a.output, a.out_lse, a.num_splits, a.scratch_split_stride, a.lse_scale, a.hb_major);
}

