// Fused writer for the target model's sliding-window pool: rotates the live heads of q into q_out (BF16 copy when
// apply_q_rope is false; padded heads zero), then rotates, quantizes and inserts kv by physical slot.  Passing q
// itself as q_out (same data pointer) selects the in-place form: only the 64 rope dims of each head are read and
// rewritten (heads must equal q_head_padded and apply_q_rope must be true).
//   q [tokens, heads, 512] BF16 (heads >= 1); q_out [tokens, q_head_padded, 512] BF16, caller-allocated,
//   q_head_padded in {8, 16, 32, 64, 128} and >= heads, fully written; kv [tokens, 512] BF16.
//   cache: uint8 3-D / HND / NHD view of the paged NVFP4 pool (384-byte records, padded page strides allowed).
//   slot_mapping [tokens_insert <= tokens] int32 | int64 (negative / out-of-range = skip); positions [tokens]
//   int64; cos_sin_cache [max_position, 64] fp32.  tokens == 0 launches nothing.
void cake_dsv4_nvfp4_rope_insert_qkv(TensorView q, TensorView q_out, TensorView kv, TensorView cache, TensorView slot_mapping,
                 TensorView positions, TensorView cos_sin_cache, bool apply_q_rope) {
  TVM_FFI_CHECK(kv.ndim() == 2, ValueError) << "kv must be [tokens, " << kHeadDim << "]";
  const int64_t tokens = kv.size(0);
  TVM_FFI_CHECK(tokens <= kMaxInt32, ValueError) << "num_tokens does not fit the kernel's int";
  const DLDevice device = kv.device();
  TVM_FFI_CHECK(device.device_type == kDLCUDA, ValueError) << "kv must be a CUDA tensor";
  CheckKv(kv, tokens, device);
  TVM_FFI_CHECK(q.ndim() == 3 && q.size(1) >= 1, ValueError)
      << "q must be [tokens, heads, " << kHeadDim << "] with at least one head";
  const int64_t heads = q.size(1);
  CheckQ(q, "q", tokens, heads, device);
  TVM_FFI_CHECK(q_out.ndim() == 3, ValueError) << "q_out must be [tokens, q_head_padded, " << kHeadDim << "]";
  const int64_t q_head_padded = q_out.size(1);
  TVM_FFI_CHECK(is_q_head_padded_choice(q_head_padded), ValueError)
      << "q_out must hold 8, 16, 32, 64 or 128 padded heads, got " << q_head_padded;
  TVM_FFI_CHECK(q_head_padded >= heads, ValueError)
      << "q_out holds " << q_head_padded << " padded heads, fewer than the " << heads << " query heads";
  CheckQ(q_out, "q_out", tokens, q_head_padded, device);
  const bool q_inplace = q.data_ptr() == q_out.data_ptr();
  if (q_inplace) {
    TVM_FFI_CHECK(q_head_padded == heads, ValueError)
        << "in-place q (q_out is q) needs heads == q_head_padded, got " << heads << " vs " << q_head_padded;
    TVM_FFI_CHECK(apply_q_rope, ValueError) << "in-place q without apply_q_rope is a no-op: use the kv entry";
  }
  const CacheGeometry geometry = ResolveCache(cache, device);
  const SlotMapping slots = ResolveSlots(slot_mapping, tokens, device);
  CheckPositions(positions, tokens, device);
  CheckCosSin(cos_sin_cache, device);
  if (tokens == 0) return;

  ffi::CUDADeviceGuard device_guard(device.device_id);
  const cudaStream_t stream = get_stream(device);
  CheckDeviceOnce(device.device_id);
  const KernelArgs args = MakeArgs(&q, kv, cache, slots, positions, cos_sin_cache, &q_out, tokens, heads, geometry);
  const cudaError_t status =
      launch_qkv(args, static_cast<int>(q_head_padded), apply_q_rope, slots.int64, q_inplace,
                 Grid(tokens, q_inplace ? q_head_padded / kQHeadsPerInplaceWarp : q_head_padded + 1), stream);
  TVM_FFI_CHECK(status == cudaSuccess, RuntimeError)
      << "Cake SM120 DSV4 NVFP4 RoPE-insert (qkv) launch failed: " << cudaGetErrorString(status);
}

// KV-only writer for the compressed pool and speculative-decoding context inserts: row i is inserted when
