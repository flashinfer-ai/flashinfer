  const int64_t warps = tokens * slots_per_token;
  const int64_t blocks = (warps + kWarpsPerCta - 1) / kWarpsPerCta;
  TVM_FFI_CHECK(blocks >= 1 && blocks <= kMaxGridX, ValueError)
      << "num_tokens " << tokens << " x " << slots_per_token << " warps exceeds the launch grid";
  return dim3(static_cast<unsigned>(blocks), 1, 1);
