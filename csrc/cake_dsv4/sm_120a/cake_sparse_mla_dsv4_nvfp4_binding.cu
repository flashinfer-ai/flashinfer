// of 64 (topk + extra_topk <= 1024 slots) -- longer lists take the split decode.
//   head_tiles: 16 * head_tiles heads per CTA (1 always; 2 for heads % 32 == 0; 4 for heads % 64 == 0).
//   The grid is (tokens, head blocks): one CTA per (token, head block) item.
void cake_sparse_mla_sm120_dsv4_nvfp4_prefill(TensorView q, TensorView kv_cache, TensorView indices, Optional<TensorView> extra_kv_cache,
             Optional<TensorView> extra_indices, Optional<TensorView> topk_length,
             Optional<TensorView> extra_topk_length, Optional<TensorView> attn_sink, TensorView output,
             TensorView out_lse, int64_t page_size, int64_t page_stride_bytes, int64_t extra_page_size,
             int64_t extra_page_stride_bytes, int64_t head_tiles, double sm_scale, double lse_scale) {
  const Common c = ResolveCommon(q, kv_cache, indices, extra_kv_cache, extra_indices, topk_length, extra_topk_length,
                                 attn_sink, output, out_lse, page_size, page_stride_bytes, extra_page_size,
                                 extra_page_stride_bytes);
  const HeadEntry* entry = c.entry;
  TVM_FFI_CHECK(entry->prefill_tiles != 0, ValueError)
      << "Cake SM120 DSV4 NVFP4 sparse MLA has no prefill instance for " << c.heads << " query heads";
  TVM_FFI_CHECK(c.chunks <= kMaxChunksPerBlock, ValueError)
      << "the prefill kernel holds at most " << kMaxChunksPerBlock << " chunks of " << kCandidatesPerChunk
      << " candidates per token (" << c.chunks << " requested); use the split decode for longer candidate lists";
  TVM_FFI_CHECK((head_tiles == 1 || head_tiles == 2 || head_tiles == 4) && (entry->prefill_tiles & head_tiles) &&
                    c.heads % (kHeadsPerBlock * head_tiles) == 0,
                ValueError)
      << "head_tiles=" << head_tiles << " is not valid for the " << c.heads << "-head prefill";
  if (c.tokens == 0) return;

  ffi::CUDADeviceGuard device_guard(c.device.device_id);
  const cudaStream_t stream = get_stream(c.device);
  ConfigureOnce(c.device.device_id, *entry);

  PrefillArgs args{};
  FillCommonArgs(args, c, q, kv_cache, indices, extra_kv_cache, extra_indices, output, out_lse, page_size,
                 page_stride_bytes, extra_page_size, extra_page_stride_bytes, sm_scale, lse_scale);
  args.num_tokens = static_cast<int>(c.tokens);
  const int64_t head_blocks = c.heads / (kHeadsPerBlock * head_tiles);
  const dim3 grid(static_cast<unsigned>(c.tokens), static_cast<unsigned>(head_blocks), 1);
  const cudaError_t status = entry->launch_prefill(args, c.dual, static_cast<int>(head_tiles), grid, stream);
  TVM_FFI_CHECK(status == cudaSuccess, RuntimeError)
      << "Cake SM120 DSV4 NVFP4 sparse MLA prefill launch failed: " << cudaGetErrorString(status);
}

