// Cake SM120 DeepSeek-V4 NVFP4 sparse-MLA decode: ``output[t, h] = softmax(q[t, h] K^T * sm_scale) V`` over
// the ``topk`` (+ ``extra_topk``) latent rows selected by ``indices`` (and ``extra_indices``) in the NVFP4
// paged caches, with ``out_lse`` the base-2 log-sum-exp times ``lse_scale``.
//   q [tokens, heads, 512] BF16; output [tokens, heads, 512] BF16; out_lse [tokens, heads] fp32.
//   kv_cache / extra_kv_cache: flat uint8 views of the pools; page_size / page_stride_bytes describe the
//   page geometry (rows of 352 data bytes followed by the page's 32-byte scale rows).
//   indices / extra_indices [tokens, topk] int32 (-1 masks a slot); topk_length / extra_topk_length
//   [tokens] int32 clamp the valid prefix; attn_sink [heads] fp32.
//   num_splits > 1 splits the chunks_per_block * 64-candidate windows over gridDim.z CTAs that write
//   mid_out [tokens, heads, >= num_splits, 512] BF16 / mid_lse [tokens, heads, >= num_splits] fp32 and
//   a merge launch combines them; num_splits == 1 writes the output directly (scratch unused).
//   head_tiles: 1 = 16 heads per decode CTA, 2 = 32 heads per CTA sharing one gather (heads % 32 == 0).
void cake_sparse_mla_sm120_dsv4_nvfp4_decode(TensorView q, TensorView kv_cache, TensorView indices, Optional<TensorView> extra_kv_cache,
             Optional<TensorView> extra_indices, Optional<TensorView> topk_length,
             Optional<TensorView> extra_topk_length, Optional<TensorView> attn_sink, TensorView output,
             TensorView out_lse, Optional<TensorView> mid_out, Optional<TensorView> mid_lse, int64_t page_size,
             int64_t page_stride_bytes, int64_t extra_page_size, int64_t extra_page_stride_bytes,
             int64_t num_splits, int64_t chunks_per_block, int64_t head_tiles, double sm_scale,
             double lse_scale) {
  const Common c = ResolveCommon(q, kv_cache, indices, extra_kv_cache, extra_indices, topk_length, extra_topk_length,
                                 attn_sink, output, out_lse, page_size, page_stride_bytes, extra_page_size,
                                 extra_page_stride_bytes);
  const HeadEntry* entry = c.entry;
  const int64_t tokens = c.tokens;
  const int64_t heads = c.heads;
  const DLDevice device = c.device;
  TVM_FFI_CHECK(chunks_per_block >= 1 && chunks_per_block <= kMaxChunksPerBlock, ValueError)
      << "chunks_per_block must be in [1, " << kMaxChunksPerBlock << "], got " << chunks_per_block;
  TVM_FFI_CHECK(num_splits == (c.chunks + chunks_per_block - 1) / chunks_per_block, ValueError)
      << "num_splits " << num_splits << " does not match ceil(" << c.chunks << " chunks / " << chunks_per_block
      << " chunks per block)";
  TVM_FFI_CHECK(head_tiles == 1 || (head_tiles == 2 && entry->two_tiles && heads % (2 * kHeadsPerBlock) == 0),
                ValueError)
      << "head_tiles=" << head_tiles << " is not valid for " << heads << " heads";

  int64_t scratch_split_stride = 1;
  __nv_bfloat16* mid_out_ptr = static_cast<__nv_bfloat16*>(output.data_ptr());
  float* mid_lse_ptr = static_cast<float*>(out_lse.data_ptr());
  if (num_splits > 1) {
    TVM_FFI_CHECK(mid_out.has_value() && mid_lse.has_value(), ValueError)
        << "num_splits > 1 requires caller-owned mid_out / mid_lse scratch";
    const TensorView& mo = mid_out.value();
    const TensorView& ml = mid_lse.value();
    CheckDevice(mo, "mid_out", device, 16);
    CheckDtype(mo, "mid_out", dl_bfloat16, "bfloat16");
    TVM_FFI_CHECK(mo.ndim() == 4 && mo.size(0) == tokens && mo.size(1) == heads && mo.size(2) >= num_splits &&
                      mo.size(3) == kValueDim && mo.IsContiguous(),
                  ValueError)
        << "mid_out must be a contiguous [" << tokens << ", " << heads << ", >= " << num_splits << ", " << kValueDim
        << "] bfloat16 tensor";
    CheckDevice(ml, "mid_lse", device, 4);
    CheckDtype(ml, "mid_lse", dl_float32, "float32");
    TVM_FFI_CHECK(ml.ndim() == 3 && ml.size(0) == tokens && ml.size(1) == heads && ml.size(2) == mo.size(2) &&
                      ml.IsContiguous(),
                  ValueError)
        << "mid_lse must be a contiguous [" << tokens << ", " << heads << ", " << mo.size(2) << "] float32 tensor";
    scratch_split_stride = mo.size(2);
    mid_out_ptr = static_cast<__nv_bfloat16*>(mo.data_ptr());
    mid_lse_ptr = static_cast<float*>(ml.data_ptr());
  }
  if (tokens == 0) return;

  ffi::CUDADeviceGuard device_guard(device.device_id);
  const cudaStream_t stream = get_stream(device);
  ConfigureOnce(device.device_id, *entry);

  DecodeArgs args{};
  FillCommonArgs(args, c, q, kv_cache, indices, extra_kv_cache, extra_indices, output, out_lse, page_size,
                 page_stride_bytes, extra_page_size, extra_page_stride_bytes, sm_scale, lse_scale);
  args.mid_out = mid_out_ptr;
  args.mid_lse = mid_lse_ptr;
  args.scratch_split_stride = static_cast<int>(scratch_split_stride);
  args.chunks_per_block = static_cast<int>(chunks_per_block);
  args.write_direct = num_splits == 1 ? 1 : 0;
  const int64_t cta_heads = kHeadsPerBlock * head_tiles;
  const unsigned head_blocks = static_cast<unsigned>((heads + kHeadsPerBlock - 1) / kHeadsPerBlock);
  const unsigned decode_blocks = static_cast<unsigned>((heads + cta_heads - 1) / cta_heads);
  const dim3 decode_grid(static_cast<unsigned>(tokens), decode_blocks, static_cast<unsigned>(num_splits));
  cudaError_t status = entry->launch_decode(args, c.dual, static_cast<int>(head_tiles), decode_grid, stream);
  TVM_FFI_CHECK(status == cudaSuccess, RuntimeError)
      << "Cake SM120 DSV4 NVFP4 sparse MLA decode launch failed: " << cudaGetErrorString(status);
  if (num_splits > 1) {
    MergeArgs merge{};
    merge.mid_out = mid_out_ptr;
    merge.mid_lse = mid_lse_ptr;
    merge.attn_sink = const_cast<float*>(c.sink);
    merge.output = args.output;
    merge.out_lse = args.out_lse;
    merge.num_splits = static_cast<int>(num_splits);
    merge.scratch_split_stride = static_cast<int>(scratch_split_stride);
    merge.lse_scale = static_cast<float>(lse_scale);
    const dim3 merge_grid(static_cast<unsigned>(tokens), head_blocks, 1);
    status = entry->launch_merge(merge, merge_grid, stream);
    TVM_FFI_CHECK(status == cudaSuccess, RuntimeError)
        << "Cake SM120 DSV4 NVFP4 sparse MLA merge launch failed: " << cudaGetErrorString(status);
  }
}

