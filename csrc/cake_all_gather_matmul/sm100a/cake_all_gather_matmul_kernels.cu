                        }
                        if (elect_sync()) {
                            mbarrier_arrive(epilogue_done_addr + (epi_stage) * 8);
                        }
                        epi_stage += 1;
                        if (epi_stage == 2) { epi_stage = 0; _phase_mainloop_done ^= 1; }
