                            mma_tma_stage += 1;
                            if (mma_tma_stage == 4) { mma_tma_stage = 0; _phase_tma_full ^= 1; }
                        }
                        elect_commit(mainloop_done_addr + (mma_epi_stage) * 8);
                        mma_epi_stage += 1;
                        if (mma_epi_stage == 2) { mma_epi_stage = 0; _phase_epilogue_done ^= 1; }
                    }
                }
            }
        }
    }
    // ---- Role: epilogue ----
    if (warp >= 2 && warp <= 5) {
        { // epilogue_main
            unsigned int epi_stage = 0;
            const int epi_warp = warp % 4;
            const int epi_tid = epi_warp * 32 + lane;
            unsigned int _phase_mainloop_done = 0;
            #pragma unroll 1
            for (int peer_pass_1 = 0; peer_pass_1 < 2; peer_pass_1++) {
                int peer_1 = (rank - peer_pass_1 + 2) % 2;
                #pragma unroll 1
                for (int chunk_idx_2 = 0; chunk_idx_2 < (M + ((M < 2432) ? M : 2432) - 1) / ((M < 2432) ? M : 2432); chunk_idx_2++) {
