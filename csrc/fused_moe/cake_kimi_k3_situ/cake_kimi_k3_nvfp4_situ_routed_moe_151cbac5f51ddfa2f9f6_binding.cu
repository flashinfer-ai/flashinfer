// Route submission. The submitter binds the device context, resolves the
// stream and checks every stage's device once per call, then calls
// PrepareStage for every stage before SubmitStage for each in order; both
// return the tvm-ffi status of their phase (0, or -1 with the error set).
thread_local stage::PreparedLaunch route_prepared;

int PrepareStage(const TVMFFIAny* raw_args, int32_t num_args, void* stream) {
  TVM_FFI_SAFE_CALL_BEGIN();
  const tvm::ffi::AnyView* args = reinterpret_cast<const tvm::ffi::AnyView*>(raw_args);
  TVM_FFI_CHECK(num_args == 18, TypeError)
      << "prepared stage expects 18 arguments, got " << num_args;
  stage::Prepare(route_prepared, args[0].cast<TensorView>(), args[1].cast<TensorView>(), args[2].cast<TensorView>(), args[3].cast<TensorView>(), args[4].cast<TensorView>(), args[5].cast<TensorView>(), args[6].cast<TensorView>(), args[7].cast<TensorView>(), args[8].cast<TensorView>(), args[9].cast<int64_t>(), args[10].cast<int64_t>(), args[11].cast<int64_t>(), args[12].cast<int64_t>(), args[13].cast<int64_t>(), args[14].cast<TensorView>(), args[15].cast<int64_t>(), args[16].cast<int64_t>(), args[17].cast<int64_t>(), static_cast<cudaStream_t>(stream));
  TVM_FFI_SAFE_CALL_END();
}

int SubmitStage(void* stream) {
  TVM_FFI_SAFE_CALL_BEGIN();
  stage::Submit(route_prepared, static_cast<cudaStream_t>(stream));
  route_prepared.retained.clear();
  TVM_FFI_SAFE_CALL_END();
}

